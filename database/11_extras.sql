CREATE OR REPLACE PACKAGE BODY wallet_account_pkg AS
  c_max_attempts CONSTANT PLS_INTEGER := 5;

  PROCEDURE fail (p_msg VARCHAR2) IS BEGIN RAISE_APPLICATION_ERROR(c_err, p_msg); END;

  FUNCTION admin_id (p_phone VARCHAR2) RETURN NUMBER IS
    l NUMBER;
  BEGIN
    SELECT user_id INTO l FROM wlt_users WHERE phone = p_phone AND user_type = 'ADMIN' AND status = 'ACTIVE';
    RETURN l;
  EXCEPTION WHEN NO_DATA_FOUND THEN fail('للإدارة فقط'); RETURN NULL;
  END admin_id;

  -- نفس سياسة شاشة الدخول: 5 محاولات خاطئة تقفل الحساب 15 دقيقة
  PROCEDURE change_pin (p_phone VARCHAR2, p_old VARCHAR2, p_new VARCHAR2) IS
    u      wlt_users%ROWTYPE;
    l_salt VARCHAR2(16) := DBMS_RANDOM.STRING('X', 16);
    l_left NUMBER;
  BEGIN
    SELECT * INTO u FROM wlt_users WHERE phone = p_phone FOR UPDATE;
    IF u.locked_until > SYSTIMESTAMP THEN fail('محاولات كثيرة. حاول بعد ربع ساعة'); END IF;
    IF wallet_otp_pkg.sha(u.pin_salt || p_old) <> u.pin_hash THEN
      l_left := c_max_attempts - (u.failed_pin_attempts + 1);
      UPDATE wlt_users
         SET failed_pin_attempts = CASE WHEN l_left <= 0 THEN 0 ELSE failed_pin_attempts + 1 END,
             locked_until = CASE WHEN l_left <= 0 THEN SYSTIMESTAMP + INTERVAL '15' MINUTE END
       WHERE user_id = u.user_id;
      COMMIT;
      fail(CASE WHEN l_left <= 0 THEN 'محاولات كثيرة. قُفل الحساب 15 دقيقة' ELSE 'الرمز الحالي غير صحيح. بقيت ' || l_left || ' محاولات' END);
    END IF;
    wallet_otp_pkg.check_pin(p_new);
    IF p_new = p_old THEN fail('الرمز الجديد يجب أن يختلف عن الحالي'); END IF;
    UPDATE wlt_users SET pin_salt = l_salt, pin_hash = wallet_otp_pkg.sha(l_salt || p_new), failed_pin_attempts = 0
     WHERE user_id = u.user_id;
    INSERT INTO wlt_audit_log (actor_user_id, action, entity, entity_id, details)
    VALUES (u.user_id, 'PIN_CHANGE', 'USER', u.user_id, 'من صفحة حسابي');
    wallet_social_pkg.notify(u.user_id, 'SECURITY', '🔐 تمّ تغيير رمزك السري', 'إذا لم تكن أنت، تواصل مع الدعم فوراً.', 24);
    COMMIT;
  END change_pin;

  PROCEDURE set_name (p_phone VARCHAR2, p_name VARCHAR2) IS
    l_name VARCHAR2(60) := SUBSTR(TRIM(REGEXP_REPLACE(p_name, '[<>"]', '')), 1, 60);
  BEGIN
    IF l_name IS NULL OR LENGTH(l_name) < 2 THEN fail('اكتب اسماً من حرفين على الأقل'); END IF;
    UPDATE wlt_users SET display_name = l_name WHERE phone = p_phone AND user_type <> 'SYSTEM';
    COMMIT;
  END set_name;

  PROCEDURE request_tier (p_phone VARCHAR2, p_tier VARCHAR2, p_note VARCHAR2) IS
    u    wlt_users%ROWTYPE;
    l_ok NUMBER;
  BEGIN
    SELECT * INTO u FROM wlt_users WHERE phone = p_phone;
    IF wallet_family_pkg.is_child(u.user_id) THEN fail('محافظ الأبناء يرقّيها ولي الأمر'); END IF;
    SELECT COUNT(*) INTO l_ok FROM wlt_kyc_tiers t1, wlt_kyc_tiers t2
     WHERE t1.tier_code = u.kyc_tier AND t2.tier_code = p_tier AND t2.daily_limit > t1.daily_limit;
    IF l_ok = 0 THEN fail('اختر مستوى أعلى من مستواك الحالي'); END IF;
    INSERT INTO wlt_kyc_requests (user_id, from_tier, to_tier, note)
    VALUES (u.user_id, u.kyc_tier, p_tier, SUBSTR(REGEXP_REPLACE(p_note, '[<>"]', ''), 1, 300));
    COMMIT;
  EXCEPTION WHEN DUP_VAL_ON_INDEX THEN ROLLBACK; fail('لديك طلب قيد المراجعة');
  END request_tier;

  PROCEDURE decide_tier (p_admin_phone VARCHAR2, p_req_id NUMBER, p_approve VARCHAR2) IS
    l_a NUMBER := admin_id(p_admin_phone);
    r   wlt_kyc_requests%ROWTYPE;
  BEGIN
    SELECT * INTO r FROM wlt_kyc_requests WHERE req_id = p_req_id FOR UPDATE;
    IF r.status <> 'PENDING' THEN fail('الطلب مغلق مسبقاً'); END IF;
    UPDATE wlt_kyc_requests SET status = CASE WHEN p_approve = 'Y' THEN 'APPROVED' ELSE 'REJECTED' END,
           decided_by = l_a, decided_at = SYSTIMESTAMP
     WHERE req_id = r.req_id;
    IF p_approve = 'Y' THEN
      UPDATE wlt_users SET kyc_tier = r.to_tier WHERE user_id = r.user_id;
      wallet_social_pkg.notify(r.user_id, 'SECURITY', '⭐ تمّت ترقية حسابك إلى ' || r.to_tier, 'حدود أعلى للتحويل والرصيد', 24);
    ELSE
      wallet_social_pkg.notify(r.user_id, 'SECURITY', 'لم تُقبل ترقية الحساب حالياً', 'يمكنك التقديم مجدداً لاحقاً', 24);
    END IF;
    INSERT INTO wlt_audit_log (actor_user_id, action, entity, entity_id, details)
    VALUES (l_a, 'KYC_' || CASE WHEN p_approve = 'Y' THEN 'APPROVE' ELSE 'REJECT' END, 'USER', r.user_id, r.from_tier || '->' || r.to_tier);
    COMMIT;
  END decide_tier;

  -- العكس متاح فقط للعمليات التي لا ترتبط بحالة في جداول أخرى (جمعية، ضمان، تقسيط، حصّالة…)
  FUNCTION reversible (p_txn_type VARCHAR2) RETURN VARCHAR2 IS
  BEGIN
    RETURN CASE WHEN p_txn_type IN ('TRANSFER','MERCHANT_PAY','TOPUP','CASH_IN','RECHARGE') THEN 'Y' ELSE 'N' END;
  END reversible;

  FUNCTION admin_reverse (p_admin_phone VARCHAR2, p_ref VARCHAR2, p_reason VARCHAR2) RETURN VARCHAR2 IS
    l_a   NUMBER := admin_id(p_admin_phone);
    t     wlt_transactions%ROWTYPE;
    l_av  NUMBER;
    l_ref VARCHAR2(20);
    l_fu  NUMBER;
    l_neg VARCHAR2(1);
  BEGIN
    IF TRIM(p_reason) IS NULL THEN fail('اكتب سبب العكس'); END IF;
    BEGIN
      SELECT * INTO t FROM wlt_transactions WHERE txn_ref = UPPER(TRIM(p_ref));
    EXCEPTION WHEN NO_DATA_FOUND THEN fail('لا توجد عملية بهذا المرجع');
    END;
    IF reversible(t.txn_type) = 'N' THEN fail('هذا النوع من العمليات لا يُعكس من هنا'); END IF;
    IF t.status <> 'COMPLETED' THEN fail('العملية ليست مكتملة أو معكوسة مسبقاً'); END IF;
    SELECT balance - held_amount, allow_negative INTO l_av, l_neg FROM wlt_wallets WHERE wallet_id = t.to_wallet_id;
    IF l_av < t.amount AND l_neg <> 'Y' THEN
      fail('رصيد المستلم الحالي (' || TO_CHAR(l_av, 'FM999G990D000') || ') لا يكفي للعكس');
    END IF;
    l_ref := wallet_core_pkg.reverse(t.txn_ref, SUBSTR(p_reason, 1, 150));
    SELECT user_id INTO l_fu FROM wlt_wallets WHERE wallet_id = t.from_wallet_id;
    INSERT INTO wlt_audit_log (actor_user_id, action, entity, entity_id, details)
    VALUES (l_a, 'ADMIN_REVERSE', 'TRANSACTION', t.txn_id, t.txn_ref || ' -> ' || l_ref || ' : ' || SUBSTR(p_reason, 1, 200));
    wallet_social_pkg.notify(l_fu, 'MONEY_IN', '↩️ أُعيد لك ' || TO_CHAR(t.amount + t.fee, 'FM999G990D000') || ' د.أ',
      'عكس العملية ' || t.txn_ref || ' · ' || SUBSTR(p_reason, 1, 100), 23);
    COMMIT;
    RETURN l_ref;
  END admin_reverse;

END wallet_account_pkg;
/



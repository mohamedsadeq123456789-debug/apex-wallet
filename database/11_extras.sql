    l_msg VARCHAR2(4000);
    FUNCTION d (p VARCHAR2) RETURN DATE IS BEGIN RETURN CASE WHEN p IS NOT NULL THEN TO_DATE(p, 'YYYY-MM-DD') END; END;
    PROCEDURE ok IS BEGIN apex_json.open_object; apex_json.write('ok', TRUE); END;
  BEGIN
    l := me;
    CASE a
      WHEN 'hist' THEN
        hist_rows(l.user_id, x2, x3, d(x4), d(x5), x6, NVL(TO_NUMBER(x7), 0), l_html, l_more, l_c, l_i, l_o);
        ok; apex_json.write('html', l_html); apex_json.write('more', l_more);
        apex_json.write('cnt', l_c); apex_json.write('in', money(l_i)); apex_json.write('out', money(l_o));
        apex_json.close_object;
      WHEN 'csv' THEN
        ok; apex_json.open_array('rows');
        FOR r IN (SELECT * FROM (
                    SELECT t.txn_ref, t.created_at, tt.name_ar, t.amount, t.fee, t.currency_code, t.status, t.description, t.txn_type,
                           CASE WHEN fw.user_id = l.user_id AND fw.wallet_type IN ('MAIN','FX') THEN 'خارج' ELSE 'داخل' END dir,
                           CASE WHEN fw.user_id = l.user_id AND fw.wallet_type IN ('MAIN','FX') THEN ow.shown_name ELSE fw.shown_name END who
                      FROM wlt_transactions t JOIN wlt_txn_types tt ON tt.txn_type = t.txn_type
                      JOIN wlt_v_wallets fw ON fw.wallet_id = t.from_wallet_id JOIN wlt_v_wallets ow ON ow.wallet_id = t.to_wallet_id
                     WHERE t.status IN ('COMPLETED','REVERSED')
                       AND ((fw.user_id = l.user_id AND fw.wallet_type IN ('MAIN','FX')) OR (ow.user_id = l.user_id AND ow.wallet_type IN ('MAIN','FX'))))
                   WHERE (x2 IS NULL OR dir = CASE x2 WHEN 'in' THEN 'داخل' ELSE 'خارج' END)
                     AND (x3 IS NULL OR wallet_ui8_pkg.cat_of(txn_type) = x3)
                     AND (x4 IS NULL OR CAST(created_at AS DATE) + 3/24 >= TO_DATE(x4, 'YYYY-MM-DD'))
                     AND (x5 IS NULL OR CAST(created_at AS DATE) + 3/24 < TO_DATE(x5, 'YYYY-MM-DD') + 1)
                     AND (x6 IS NULL OR txn_ref LIKE '%' || UPPER(x6) || '%' OR UPPER(who) LIKE '%' || UPPER(x6) || '%' OR UPPER(description) LIKE '%' || UPPER(x6) || '%')
                   ORDER BY created_at DESC FETCH FIRST 2000 ROWS ONLY) LOOP
          apex_json.open_array;
          apex_json.write(r.txn_ref); apex_json.write(TO_CHAR(wlt_local(r.created_at), 'YYYY-MM-DD HH24:MI')); apex_json.write(r.name_ar);
          apex_json.write(r.who); apex_json.write(r.dir); apex_json.write(TO_CHAR(r.amount, 'FM9999999990D000', 'NLS_NUMERIC_CHARACTERS=''.,'''));
          apex_json.write(TO_CHAR(r.fee, 'FM9999999990D000', 'NLS_NUMERIC_CHARACTERS=''.,''')); apex_json.write(r.currency_code);
          apex_json.write(CASE r.status WHEN 'REVERSED' THEN 'معكوسة' ELSE 'مكتملة' END); apex_json.write(r.description);
          apex_json.close_array;
        END LOOP;
        apex_json.close_array; apex_json.close_object;
      WHEN 'name' THEN wallet_account_pkg.set_name(u, x2); ok; apex_json.close_object;
      WHEN 'pin'  THEN wallet_account_pkg.change_pin(u, x2, x3); ok; apex_json.close_object;
      WHEN 'kyc'  THEN wallet_account_pkg.request_tier(u, x2, x3); ok; apex_json.close_object;
      WHEN 'kycdo' THEN wallet_account_pkg.decide_tier(u, TO_NUMBER(x2), x3); ok; apex_json.close_object;
      WHEN 'txinfo' THEN
        IF l.user_type <> 'ADMIN' THEN RAISE_APPLICATION_ERROR(-20190, 'للإدارة فقط'); END IF;
        BEGIN
          SELECT * INTO t FROM wlt_transactions WHERE txn_ref = UPPER(TRIM(x2));
        EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20190, 'لا توجد عملية بهذا المرجع');
        END;
        SELECT shown_name INTO l_fn FROM wlt_v_wallets WHERE wallet_id = t.from_wallet_id;
        SELECT shown_name INTO l_tn FROM wlt_v_wallets WHERE wallet_id = t.to_wallet_id;
        SELECT name_ar INTO l_tt FROM wlt_txn_types WHERE txn_type = t.txn_type;
        ok; apex_json.write('ref', t.txn_ref); apex_json.write('type', l_tt); apex_json.write('amount', money(t.amount)); apex_json.write('fee', money(t.fee));
        apex_json.write('cur', t.currency_code); apex_json.write('from', l_fn); apex_json.write('to', l_tn); apex_json.write('desc', t.description);
        apex_json.write('time', TO_CHAR(wlt_local(t.created_at), 'DD/MM/YYYY HH24:MI'));
        apex_json.write('status', CASE t.status WHEN 'COMPLETED' THEN '✅ مكتملة' WHEN 'REVERSED' THEN '↩️ معكوسة' ELSE t.status END);
        apex_json.write('can', t.status = 'COMPLETED' AND wallet_account_pkg.reversible(t.txn_type) = 'Y');
        apex_json.write('why', CASE WHEN t.status <> 'COMPLETED' THEN 'العملية معكوسة مسبقاً' ELSE 'هذا النوع مرتبط بحالة أخرى (جمعية، ضمان، تقسيط، حصّالة…) ولا يُعكس من هنا' END);
        apex_json.close_object;
      WHEN 'reverse' THEN
        l_s := wallet_account_pkg.admin_reverse(u, x2, x3);
        ok; apex_json.write('ref', l_s); apex_json.close_object;
      ELSE RAISE_APPLICATION_ERROR(-20199, 'عملية غير معروفة');
    END CASE;
  EXCEPTION WHEN OTHERS THEN
    l_msg := CASE WHEN SQLCODE BETWEEN -20999 AND -20000
                  THEN REGEXP_REPLACE(REGEXP_SUBSTR(SQLERRM, '^[^' || CHR(10) || ']+'), '^ORA-\d+: ', '')
                  WHEN SQLCODE IN (-6502, -1722, -1830, -1843, -1847, -1858, -1861) THEN 'تحقق من القيم المدخلة'
                  ELSE 'حدث خطأ غير متوقع' END;
    apex_json.open_object;
    apex_json.write('ok', FALSE);
    apex_json.write('msg', l_msg);
    apex_json.close_object;
  END api;

END wallet_ui8_pkg;

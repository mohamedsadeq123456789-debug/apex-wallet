  -- -----------------------------------------------------------------
  -- صفوف السجل حسب الفلاتر: نستخدمها عند العرض الأول وعند «عرض المزيد»
  -- -----------------------------------------------------------------
  PROCEDURE hist_rows (p_user NUMBER, p_dir VARCHAR2, p_cat VARCHAR2, p_from DATE, p_to DATE, p_q VARCHAR2,
                       p_offset NUMBER, p_html OUT CLOB, p_more OUT BOOLEAN,
                       p_cnt OUT NUMBER, p_in OUT NUMBER, p_out OUT NUMBER) IS
    l_day  DATE;
    l_n    PLS_INTEGER := 0;
    l_q    VARCHAR2(100) := UPPER(TRIM(p_q));
  BEGIN
    -- ملخص كامل للفلتر (العدد ومجموع الداخل والخارج بالدينار)
    SELECT COUNT(*), NVL(SUM(CASE WHEN dir = 'in' AND cur = 'JOD' THEN amount END), 0), NVL(SUM(CASE WHEN dir = 'out' AND cur = 'JOD' THEN amount + fee END), 0)
      INTO p_cnt, p_in, p_out
      FROM (SELECT t.amount, t.fee, t.currency_code cur,
                   CASE WHEN fw.user_id = p_user AND fw.wallet_type IN ('MAIN','FX') THEN 'out' ELSE 'in' END dir, t.txn_type, t.txn_ref, t.description, t.created_at,
                   CASE WHEN fw.user_id = p_user AND fw.wallet_type IN ('MAIN','FX') THEN ow.shown_name ELSE iw.shown_name END who
              FROM wlt_transactions t
              JOIN wlt_v_wallets fw ON fw.wallet_id = t.from_wallet_id
              JOIN wlt_v_wallets ow ON ow.wallet_id = t.to_wallet_id
              JOIN wlt_v_wallets iw ON iw.wallet_id = t.from_wallet_id
             WHERE t.status IN ('COMPLETED','REVERSED')
               AND ((fw.user_id = p_user AND fw.wallet_type IN ('MAIN','FX')) OR (ow.user_id = p_user AND ow.wallet_type IN ('MAIN','FX')))
           )
     WHERE (p_dir IS NULL OR dir = p_dir)
       AND (p_cat IS NULL OR wallet_ui8_pkg.cat_of(txn_type) = p_cat)
       AND (p_from IS NULL OR CAST(created_at AS DATE) + 3/24 >= p_from)
       AND (p_to IS NULL OR CAST(created_at AS DATE) + 3/24 < p_to + 1)
       AND (l_q IS NULL OR txn_ref LIKE '%' || l_q || '%' OR UPPER(who) LIKE '%' || l_q || '%' OR UPPER(description) LIKE '%' || l_q || '%');

    FOR r IN (
      SELECT * FROM (
        SELECT t.txn_ref, t.txn_type, tt.name_ar, t.amount, t.fee, t.status, t.description, t.created_at, t.currency_code cur,
               CASE WHEN fw.user_id = p_user AND fw.wallet_type IN ('MAIN','FX') THEN 'out' ELSE 'in' END dir,
               CASE WHEN fw.user_id = p_user AND fw.wallet_type IN ('MAIN','FX') THEN CASE WHEN ow.user_type = 'SYSTEM' OR ow.user_id = p_user THEN tt.name_ar ELSE ow.shown_name END
                    ELSE CASE WHEN fw.user_type = 'SYSTEM' OR fw.user_id = p_user AND fw.wallet_type IN ('MAIN','FX') THEN tt.name_ar ELSE fw.shown_name END END who,
               t.txn_id
          FROM wlt_transactions t
          JOIN wlt_txn_types tt ON tt.txn_type = t.txn_type
          JOIN wlt_v_wallets fw ON fw.wallet_id = t.from_wallet_id
          JOIN wlt_v_wallets ow ON ow.wallet_id = t.to_wallet_id
         WHERE t.status IN ('COMPLETED','REVERSED')
           AND ((fw.user_id = p_user AND fw.wallet_type IN ('MAIN','FX')) OR (ow.user_id = p_user AND ow.wallet_type IN ('MAIN','FX'))))
       WHERE (p_dir IS NULL OR dir = p_dir)
         AND (p_cat IS NULL OR wallet_ui8_pkg.cat_of(txn_type) = p_cat)
         AND (p_from IS NULL OR CAST(created_at AS DATE) + 3/24 >= p_from)
         AND (p_to IS NULL OR CAST(created_at AS DATE) + 3/24 < p_to + 1)
         AND (l_q IS NULL OR txn_ref LIKE '%' || l_q || '%' OR UPPER(who) LIKE '%' || l_q || '%' OR UPPER(description) LIKE '%' || l_q || '%')
       ORDER BY txn_id DESC
       OFFSET p_offset ROWS FETCH NEXT c_page + 1 ROWS ONLY) LOOP
      l_n := l_n + 1;
      EXIT WHEN l_n > c_page;

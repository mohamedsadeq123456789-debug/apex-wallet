CREATE TABLE wlt_kyc_requests (
  req_id      NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_kycr PRIMARY KEY,
  user_id     NUMBER        NOT NULL CONSTRAINT fk_wlt_kycr_user REFERENCES wlt_users,
  from_tier   VARCHAR2(10)  NOT NULL,
  to_tier     VARCHAR2(10)  NOT NULL CONSTRAINT fk_wlt_kycr_tier REFERENCES wlt_kyc_tiers,
  note        VARCHAR2(300),
  status      VARCHAR2(10)  DEFAULT 'PENDING' NOT NULL CONSTRAINT ck_wlt_kycr_status CHECK (status IN ('PENDING','APPROVED','REJECTED')),
  decided_by  NUMBER        CONSTRAINT fk_wlt_kycr_admin REFERENCES wlt_users,
  decided_at  TIMESTAMP,
  created_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
-- طلب معلّق واحد فقط لكل مستخدم
CREATE UNIQUE INDEX uq_wlt_kycr_pending ON wlt_kyc_requests (CASE WHEN status = 'PENDING' THEN user_id END);
CREATE INDEX ix_wlt_kycr_user  ON wlt_kyc_requests (user_id);
CREATE INDEX ix_wlt_kycr_admin ON wlt_kyc_requests (decided_by);
CREATE INDEX ix_wlt_kycr_tier  ON wlt_kyc_requests (to_tier);



-- ---------------------------------------------------------------------
-- الحصّالات: كل حصّالة محفظة SAVINGS مستقلة يملكها المستخدم، بقيودها في الدفتر
-- ---------------------------------------------------------------------
CREATE TABLE wlt_goals (
  goal_id        NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_goal PRIMARY KEY,
  user_id        NUMBER        NOT NULL CONSTRAINT fk_wlt_goal_user REFERENCES wlt_users,
  wallet_id      NUMBER        NOT NULL CONSTRAINT fk_wlt_goal_wallet REFERENCES wlt_wallets
                               CONSTRAINT uq_wlt_goal_wallet UNIQUE,
  name           VARCHAR2(60)  NOT NULL,
  emoji          VARCHAR2(16)  DEFAULT '🎯' NOT NULL,
  target_amount  NUMBER(15,3)  CONSTRAINT ck_wlt_goal_target CHECK (target_amount IS NULL OR target_amount > 0),
  target_date    DATE,
  locked_until   DATE,
  reached_at     TIMESTAMP,
  status         VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL CONSTRAINT ck_wlt_goal_status CHECK (status IN ('ACTIVE','CLOSED')),
  created_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_wlt_goal_user ON wlt_goals (user_id, status);

-- ---------------------------------------------------------------------
-- القواعد الذكية: قاعدة واحدة من كل نوع لكل مستخدم
--   ROUNDUP     : قرّب كل دفعة لأعلى (param = 0.5 أو 1) والفكّة للحصّالة
--   PCT_IN      : ادّخر param % من كل مبلغ يصلك
--   SWEEP       : آخر اليوم انقل ما يزيد عن param د.أ للحصّالة
--   SPEND_ALERT : نبّهني إذا تجاوز صرفي اليومي param د.أ
-- ---------------------------------------------------------------------
CREATE TABLE wlt_smart_rules (
  rule_id      NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_rule PRIMARY KEY,
  user_id      NUMBER        NOT NULL CONSTRAINT fk_wlt_rule_user REFERENCES wlt_users,
  rule_type    VARCHAR2(12)  NOT NULL CONSTRAINT ck_wlt_rule_type CHECK (rule_type IN ('ROUNDUP','PCT_IN','SWEEP','SPEND_ALERT')),
  goal_id      NUMBER        CONSTRAINT fk_wlt_rule_goal REFERENCES wlt_goals,
  param_num    NUMBER(15,3)  NOT NULL CONSTRAINT ck_wlt_rule_param CHECK (param_num > 0),
  is_active    CHAR(1)       DEFAULT 'Y' NOT NULL CONSTRAINT ck_wlt_rule_active CHECK (is_active IN ('Y','N')),
  fired_count  NUMBER        DEFAULT 0 NOT NULL,
  total_moved  NUMBER(15,3)  DEFAULT 0 NOT NULL,
  last_fired   TIMESTAMP,
  created_at   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_wlt_rule_user_type UNIQUE (user_id, rule_type),
  CONSTRAINT ck_wlt_rule_goal CHECK (rule_type = 'SPEND_ALERT' OR goal_id IS NOT NULL)
);
CREATE INDEX ix_wlt_rule_goal ON wlt_smart_rules (goal_id);

-- طابور الأحداث: المشغّل يسجّل الحركة فقط، والمعالجة تتم خارج معاملة التحويل
CREATE TABLE wlt_rule_events (
  txn_id      NUMBER     CONSTRAINT pk_wlt_rev PRIMARY KEY CONSTRAINT fk_wlt_rev_txn REFERENCES wlt_transactions,
  created_at  TIMESTAMP  DEFAULT SYSTIMESTAMP NOT NULL
);

-- ---------------------------------------------------------------------
-- محافظ الأبناء: الابن مستخدم كامل برقمه، وولي الأمر يضع الضوابط
-- ---------------------------------------------------------------------
CREATE TABLE wlt_child_links (
  child_user_id   NUMBER        CONSTRAINT pk_wlt_child PRIMARY KEY CONSTRAINT fk_wlt_child_user REFERENCES wlt_users,
  parent_user_id  NUMBER        NOT NULL CONSTRAINT fk_wlt_child_parent REFERENCES wlt_users,
  daily_limit     NUMBER(15,3)  DEFAULT 5 NOT NULL CONSTRAINT ck_wlt_child_limit CHECK (daily_limit >= 0),
  allow_p2p       CHAR(1)       DEFAULT 'N' NOT NULL CONSTRAINT ck_wlt_child_p2p   CHECK (allow_p2p  IN ('Y','N')),
  allow_cash      CHAR(1)       DEFAULT 'N' NOT NULL CONSTRAINT ck_wlt_child_cash  CHECK (allow_cash IN ('Y','N')),
  blocked_cats    VARCHAR2(300),
  paused          CHAR(1)       DEFAULT 'N' NOT NULL CONSTRAINT ck_wlt_child_pause CHECK (paused IN ('Y','N')),
  notify_parent   CHAR(1)       DEFAULT 'Y' NOT NULL CONSTRAINT ck_wlt_child_notif CHECK (notify_parent IN ('Y','N')),
  created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_wlt_child_self CHECK (child_user_id <> parent_user_id)
);
CREATE INDEX ix_wlt_child_parent ON wlt_child_links (parent_user_id);


CREATE OR REPLACE PACKAGE BODY wallet_save_pkg AS

  PROCEDURE fail (p_msg VARCHAR2) IS BEGIN RAISE_APPLICATION_ERROR(c_err, p_msg); END;

  FUNCTION money (p NUMBER) RETURN VARCHAR2 IS
  BEGIN RETURN TO_CHAR(p, 'FM999G999G990D000', 'NLS_NUMERIC_CHARACTERS=''.,'''); END;

  FUNCTION user_of (p_phone VARCHAR2) RETURN wlt_v_wallets%ROWTYPE IS
    l wlt_v_wallets%ROWTYPE;
  BEGIN
    SELECT * INTO l FROM wlt_v_wallets
     WHERE phone = p_phone AND wallet_type = 'MAIN' AND currency_code = 'JOD' AND user_type <> 'SYSTEM';
    RETURN l;
  EXCEPTION WHEN NO_DATA_FOUND THEN
    fail('الرقم غير مسجّل في المحفظة');
    RETURN l;
  END user_of;

  FUNCTION goal_of (p_user NUMBER, p_goal NUMBER) RETURN wlt_goals%ROWTYPE IS
    l wlt_goals%ROWTYPE;
  BEGIN
    SELECT * INTO l FROM wlt_goals WHERE goal_id = p_goal AND user_id = p_user AND status = 'ACTIVE';
    RETURN l;
  EXCEPTION WHEN NO_DATA_FOUND THEN
    fail('الحصّالة غير موجودة');
    RETURN l;
  END goal_of;

  FUNCTION bal (p_wallet NUMBER) RETURN NUMBER IS
    l NUMBER;
  BEGIN
    SELECT balance INTO l FROM wlt_wallets WHERE wallet_id = p_wallet;
    RETURN l;
  END bal;

  -- هل وصلت الحصّالة لهدفها؟ إشعار مرة واحدة فقط
  PROCEDURE check_reached (p_goal NUMBER) IS
    g wlt_goals%ROWTYPE;
  BEGIN
    SELECT * INTO g FROM wlt_goals WHERE goal_id = p_goal;
    IF g.reached_at IS NULL AND g.target_amount IS NOT NULL AND bal(g.wallet_id) >= g.target_amount THEN
      UPDATE wlt_goals SET reached_at = SYSTIMESTAMP WHERE goal_id = p_goal;
      wallet_social_pkg.notify(g.user_id, 'GOAL', g.emoji || ' وصلت لهدفك: ' || g.name,
        'جمعت ' || money(g.target_amount) || ' د.أ. مبروك! 🎉', 14);
    END IF;
  END check_reached;

  FUNCTION create_goal (p_phone VARCHAR2, p_name VARCHAR2, p_emoji VARCHAR2, p_target NUMBER,
                        p_date DATE DEFAULT NULL, p_lock VARCHAR2 DEFAULT 'N') RETURN NUMBER IS
    l_u    wlt_v_wallets%ROWTYPE := user_of(p_phone);
    l_name VARCHAR2(60) := SUBSTR(TRIM(REGEXP_REPLACE(p_name, '[<>"]', '')), 1, 60);
    l_w    NUMBER;
    l_id   NUMBER;
    l_n    NUMBER;
  BEGIN
    IF l_name IS NULL THEN fail('اكتب اسماً للحصّالة'); END IF;
    IF p_target IS NOT NULL AND (p_target <= 0 OR p_target <> ROUND(p_target, 3)) THEN fail('الهدف غير صحيح'); END IF;
    IF p_date IS NOT NULL AND p_date <= TRUNC(SYSDATE) THEN fail('تاريخ الهدف يجب أن يكون في المستقبل'); END IF;
    IF p_lock = 'Y' AND p_date IS NULL THEN fail('لقفل الحصّالة حدّد تاريخاً'); END IF;
    SELECT COUNT(*) INTO l_n FROM wlt_goals WHERE user_id = l_u.user_id AND status = 'ACTIVE';
    IF l_n >= 8 THEN fail('الحد الأقصى 8 حصّالات'); END IF;

    INSERT INTO wlt_wallets (user_id, wallet_type, label) VALUES (l_u.user_id, 'SAVINGS', SUBSTR('حصّالة ' || l_name, 1, 50))
    RETURNING wallet_id INTO l_w;
    INSERT INTO wlt_goals (user_id, wallet_id, name, emoji, target_amount, target_date, locked_until)
    VALUES (l_u.user_id, l_w, l_name, NVL(SUBSTR(p_emoji, 1, 4), '🎯'), p_target, p_date,
            CASE WHEN p_lock = 'Y' THEN p_date END)
    RETURNING goal_id INTO l_id;
    COMMIT;
    RETURN l_id;
  END create_goal;

  FUNCTION deposit (p_phone VARCHAR2, p_goal_id NUMBER, p_amount NUMBER, p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
    l_u   wlt_v_wallets%ROWTYPE := user_of(p_phone);
    g     wlt_goals%ROWTYPE := goal_of(l_u.user_id, p_goal_id);
    l_ref VARCHAR2(20);
  BEGIN
    l_ref := wallet_core_pkg.transfer(p_from_wallet => l_u.wallet_id, p_to_wallet => g.wallet_id, p_amount => p_amount,
               p_txn_type => 'SAVE', p_idem_key => p_idem, p_description => g.emoji || ' ' || g.name, p_commit => FALSE);
    check_reached(g.goal_id);
    COMMIT;
    RETURN l_ref;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END deposit;

  FUNCTION withdraw (p_phone VARCHAR2, p_goal_id NUMBER, p_amount NUMBER, p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
    l_u   wlt_v_wallets%ROWTYPE := user_of(p_phone);
    g     wlt_goals%ROWTYPE := goal_of(l_u.user_id, p_goal_id);
    l_ref VARCHAR2(20);
  BEGIN
    IF g.locked_until > SYSDATE THEN
      fail('الحصّالة مقفلة حتى ' || TO_CHAR(g.locked_until, 'DD/MM/YYYY') || ' 🔒');
    END IF;
    l_ref := wallet_core_pkg.transfer(p_from_wallet => g.wallet_id, p_to_wallet => l_u.wallet_id, p_amount => p_amount,
               p_txn_type => 'SAVE_OUT', p_idem_key => p_idem, p_description => g.emoji || ' ' || g.name, p_commit => TRUE);
    RETURN l_ref;
  END withdraw;

  PROCEDURE close_goal (p_phone VARCHAR2, p_goal_id NUMBER) IS
    l_u   wlt_v_wallets%ROWTYPE := user_of(p_phone);
    g     wlt_goals%ROWTYPE := goal_of(l_u.user_id, p_goal_id);
    l_b   NUMBER;
    l_ref VARCHAR2(20);
  BEGIN
    IF g.locked_until > SYSDATE THEN fail('الحصّالة مقفلة حتى ' || TO_CHAR(g.locked_until, 'DD/MM/YYYY') || ' 🔒'); END IF;
    l_b := bal(g.wallet_id);
    IF l_b > 0 THEN
      l_ref := wallet_core_pkg.transfer(p_from_wallet => g.wallet_id, p_to_wallet => l_u.wallet_id, p_amount => l_b,
                 p_txn_type => 'SAVE_OUT', p_idem_key => 'GOALCLOSE-' || g.goal_id,
                 p_description => 'إغلاق ' || g.name, p_commit => FALSE);
    END IF;
    UPDATE wlt_goals SET status = 'CLOSED' WHERE goal_id = g.goal_id;
    UPDATE wlt_wallets SET status = 'CLOSED' WHERE wallet_id = g.wallet_id;
    UPDATE wlt_smart_rules SET is_active = 'N' WHERE goal_id = g.goal_id;
    COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END close_goal;

  PROCEDURE set_rule (p_phone VARCHAR2, p_type VARCHAR2, p_goal_id NUMBER, p_param NUMBER, p_active VARCHAR2) IS
    l_u wlt_v_wallets%ROWTYPE := user_of(p_phone);
    g   wlt_goals%ROWTYPE;
  BEGIN
    IF p_type NOT IN ('ROUNDUP','PCT_IN','SWEEP','SPEND_ALERT') THEN fail('قاعدة غير معروفة'); END IF;
    IF p_type <> 'SPEND_ALERT' THEN g := goal_of(l_u.user_id, p_goal_id); END IF;
    IF p_param IS NULL OR p_param <= 0 THEN fail('أدخل قيمة صحيحة'); END IF;
    IF p_type = 'ROUNDUP' AND p_param NOT IN (0.25, 0.5, 1) THEN fail('التقريب لأقرب ربع أو نصف أو دينار'); END IF;
    IF p_type = 'PCT_IN' AND p_param > 50 THEN fail('النسبة بين 1% و 50%'); END IF;

    MERGE INTO wlt_smart_rules r
    USING (SELECT l_u.user_id u, p_type t FROM dual) s
       ON (r.user_id = s.u AND r.rule_type = s.t)
     WHEN MATCHED THEN UPDATE SET goal_id = g.goal_id, param_num = p_param, is_active = NVL(p_active, 'Y')
     WHEN NOT MATCHED THEN INSERT (user_id, rule_type, goal_id, param_num, is_active)
                           VALUES (l_u.user_id, p_type, g.goal_id, p_param, NVL(p_active, 'Y'));
    COMMIT;
  END set_rule;

  -- نقل تلقائي للحصّالة: إن لم يكفِ الرصيد نتجاوز بصمت، فالقاعدة لا تُفشل عملية المستخدم أبداً
  PROCEDURE auto_move (p_rule wlt_smart_rules%ROWTYPE, p_from NUMBER, p_amount NUMBER, p_type VARCHAR2,
                       p_idem VARCHAR2, p_desc VARCHAR2) IS
    l_w   NUMBER;
    l_ref VARCHAR2(20);
  BEGIN
    IF p_amount < 0.001 THEN RETURN; END IF;
    SELECT wallet_id INTO l_w FROM wlt_goals WHERE goal_id = p_rule.goal_id AND status = 'ACTIVE';
    l_ref := wallet_core_pkg.transfer(p_from_wallet => p_from, p_to_wallet => l_w, p_amount => ROUND(p_amount, 3),
               p_txn_type => p_type, p_idem_key => p_idem, p_description => p_desc, p_commit => FALSE);
    UPDATE wlt_smart_rules SET fired_count = fired_count + 1, total_moved = total_moved + ROUND(p_amount, 3),
                               last_fired = SYSTIMESTAMP
     WHERE rule_id = p_rule.rule_id;
    check_reached(p_rule.goal_id);
  EXCEPTION WHEN OTHERS THEN NULL;
  END auto_move;

  PROCEDURE handle (p_txn_id NUMBER) IS
    t       wlt_transactions%ROWTYPE;
    l_fu    NUMBER; l_ft VARCHAR2(10);
    l_tu    NUMBER; l_tt VARCHAR2(10);
    l_today NUMBER;
    l_name  VARCHAR2(200);
    l_other VARCHAR2(200);
    r       wlt_smart_rules%ROWTYPE;
  BEGIN
    SELECT * INTO t FROM wlt_transactions WHERE txn_id = p_txn_id;
    IF t.status <> 'COMPLETED' THEN RETURN; END IF;
    SELECT user_id, wallet_type INTO l_fu, l_ft FROM wlt_wallets WHERE wallet_id = t.from_wallet_id;
    SELECT user_id, wallet_type INTO l_tu, l_tt FROM wlt_wallets WHERE wallet_id = t.to_wallet_id;

    -- جهة الصرف
    IF l_ft = 'MAIN' AND l_fu <> l_tu
       AND t.txn_type IN ('TRANSFER','MERCHANT_PAY','BILL_PAY','RECHARGE','CASH_OUT','JAMIYA','EIDIYA','ALLOWANCE') THEN
      FOR x IN (SELECT * FROM wlt_smart_rules WHERE user_id = l_fu AND is_active = 'Y') LOOP
        r := x;
        IF x.rule_type = 'ROUNDUP' THEN
          auto_move(r, t.from_wallet_id, CEIL(t.amount / x.param_num) * x.param_num - t.amount,
                    'ROUNDUP', 'RU-' || t.txn_id, 'فكّة ' || t.txn_ref);
        ELSIF x.rule_type = 'SPEND_ALERT' THEN
          SELECT NVL(SUM(amount), 0) INTO l_today FROM wlt_transactions
           WHERE from_wallet_id = t.from_wallet_id AND status = 'COMPLETED' AND created_at >= TRUNC(SYSDATE)
             AND txn_type NOT IN ('SAVE','ROUNDUP') AND txn_id <= t.txn_id;
          IF l_today >= x.param_num AND l_today - t.amount < x.param_num THEN
            wallet_social_pkg.notify(l_fu, 'ALERT', '⚠️ تجاوزت حد صرفك اليومي',
              'صرفت اليوم ' || money(l_today) || ' د.أ من أصل ' || money(x.param_num) || ' حدّدتها لنفسك', 14);
            UPDATE wlt_smart_rules SET fired_count = fired_count + 1, last_fired = SYSTIMESTAMP WHERE rule_id = x.rule_id;
          END IF;
        END IF;
      END LOOP;

      -- إشعار ولي الأمر بكل صرف من محفظة الابن
      FOR c IN (SELECT parent_user_id FROM wlt_child_links WHERE child_user_id = l_fu AND notify_parent = 'Y') LOOP
        SELECT shown_name INTO l_name  FROM wlt_v_wallets WHERE wallet_id = t.from_wallet_id;
        SELECT CASE WHEN user_type = 'SYSTEM' THEN NULL ELSE shown_name END INTO l_other
          FROM wlt_v_wallets WHERE wallet_id = t.to_wallet_id;
        IF l_tu <> c.parent_user_id THEN
          wallet_social_pkg.notify(c.parent_user_id, 'CHILD', '👧 ' || l_name || ' صرف ' || money(t.amount) || ' د.أ',
            NVL(l_other, 'عملية') || ' · ' || t.txn_ref, 16);
        END IF;
      END LOOP;
    END IF;

    -- جهة الاستلام: ادّخر نسبة من كل مبلغ يصلك
    IF l_tt = 'MAIN' AND l_fu <> l_tu
       AND t.txn_type IN ('TRANSFER','TOPUP','CASH_IN','JAMIYA_PAYOUT','EIDIYA_CLAIM','ALLOWANCE','REFUND') THEN
      FOR x IN (SELECT * FROM wlt_smart_rules WHERE user_id = l_tu AND is_active = 'Y' AND rule_type = 'PCT_IN') LOOP
        r := x;
        auto_move(r, t.to_wallet_id, TRUNC(t.amount * x.param_num / 100, 3),
                  'SAVE', 'PI-' || t.txn_id, 'ادّخار ' || x.param_num || '% من ' || t.txn_ref);
      END LOOP;
    END IF;
  END handle;

  FUNCTION process_events (p_wallet NUMBER DEFAULT NULL, p_max NUMBER DEFAULT 500) RETURN NUMBER IS
    l_ids sys.odcinumberlist;
    l_one NUMBER;
    l_n   NUMBER := 0;
  BEGIN
    SELECT e.txn_id BULK COLLECT INTO l_ids
      FROM wlt_rule_events e JOIN wlt_transactions t ON t.txn_id = e.txn_id
     WHERE p_wallet IS NULL OR t.from_wallet_id = p_wallet OR t.to_wallet_id = p_wallet
     ORDER BY e.txn_id FETCH FIRST p_max ROWS ONLY;
    FOR i IN 1 .. l_ids.COUNT LOOP
      BEGIN
        SELECT txn_id INTO l_one FROM wlt_rule_events WHERE txn_id = l_ids(i) FOR UPDATE SKIP LOCKED;
        handle(l_one);
        DELETE FROM wlt_rule_events WHERE txn_id = l_one;
        COMMIT;
        l_n := l_n + 1;
      EXCEPTION
        WHEN NO_DATA_FOUND THEN NULL;  -- يعالجها طرف آخر الآن
        WHEN OTHERS THEN ROLLBACK;
      END;
    END LOOP;
    RETURN l_n;
  END process_events;

  -- تُستدعى من الشاشة الرئيسية: الفكّة تظهر فوراً قبل عرض الرصيد
  PROCEDURE process_wallet (p_wallet NUMBER) IS
    l NUMBER;
  BEGIN
    l := process_events(p_wallet, 50);
  EXCEPTION WHEN OTHERS THEN NULL;
  END process_wallet;

  -- آخر اليوم (بعد التاسعة مساءً بتوقيت الخادم): الزيادة فوق الحد تذهب للحصّالة
  FUNCTION run_sweeps (p_force BOOLEAN DEFAULT FALSE) RETURN NUMBER IS
    l_n    NUMBER := 0;
    l_main NUMBER;
    l_av   NUMBER;
    r      wlt_smart_rules%ROWTYPE;
  BEGIN
    IF NOT p_force AND TO_NUMBER(TO_CHAR(SYSDATE, 'HH24')) < 21 THEN RETURN 0; END IF;
    FOR x IN (SELECT * FROM wlt_smart_rules
               WHERE rule_type = 'SWEEP' AND is_active = 'Y'
                 AND (last_fired IS NULL OR last_fired < TRUNC(SYSTIMESTAMP))) LOOP
      r := x;
      BEGIN
        SELECT wallet_id, balance - held_amount INTO l_main, l_av FROM wlt_wallets
         WHERE user_id = x.user_id AND wallet_type = 'MAIN' AND currency_code = 'JOD';
        IF l_av > x.param_num THEN
          auto_move(r, l_main, l_av - x.param_num, 'SAVE', 'SW-' || x.rule_id || '-' || TO_CHAR(SYSDATE, 'YYYYMMDD'),
                    'ادّخار ما زاد عن ' || money(x.param_num) || ' د.أ');
          l_n := l_n + 1;
        END IF;
        UPDATE wlt_smart_rules SET last_fired = SYSTIMESTAMP WHERE rule_id = x.rule_id;
        COMMIT;
      EXCEPTION WHEN OTHERS THEN ROLLBACK;
      END;
    END LOOP;
    RETURN l_n;
  END run_sweeps;

  PROCEDURE run_job IS
    l NUMBER;
  BEGIN
    l := process_events;
    l := run_sweeps;
    UPDATE wlt_pay_codes SET status = 'EXPIRED' WHERE status = 'ACTIVE' AND expires_at < SYSTIMESTAMP;
    COMMIT;
  END run_job;

END wallet_save_pkg;

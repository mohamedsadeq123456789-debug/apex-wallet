CREATE OR REPLACE PACKAGE wallet_paycode_pkg AS
  c_err CONSTANT PLS_INTEGER := -20162;
  PROCEDURE new_code (p_phone VARCHAR2, p_max NUMBER, p_minutes NUMBER, p_code OUT VARCHAR2, p_id OUT NUMBER);
  PROCEDURE cancel_code (p_phone VARCHAR2, p_code_id NUMBER);
  FUNCTION charge (p_merchant_phone VARCHAR2, p_code VARCHAR2, p_amount NUMBER, p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2;

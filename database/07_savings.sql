/

CREATE OR REPLACE PACKAGE BODY wallet_paycode_pkg AS
  c_max_fail CONSTANT PLS_INTEGER := 8;

  PROCEDURE fail (p_msg VARCHAR2) IS BEGIN RAISE_APPLICATION_ERROR(c_err, p_msg); END;

  FUNCTION money (p NUMBER) RETURN VARCHAR2 IS
  BEGIN RETURN TO_CHAR(p, 'FM999G999G990D000', 'NLS_NUMERIC_CHARACTERS=''.,'''); END;

  FUNCTION user_of (p_phone VARCHAR2) RETURN wlt_v_wallets%ROWTYPE IS
    l wlt_v_wallets%ROWTYPE;
  BEGIN
    SELECT * INTO l FROM wlt_v_wallets
     WHERE phone = p_phone AND wallet_type = 'MAIN' AND currency_code = 'JOD' AND user_type <> 'SYSTEM';
    RETURN l;
  EXCEPTION WHEN NO_DATA_FOUND THEN fail('الرقم غير مسجّل'); RETURN l;
  END user_of;

  PROCEDURE log_attempt (p_merchant NUMBER) IS
    PRAGMA AUTONOMOUS_TRANSACTION;
  BEGIN
    INSERT INTO wlt_code_attempts (merchant_user_id) VALUES (p_merchant);
    COMMIT;
  END log_attempt;

  PROCEDURE new_code (p_phone VARCHAR2, p_max NUMBER, p_minutes NUMBER, p_code OUT VARCHAR2, p_id OUT NUMBER) IS
    l_u   wlt_v_wallets%ROWTYPE := user_of(p_phone);
    l_min NUMBER := NVL(p_minutes, 10);
  BEGIN
    IF p_max IS NULL OR p_max <= 0 OR p_max <> ROUND(p_max, 3) THEN fail('حدّد أقصى مبلغ للكود'); END IF;
    IF p_max > l_u.available_balance THEN fail('السقف أكبر من رصيدك المتاح ' || money(l_u.available_balance)); END IF;
    IF l_min NOT IN (2, 5, 10, 30) THEN fail('مدة غير مسموحة'); END IF;
    -- كود فعّال واحد لكل شخص: الجديد يلغي القديم
    UPDATE wlt_pay_codes SET status = CASE WHEN expires_at < SYSTIMESTAMP THEN 'EXPIRED' ELSE 'CANCELLED' END
     WHERE user_id = l_u.user_id AND status = 'ACTIVE';
    LOOP
      p_code := LPAD(TRUNC(DBMS_RANDOM.VALUE(0, 100000000)), 8, '0');
      BEGIN
        INSERT INTO wlt_pay_codes (user_id, code_hash, max_amount, expires_at)
        VALUES (l_u.user_id, wallet_otp_pkg.sha('PAY:' || p_code), p_max, SYSTIMESTAMP + NUMTODSINTERVAL(l_min, 'MINUTE'))
        RETURNING code_id INTO p_id;
        EXIT;
      EXCEPTION WHEN DUP_VAL_ON_INDEX THEN NULL;   -- تصادم نادر: نولّد رقماً آخر
      END;
    END LOOP;
    COMMIT;
  END new_code;

  PROCEDURE cancel_code (p_phone VARCHAR2, p_code_id NUMBER) IS
    l_u wlt_v_wallets%ROWTYPE := user_of(p_phone);
  BEGIN
    UPDATE wlt_pay_codes SET status = 'CANCELLED'
     WHERE code_id = p_code_id AND user_id = l_u.user_id AND status = 'ACTIVE';
    COMMIT;
  END cancel_code;

  FUNCTION charge (p_merchant_phone VARCHAR2, p_code VARCHAR2, p_amount NUMBER, p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
    l_m    wlt_v_wallets%ROWTYPE := user_of(p_merchant_phone);
    l_c    wlt_pay_codes%ROWTYPE;
    l_cw   NUMBER;
    l_ref  VARCHAR2(20);
    l_n    NUMBER;
    l_code VARCHAR2(20) := REGEXP_REPLACE(TRANSLATE(p_code, '٠١٢٣٤٥٦٧٨٩', '0123456789'), '[^0-9]', '');
  BEGIN
    IF l_m.user_type <> 'MERCHANT' THEN fail('التحصيل بالكود متاح للتجار فقط'); END IF;
    IF p_idem IS NOT NULL THEN
      SELECT MAX(txn_ref) INTO l_ref FROM wlt_transactions WHERE idempotency_key = p_idem;
      IF l_ref IS NOT NULL THEN RETURN l_ref; END IF;
    END IF;
    SELECT COUNT(*) INTO l_n FROM wlt_code_attempts
     WHERE merchant_user_id = l_m.user_id AND attempted_at > SYSTIMESTAMP - INTERVAL '10' MINUTE;
    IF l_n >= c_max_fail THEN fail('محاولات خاطئة كثيرة. انتظر 10 دقائق'); END IF;
    IF p_amount IS NULL OR p_amount <= 0 OR p_amount <> ROUND(p_amount, 3) THEN fail('أدخل المبلغ بشكل صحيح'); END IF;

    BEGIN
      SELECT * INTO l_c FROM wlt_pay_codes
       WHERE status = 'ACTIVE' AND code_hash = wallet_otp_pkg.sha('PAY:' || l_code)
         FOR UPDATE;
    EXCEPTION WHEN NO_DATA_FOUND THEN
      log_attempt(l_m.user_id);
      fail('الكود غير صحيح أو مُستخدم');
    END;
    IF l_c.expires_at < SYSTIMESTAMP THEN
      UPDATE wlt_pay_codes SET status = 'EXPIRED' WHERE code_id = l_c.code_id;
      COMMIT;
      fail('انتهت صلاحية الكود. اطلب من العميل كوداً جديداً');
    END IF;
    IF p_amount > l_c.max_amount THEN
      fail('المبلغ أكبر من سقف الكود (' || money(l_c.max_amount) || ' د.أ)');
    END IF;

    SELECT wallet_id INTO l_cw FROM wlt_wallets WHERE user_id = l_c.user_id AND wallet_type = 'MAIN' AND currency_code = 'JOD';
    l_ref := wallet_core_pkg.transfer(p_from_wallet => l_cw, p_to_wallet => l_m.wallet_id, p_amount => p_amount,
               p_txn_type => 'MERCHANT_PAY', p_idem_key => p_idem, p_description => 'دفع بكود مؤقت',
               p_actor_user => l_c.user_id, p_commit => FALSE);
    UPDATE wlt_pay_codes
       SET status = 'USED', used_by = l_m.user_id, used_amount = p_amount, used_at = SYSTIMESTAMP,
           txn_id = (SELECT txn_id FROM wlt_transactions WHERE txn_ref = l_ref)
     WHERE code_id = l_c.code_id;
    wallet_social_pkg.notify(l_c.user_id, 'PAYCODE', 'دفعت ' || money(p_amount) || ' د.أ بالكود',
      'لدى ' || l_m.shown_name || ' · ' || l_ref, 15);
    COMMIT;
    RETURN l_ref;
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
  END charge;

END wallet_paycode_pkg;

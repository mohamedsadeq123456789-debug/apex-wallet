DECLARE
  l CLOB;
BEGIN
  FOR r IN (SELECT text FROM user_source WHERE name = 'WALLET_UI_PKG' AND type = 'PACKAGE BODY' ORDER BY line) LOOP
    l := l || r.text;
  END LOOP;
  IF INSTR(l, 'process_wallet') = 0 THEN
    l := REPLACE(l, 'SELECT daily_limit INTO l_daily',
      'wallet_save_pkg.process_wallet(l_w);' || CHR(10) || '    SELECT * INTO l_v FROM wlt_v_wallets WHERE wallet_id = l_w;'
      || CHR(10) || '    SELECT daily_limit INTO l_daily');
    EXECUTE IMMEDIATE 'CREATE OR REPLACE ' || l;
  END IF;
END;

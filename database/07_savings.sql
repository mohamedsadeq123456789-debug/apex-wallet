CREATE OR REPLACE PACKAGE BODY wallet_family_pkg AS

  PROCEDURE fail (p_msg VARCHAR2) IS BEGIN RAISE_APPLICATION_ERROR(c_err, p_msg); END;

  FUNCTION money (p NUMBER) RETURN VARCHAR2 IS
  BEGIN RETURN TO_CHAR(p, 'FM999G999G990D000', 'NLS_NUMERIC_CHARACTERS=''.,'''); END;

  FUNCTION user_of (p_phone VARCHAR2) RETURN wlt_v_wallets%ROWTYPE IS
    l wlt_v_wallets%ROWTYPE;
  BEGIN
    SELECT * INTO l FROM wlt_v_wallets
     WHERE phone = p_phone AND wallet_type = 'MAIN' AND currency_code = 'JOD' AND user_type <> 'SYSTEM';
    RETURN l;
  EXCEPTION WHEN NO_DATA_FOUND THEN fail('الرقم غير مسجّل'); RETURN l;
  END user_of;

  FUNCTION is_child (p_user_id NUMBER) RETURN BOOLEAN IS
    n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM wlt_child_links WHERE child_user_id = p_user_id;
    RETURN n > 0;
  END is_child;

  -- الابن لازم يكون تابعاً لنفس ولي الأمر
  FUNCTION child_of (p_parent NUMBER, p_child NUMBER) RETURN wlt_v_wallets%ROWTYPE IS
    l wlt_v_wallets%ROWTYPE;
  BEGIN
    SELECT w.* INTO l FROM wlt_v_wallets w JOIN wlt_child_links c ON c.child_user_id = w.user_id
     WHERE c.parent_user_id = p_parent AND c.child_user_id = p_child AND w.wallet_type = 'MAIN';
    RETURN l;
  EXCEPTION WHEN NO_DATA_FOUND THEN fail('هذه المحفظة ليست من محافظ أبنائك'); RETURN l;
  END child_of;

  FUNCTION add_child (p_parent_phone VARCHAR2, p_child_phone VARCHAR2, p_ticket VARCHAR2,
                      p_name VARCHAR2, p_pin VARCHAR2, p_daily NUMBER DEFAULT 5) RETURN NUMBER IS
    l_p     wlt_v_wallets%ROWTYPE := user_of(p_parent_phone);
    l_phone VARCHAR2(15) := wallet_otp_pkg.normalize_phone(p_child_phone);
    l_name  VARCHAR2(60) := SUBSTR(TRIM(REGEXP_REPLACE(p_name, '[<>"]', '')), 1, 60);
    l_salt  VARCHAR2(16) := DBMS_RANDOM.STRING('X', 16);
    l_id    NUMBER;
    l_n     NUMBER;
  BEGIN
    IF l_p.user_type <> 'CUSTOMER' THEN fail('إضافة الأبناء متاحة لحسابات العملاء فقط'); END IF;
    IF is_child(l_p.user_id) THEN fail('محفظة الابن لا يمكنها إضافة أبناء'); END IF;
    IF l_phone IS NULL THEN fail('رقم الابن غير صحيح'); END IF;
    IF l_name IS NULL THEN fail('اكتب اسم الابن'); END IF;
    IF p_daily IS NULL OR p_daily < 0 OR p_daily > 100 THEN fail('المصروف اليومي بين 0 و 100 د.أ'); END IF;
    SELECT COUNT(*) INTO l_n FROM wlt_child_links WHERE parent_user_id = l_p.user_id;
    IF l_n >= 6 THEN fail('الحد الأقصى 6 أبناء'); END IF;
    wallet_otp_pkg.check_pin(p_pin);
    l_n := wallet_otp_pkg.use_ticket(l_phone, 'CHILD', p_ticket);
    SELECT COUNT(*) INTO l_n FROM wlt_users WHERE phone = l_phone;
    IF l_n > 0 THEN fail('هذا الرقم مسجّل مسبقاً'); END IF;

    INSERT INTO wlt_users (phone, display_name, user_type, kyc_tier, pin_hash, pin_salt)
    VALUES (l_phone, l_name, 'CUSTOMER', 'BASIC', wallet_otp_pkg.sha(l_salt || p_pin), l_salt)
    RETURNING user_id INTO l_id;
    INSERT INTO wlt_wallets (user_id, wallet_type, label) VALUES (l_id, 'MAIN', 'محفظة ' || l_name);
    INSERT INTO wlt_child_links (child_user_id, parent_user_id, daily_limit) VALUES (l_id, l_p.user_id, p_daily);
    INSERT INTO wlt_audit_log (actor_user_id, action, entity, entity_id, details)
    VALUES (l_p.user_id, 'ADD_CHILD', 'USER', l_id, 'إضافة محفظة ابن برمز تفعيل');
    wallet_social_pkg.notify(l_id, 'WELCOME', 'أهلاً ' || l_name || ' 👋',
      'محفظتك جاهزة، ويديرها ولي أمرك. مصروفك اليومي ' || money(p_daily) || ' د.أ', 1);
    COMMIT;
    RETURN l_id;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END add_child;

  PROCEDURE set_controls (p_parent_phone VARCHAR2, p_child_id NUMBER, p_daily NUMBER, p_p2p VARCHAR2,
                          p_cash VARCHAR2, p_blocked VARCHAR2, p_paused VARCHAR2, p_notify VARCHAR2 DEFAULT 'Y') IS
    l_p wlt_v_wallets%ROWTYPE := user_of(p_parent_phone);
    l_c wlt_v_wallets%ROWTYPE := child_of(l_p.user_id, p_child_id);
    l_was CHAR(1);
  BEGIN
    IF p_daily IS NULL OR p_daily < 0 OR p_daily > 100 THEN fail('المصروف اليومي بين 0 و 100 د.أ'); END IF;
    SELECT paused INTO l_was FROM wlt_child_links WHERE child_user_id = l_c.user_id;
    UPDATE wlt_child_links
       SET daily_limit = p_daily,
           allow_p2p  = CASE WHEN p_p2p  = 'Y' THEN 'Y' ELSE 'N' END,
           allow_cash = CASE WHEN p_cash = 'Y' THEN 'Y' ELSE 'N' END,
           blocked_cats = SUBSTR(TRIM(BOTH ':' FROM p_blocked), 1, 300),
           paused = CASE WHEN p_paused = 'Y' THEN 'Y' ELSE 'N' END,
           notify_parent = CASE WHEN p_notify = 'N' THEN 'N' ELSE 'Y' END
     WHERE child_user_id = l_c.user_id;
    IF l_was <> CASE WHEN p_paused = 'Y' THEN 'Y' ELSE 'N' END THEN
      wallet_social_pkg.notify(l_c.user_id, 'CHILD',
        CASE WHEN p_paused = 'Y' THEN '⏸ ولي أمرك أوقف الصرف مؤقتاً' ELSE '▶️ ولي أمرك أعاد تفعيل محفظتك' END, NULL, 16);
    END IF;
    COMMIT;
  END set_controls;

  FUNCTION send_allowance (p_parent_phone VARCHAR2, p_child_id NUMBER, p_amount NUMBER,
                           p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
    l_p wlt_v_wallets%ROWTYPE := user_of(p_parent_phone);
    l_c wlt_v_wallets%ROWTYPE := child_of(l_p.user_id, p_child_id);
  BEGIN
    RETURN wallet_core_pkg.transfer(p_from_wallet => l_p.wallet_id, p_to_wallet => l_c.wallet_id, p_amount => p_amount,
             p_txn_type => 'ALLOWANCE', p_idem_key => p_idem, p_description => 'مصروف ' || l_c.shown_name);
  END send_allowance;

  -- المصروف الأسبوعي يستخدم محرك التحويلات المجدولة من الجلسة 5
  FUNCTION weekly_allowance (p_parent_phone VARCHAR2, p_child_id NUMBER, p_amount NUMBER, p_first DATE) RETURN NUMBER IS
    l_p wlt_v_wallets%ROWTYPE := user_of(p_parent_phone);
    l_c wlt_v_wallets%ROWTYPE := child_of(l_p.user_id, p_child_id);
  BEGIN
    RETURN wallet_social_pkg.schedule(p_parent_phone, l_c.phone, p_amount, 'مصروف أسبوعي', 'WEEKLY',
             CAST(NVL(p_first, TRUNC(SYSDATE) + 1) + 8/24 AS TIMESTAMP));
  END weekly_allowance;

END wallet_family_pkg;

-- ---------------------------------------------------------------------
-- محرك التحويل: ضوابط ولي الأمر تُفحص داخل نفس القفل، فلا يمكن تجاوزها من أي شاشة
-- ---------------------------------------------------------------------
DECLARE
  l      CLOB;
  c_decl CONSTANT VARCHAR2(100) := 'l_month    NUMBER;';
  -- التعليقات لا تُحفظ في المصدر المنشور، لذلك نرتكز على سطر فحص أقصى الرصيد
  c_anch CONSTANT VARCHAR2(200) := q'#IF l_to.user_type = 'CUSTOMER' AND l_to.wallet_type = 'MAIN' THEN#';
  c_blk  CONSTANT VARCHAR2(4000) := q'#    -- 6ب) ضوابط ولي الأمر على محفظة الابن
    IF l_from.wallet_type = 'MAIN' AND l_to.user_id <> l_from.user_id
       AND p_txn_type NOT IN ('SAVE','ROUNDUP','REVERSAL','FEE') THEN
      FOR c IN (SELECT * FROM wlt_child_links WHERE child_user_id = l_from.user_id) LOOP
        IF c.paused = 'Y' THEN
          fail(-20161, 'ولي الأمر أوقف الصرف من هذه المحفظة مؤقتاً');
        END IF;
        IF p_txn_type = 'TRANSFER' AND c.allow_p2p = 'N' AND l_to.user_id <> c.parent_user_id THEN
          fail(-20161, 'التحويل للأشخاص غير مفعّل لهذه المحفظة. اطلب من ولي أمرك');
        END IF;
        IF p_txn_type = 'CASH_OUT' AND c.allow_cash = 'N' THEN
          fail(-20161, 'السحب النقدي غير مفعّل لهذه المحفظة');
        END IF;
        IF p_txn_type = 'MERCHANT_PAY' AND c.blocked_cats IS NOT NULL THEN
          SELECT COUNT(*) INTO l_child_n FROM wlt_merchant_profiles m
           WHERE m.user_id = l_to.user_id AND INSTR(':' || c.blocked_cats || ':', ':' || m.category || ':') > 0;
          IF l_child_n > 0 THEN fail(-20161, 'ولي الأمر حظر الدفع لهذا النوع من المتاجر'); END IF;
        END IF;
        IF l_to.user_id <> c.parent_user_id THEN
          SELECT NVL(SUM(x.amount), 0) INTO l_child_n FROM wlt_transactions x
           WHERE x.from_wallet_id = p_from_wallet AND x.status = 'COMPLETED'
             AND x.created_at >= TRUNC(SYSDATE) AND x.txn_type NOT IN ('SAVE','ROUNDUP')
             AND x.to_wallet_id NOT IN (SELECT pw.wallet_id FROM wlt_wallets pw WHERE pw.user_id = c.parent_user_id);
          IF l_child_n + p_amount > c.daily_limit THEN
            fail(-20161, 'تجاوزت المصروف اليومي ' || TO_CHAR(c.daily_limit, 'FM999G990D000')
                 || ' د.أ. المتبقي اليوم ' || TO_CHAR(GREATEST(c.daily_limit - l_child_n, 0), 'FM999G990D000'));
          END IF;
        END IF;
      END LOOP;
    END IF;
    #';
BEGIN
  FOR r IN (SELECT text FROM user_source WHERE name = 'WALLET_CORE_PKG' AND type = 'PACKAGE BODY' ORDER BY line) LOOP
    l := l || r.text;
  END LOOP;
  IF INSTR(l, 'wlt_child_links') = 0 THEN
    IF REGEXP_COUNT(l, c_decl) <> 1 OR INSTR(l, c_anch) = 0 OR INSTR(l, c_anch, 1, 2) > 0 THEN
      RAISE_APPLICATION_ERROR(-20000, 'لم أجد موضع التعديل في محرك التحويل');
    END IF;
    l := REPLACE(l, c_decl, c_decl || CHR(10) || '    l_child_n  NUMBER;');
    l := REPLACE(l, c_anch, LTRIM(c_blk) || c_anch);
    EXECUTE IMMEDIATE 'CREATE OR REPLACE ' || l;
  END IF;
END;

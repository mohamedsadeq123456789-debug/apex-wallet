CREATE OR REPLACE PACKAGE wallet_escrow_pkg AS
  c_err CONSTANT PLS_INTEGER := -20170;
  FUNCTION create_deal (p_buyer_phone VARCHAR2, p_seller_phone VARCHAR2, p_amount NUMBER, p_title VARCHAR2) RETURN VARCHAR2;
  PROCEDURE mark_shipped (p_seller_phone VARCHAR2, p_deal_id NUMBER);
  FUNCTION confirm (p_buyer_phone VARCHAR2, p_deal_id NUMBER) RETURN VARCHAR2;
  PROCEDURE cancel (p_phone VARCHAR2, p_deal_id NUMBER);
  PROCEDURE dispute (p_buyer_phone VARCHAR2, p_deal_id NUMBER, p_reason VARCHAR2);
  FUNCTION resolve (p_admin_phone VARCHAR2, p_deal_id NUMBER, p_decision VARCHAR2) RETURN VARCHAR2;
  FUNCTION run_due RETURN NUMBER;
END wallet_escrow_pkg;
/

CREATE OR REPLACE PACKAGE BODY wallet_escrow_pkg AS

  PROCEDURE fail (p_msg VARCHAR2) IS BEGIN RAISE_APPLICATION_ERROR(c_err, p_msg); END;

  FUNCTION money (p NUMBER) RETURN VARCHAR2 IS
  BEGIN RETURN TO_CHAR(p, 'FM999G999G990D000', 'NLS_NUMERIC_CHARACTERS=''.,'''); END;

  FUNCTION user_of (p_phone VARCHAR2) RETURN wlt_v_wallets%ROWTYPE IS
    l wlt_v_wallets%ROWTYPE;
  BEGIN
    SELECT * INTO l FROM wlt_v_wallets
     WHERE phone = p_phone AND wallet_type = 'MAIN' AND currency_code = 'JOD' AND user_type <> 'SYSTEM';
    RETURN l;
  EXCEPTION WHEN NO_DATA_FOUND THEN fail('الرقم ' || p_phone || ' غير مسجّل في المحفظة'); RETURN l;
  END user_of;

  FUNCTION name_of (p_user NUMBER) RETURN VARCHAR2 IS
    l VARCHAR2(200);
  BEGIN
    SELECT shown_name INTO l FROM wlt_v_wallets WHERE user_id = p_user AND wallet_type = 'MAIN' AND currency_code = 'JOD';
    RETURN l;
  END name_of;

  FUNCTION lock_deal (p_deal NUMBER) RETURN wlt_escrow_deals%ROWTYPE IS
    l wlt_escrow_deals%ROWTYPE;
  BEGIN
    SELECT * INTO l FROM wlt_escrow_deals WHERE deal_id = p_deal FOR UPDATE;
    RETURN l;
  EXCEPTION WHEN NO_DATA_FOUND THEN fail('الصفقة غير موجودة'); RETURN l;
  END lock_deal;

  -- فك الحجز عن محفظة المشتري
  PROCEDURE unhold (d wlt_escrow_deals%ROWTYPE) IS
  BEGIN
    UPDATE wlt_wallets SET held_amount = held_amount - d.amount WHERE wallet_id = d.buyer_wallet_id;
  END unhold;

  FUNCTION create_deal (p_buyer_phone VARCHAR2, p_seller_phone VARCHAR2, p_amount NUMBER, p_title VARCHAR2) RETURN VARCHAR2 IS
    l_b    wlt_v_wallets%ROWTYPE := user_of(p_buyer_phone);
    l_s    wlt_v_wallets%ROWTYPE := user_of(wallet_otp_pkg.normalize_phone(p_seller_phone));
    l_av   NUMBER;
    l_max  NUMBER;
    l_code VARCHAR2(8);
    l_n    NUMBER;
    l_title VARCHAR2(100) := SUBSTR(TRIM(REGEXP_REPLACE(p_title, '[<>"]', '')), 1, 100);
  BEGIN
    IF l_b.user_id = l_s.user_id THEN fail('لا يمكنك إنشاء صفقة مع نفسك'); END IF;
    IF wallet_family_pkg.is_child(l_b.user_id) THEN fail('صفقات الضمان غير متاحة لمحافظ الأبناء'); END IF;
    IF l_title IS NULL THEN fail('اكتب وصفاً للصفقة'); END IF;
    IF p_amount IS NULL OR p_amount <= 0 OR p_amount <> ROUND(p_amount, 3) THEN fail('أدخل المبلغ بشكل صحيح'); END IF;
    SELECT single_txn_limit INTO l_max FROM wlt_kyc_tiers WHERE tier_code = l_b.kyc_tier;
    IF p_amount > l_max THEN fail('الحد الأقصى للصفقة لمستواك ' || money(l_max) || ' د.أ'); END IF;

    -- الحجز تحت القفل: لا أحد يصرف نفس المال في نفس اللحظة
    SELECT balance - held_amount INTO l_av FROM wlt_wallets WHERE wallet_id = l_b.wallet_id FOR UPDATE;
    IF l_av < p_amount THEN fail('رصيدك المتاح ' || money(l_av) || ' لا يكفي لحجز المبلغ'); END IF;
    UPDATE wlt_wallets SET held_amount = held_amount + p_amount WHERE wallet_id = l_b.wallet_id;

    LOOP
      l_code := 'D' || TRANSLATE(DBMS_RANDOM.STRING('X', 5), '0O1I', '7K9P');
      SELECT COUNT(*) INTO l_n FROM wlt_escrow_deals WHERE code = l_code;
      EXIT WHEN l_n = 0;
    END LOOP;
    INSERT INTO wlt_escrow_deals (code, buyer_user_id, seller_user_id, buyer_wallet_id, amount, title, expires_at)
    VALUES (l_code, l_b.user_id, l_s.user_id, l_b.wallet_id, p_amount, l_title, SYSTIMESTAMP + INTERVAL '7' DAY);
    wallet_social_pkg.notify(l_s.user_id, 'ESCROW', '🛡️ صفقة مضمونة جديدة: ' || money(p_amount) || ' د.أ',
      l_b.shown_name || ' حجز المبلغ لـ «' || l_title || '». سلّم الطلب ثم اضغط «تمّ التسليم».', 17);
    COMMIT;
    RETURN l_code;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END create_deal;

  PROCEDURE mark_shipped (p_seller_phone VARCHAR2, p_deal_id NUMBER) IS
    l_s  wlt_v_wallets%ROWTYPE := user_of(p_seller_phone);
    d    wlt_escrow_deals%ROWTYPE := lock_deal(p_deal_id);
    l_days NUMBER;
  BEGIN
    IF d.seller_user_id <> l_s.user_id THEN fail('هذه الصفقة ليست لك'); END IF;
    IF d.status <> 'HELD' THEN fail('لا يمكن تعديل الصفقة في حالتها الحالية'); END IF;
    SELECT TO_NUMBER(setting_value) INTO l_days FROM wlt_app_settings WHERE setting_key = 'ESCROW_AUTO_DAYS';
    UPDATE wlt_escrow_deals SET status = 'SHIPPED', shipped_at = SYSTIMESTAMP,
           auto_release_at = SYSTIMESTAMP + NUMTODSINTERVAL(l_days, 'DAY')
     WHERE deal_id = d.deal_id;
    wallet_social_pkg.notify(d.buyer_user_id, 'ESCROW', '📦 البائع سلّم «' || d.title || '»',
      'تأكد من الطلب واضغط «استلمت». إذا لم تفعل خلال ' || l_days || ' أيام يُحرَّر المبلغ تلقائياً.', 17);
    COMMIT;
  END mark_shipped;

  FUNCTION do_release (d wlt_escrow_deals%ROWTYPE, p_note VARCHAR2) RETURN VARCHAR2 IS
    l_sw  NUMBER;
    l_ref VARCHAR2(20);
  BEGIN
    SELECT wallet_id INTO l_sw FROM wlt_wallets WHERE user_id = d.seller_user_id AND wallet_type = 'MAIN' AND currency_code = 'JOD';
    unhold(d);
    l_ref := wallet_core_pkg.transfer(p_from_wallet => d.buyer_wallet_id, p_to_wallet => l_sw, p_amount => d.amount,
               p_txn_type => 'ESCROW_REL', p_idem_key => 'ESC-' || d.deal_id,
               p_description => 'ضمان ' || d.code || ' · ' || d.title, p_actor_user => d.buyer_user_id, p_commit => FALSE);
    UPDATE wlt_escrow_deals SET status = 'RELEASED', closed_at = SYSTIMESTAMP,
           release_txn_id = (SELECT txn_id FROM wlt_transactions WHERE txn_ref = l_ref)
     WHERE deal_id = d.deal_id;
    wallet_social_pkg.notify(d.buyer_user_id, 'ESCROW', '✅ اكتملت صفقة «' || d.title || '»', p_note, 17);
    RETURN l_ref;
  END do_release;

  FUNCTION confirm (p_buyer_phone VARCHAR2, p_deal_id NUMBER) RETURN VARCHAR2 IS
    l_b   wlt_v_wallets%ROWTYPE := user_of(p_buyer_phone);
    d     wlt_escrow_deals%ROWTYPE := lock_deal(p_deal_id);
    l_ref VARCHAR2(20);
  BEGIN
    IF d.buyer_user_id <> l_b.user_id THEN fail('هذه الصفقة ليست لك'); END IF;
    IF d.status = 'RELEASED' THEN
      SELECT txn_ref INTO l_ref FROM wlt_transactions WHERE txn_id = d.release_txn_id;
      RETURN l_ref;
    END IF;
    IF d.status NOT IN ('HELD','SHIPPED') THEN fail('لا يمكن تأكيد الصفقة في حالتها الحالية'); END IF;
    l_ref := do_release(d, 'وصل المبلغ للبائع ' || name_of(d.seller_user_id) || ' بعد تأكيدك');
    COMMIT;
    RETURN l_ref;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END confirm;

  -- المشتري يلغي قبل التسليم، والبائع يعتذر في أي وقت قبل التحرير
  PROCEDURE cancel (p_phone VARCHAR2, p_deal_id NUMBER) IS
    l_u wlt_v_wallets%ROWTYPE := user_of(p_phone);
    d   wlt_escrow_deals%ROWTYPE := lock_deal(p_deal_id);
  BEGIN
    IF l_u.user_id = d.buyer_user_id THEN
      IF d.status <> 'HELD' THEN fail('البائع سلّم الطلب. أكّد الاستلام أو افتح اعتراضاً'); END IF;
      wallet_social_pkg.notify(d.seller_user_id, 'ESCROW', 'أُلغيت صفقة «' || d.title || '»', 'ألغاها المشتري قبل التسليم', 17);
    ELSIF l_u.user_id = d.seller_user_id THEN
      IF d.status NOT IN ('HELD','SHIPPED','DISPUTED') THEN fail('لا يمكن إلغاء الصفقة في حالتها الحالية'); END IF;
      wallet_social_pkg.notify(d.buyer_user_id, 'ESCROW', '↩️ أُلغيت صفقة «' || d.title || '»',
        'اعتذر البائع، وفُكّ الحجز عن ' || money(d.amount) || ' د.أ في رصيدك', 17);
    ELSE
      fail('هذه الصفقة ليست لك');
    END IF;
    unhold(d);
    UPDATE wlt_escrow_deals SET status = CASE WHEN l_u.user_id = d.buyer_user_id THEN 'CANCELLED' ELSE 'REFUNDED' END,
           closed_at = SYSTIMESTAMP
     WHERE deal_id = d.deal_id;
    COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END cancel;

  PROCEDURE dispute (p_buyer_phone VARCHAR2, p_deal_id NUMBER, p_reason VARCHAR2) IS
    l_b wlt_v_wallets%ROWTYPE := user_of(p_buyer_phone);
    d   wlt_escrow_deals%ROWTYPE := lock_deal(p_deal_id);
  BEGIN
    IF d.buyer_user_id <> l_b.user_id THEN fail('هذه الصفقة ليست لك'); END IF;
    IF d.status <> 'SHIPPED' THEN fail('الاعتراض متاح بعد التسليم وقبل التحرير فقط'); END IF;
    IF TRIM(p_reason) IS NULL THEN fail('اكتب سبب الاعتراض'); END IF;
    UPDATE wlt_escrow_deals SET status = 'DISPUTED', auto_release_at = NULL,
           dispute_reason = SUBSTR(REGEXP_REPLACE(p_reason, '[<>"]', ''), 1, 300)
     WHERE deal_id = d.deal_id;
    wallet_social_pkg.notify(d.seller_user_id, 'ESCROW', '⚠️ اعتراض على «' || d.title || '»',
      'المبلغ مجمّد حتى تراجع الإدارة الصفقة', 17);
    COMMIT;
  END dispute;

  FUNCTION resolve (p_admin_phone VARCHAR2, p_deal_id NUMBER, p_decision VARCHAR2) RETURN VARCHAR2 IS
    l_a   wlt_v_wallets%ROWTYPE := user_of(p_admin_phone);
    d     wlt_escrow_deals%ROWTYPE := lock_deal(p_deal_id);
    l_ref VARCHAR2(20);
  BEGIN
    IF l_a.user_type <> 'ADMIN' THEN fail('للإدارة فقط'); END IF;
    IF d.status <> 'DISPUTED' THEN fail('الصفقة ليست قيد الاعتراض'); END IF;
    IF p_decision = 'RELEASE' THEN
      l_ref := do_release(d, 'قررت الإدارة تحرير المبلغ للبائع');
    ELSIF p_decision = 'REFUND' THEN
      unhold(d);
      UPDATE wlt_escrow_deals SET status = 'REFUNDED', closed_at = SYSTIMESTAMP WHERE deal_id = d.deal_id;
      wallet_social_pkg.notify(d.buyer_user_id, 'ESCROW', '↩️ قُبل اعتراضك على «' || d.title || '»',
        'فُكّ الحجز عن ' || money(d.amount) || ' د.أ', 17);
    ELSE
      fail('قرار غير معروف');
    END IF;
    INSERT INTO wlt_audit_log (actor_user_id, action, entity, entity_id, details)
    VALUES (l_a.user_id, 'ESCROW_' || p_decision, 'DEAL', d.deal_id, d.code);
    COMMIT;
    RETURN l_ref;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END resolve;

  -- تحرير تلقائي بعد مهلة التسليم + إرجاع الصفقات التي لم تُسلَّم خلال 7 أيام
  FUNCTION run_due RETURN NUMBER IS
    l_n   NUMBER := 0;
    l_ref VARCHAR2(20);
    d     wlt_escrow_deals%ROWTYPE;
  BEGIN
    FOR x IN (SELECT deal_id FROM wlt_escrow_deals
               WHERE (status = 'SHIPPED' AND auto_release_at < SYSTIMESTAMP)
                  OR (status = 'HELD' AND expires_at < SYSTIMESTAMP)) LOOP
      BEGIN
        SELECT * INTO d FROM wlt_escrow_deals WHERE deal_id = x.deal_id FOR UPDATE SKIP LOCKED;
        IF d.status = 'SHIPPED' THEN
          l_ref := do_release(d, 'حُرّر المبلغ تلقائياً بعد انتهاء مهلة التأكيد');
        ELSIF d.status = 'HELD' THEN
          unhold(d);
          UPDATE wlt_escrow_deals SET status = 'REFUNDED', closed_at = SYSTIMESTAMP WHERE deal_id = d.deal_id;
          wallet_social_pkg.notify(d.buyer_user_id, 'ESCROW', '↩️ انتهت صفقة «' || d.title || '»',
            'لم يسلّم البائع خلال 7 أيام، فُكّ الحجز عن مبلغك', 17);
        END IF;
        COMMIT;
        l_n := l_n + 1;
      EXCEPTION
        WHEN NO_DATA_FOUND THEN NULL;
        WHEN OTHERS THEN ROLLBACK;
      END;
    END LOOP;
    RETURN l_n;
  END run_due;

END wallet_escrow_pkg;

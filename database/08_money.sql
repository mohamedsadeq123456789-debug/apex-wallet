DECLARE
  l CLOB;
  PROCEDURE patch (p_name VARCHAR2, p_type VARCHAR2, p_old VARCHAR2, p_new VARCHAR2, p_marker VARCHAR2) IS
  BEGIN
    l := NULL;
    FOR r IN (SELECT text FROM user_source WHERE name = p_name AND type = p_type ORDER BY line) LOOP
      l := l || r.text;
    END LOOP;
    IF INSTR(l, p_marker) > 0 THEN RETURN; END IF;
    IF INSTR(l, p_old) = 0 OR INSTR(l, p_old, 1, 2) > 0 THEN
      RAISE_APPLICATION_ERROR(-20000, 'anchor not found in ' || p_name);
    END IF;
    EXECUTE IMMEDIATE 'CREATE OR REPLACE ' || REPLACE(l, p_old, p_new);
  END;
BEGIN
  -- handle() يستدعي المكافآت أولاً
  patch('WALLET_SAVE_PKG', 'PACKAGE BODY', q'#    IF t.status <> 'COMPLETED' THEN RETURN; END IF;#',
        q'#    IF t.status <> 'COMPLETED' THEN RETURN; END IF;
    BEGIN wallet_reward_pkg.on_txn(t.txn_id); EXCEPTION WHEN OTHERS THEN NULL; END;#', 'wallet_reward_pkg');
  -- لا إشعار «استلمت» عند الصرافة بين محافظ نفس الشخص
  patch('WLT_TXN_NOTIFY_TRG', 'TRIGGER', q'#IN ('SAVE','SAVE_OUT','ROUNDUP')#', q'#IN ('SAVE','SAVE_OUT','ROUNDUP','FX')#', q'#'ROUNDUP','FX'#');
  -- المهمة الدورية تشمل الضمان والتقسيط
  patch('WALLET_SAVE_PKG', 'PACKAGE BODY', q'#    l := run_sweeps;#',
        q'#    l := run_sweeps;
    BEGIN l := wallet_escrow_pkg.run_due; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN l := wallet_bnpl_pkg.run_due;   EXCEPTION WHEN OTHERS THEN NULL; END;#', 'wallet_escrow_pkg');
END;
/

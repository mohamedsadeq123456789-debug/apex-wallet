  deal_id          NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_deal PRIMARY KEY,
  code             VARCHAR2(8)   NOT NULL CONSTRAINT uq_wlt_deal_code UNIQUE,
  buyer_user_id    NUMBER        NOT NULL CONSTRAINT fk_wlt_deal_buyer  REFERENCES wlt_users,
  seller_user_id   NUMBER        NOT NULL CONSTRAINT fk_wlt_deal_seller REFERENCES wlt_users,
  buyer_wallet_id  NUMBER        NOT NULL CONSTRAINT fk_wlt_deal_wallet REFERENCES wlt_wallets,
  amount           NUMBER(15,3)  NOT NULL CONSTRAINT ck_wlt_deal_amount CHECK (amount > 0),
  title            VARCHAR2(100) NOT NULL,
  status           VARCHAR2(10)  DEFAULT 'HELD' NOT NULL
                   CONSTRAINT ck_wlt_deal_status CHECK (status IN ('HELD','SHIPPED','DISPUTED','RELEASED','REFUNDED','CANCELLED')),
  shipped_at       TIMESTAMP,
  auto_release_at  TIMESTAMP,
  expires_at       TIMESTAMP     NOT NULL,
  dispute_reason   VARCHAR2(300),
  release_txn_id   NUMBER        CONSTRAINT fk_wlt_deal_txn REFERENCES wlt_transactions,
  closed_at        TIMESTAMP,
  created_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_wlt_deal_self CHECK (buyer_user_id <> seller_user_id)
);

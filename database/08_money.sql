CREATE OR REPLACE PACKAGE wallet_bnpl_pkg AS
  c_err CONSTANT PLS_INTEGER := -20171;
  TYPE t_elig IS RECORD (
    age_days NUMBER, txns_90 NUMBER, inflow_90 NUMBER, active_months NUMBER, late_count NUMBER,
    p_age NUMBER, p_activity NUMBER, p_inflow NUMBER, p_punctual NUMBER, score NUMBER,
    cap NUMBER, credit_limit NUMBER, used NUMBER, available NUMBER, eligible VARCHAR2(1), reason VARCHAR2(200));
  FUNCTION eligibility (p_user_id NUMBER) RETURN t_elig;
  FUNCTION purchase (p_phone VARCHAR2, p_merchant VARCHAR2, p_amount NUMBER, p_installments NUMBER,
                     p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2;
  FUNCTION pay_next (p_phone VARCHAR2, p_loan_id NUMBER) RETURN VARCHAR2;
  FUNCTION run_due RETURN NUMBER;
END wallet_bnpl_pkg;
/

CREATE OR REPLACE PACKAGE BODY wallet_bnpl_pkg AS
  c_min_amount CONSTANT NUMBER := 10;
  c_min_score  CONSTANT NUMBER := 40;

  PROCEDURE fail (p_msg VARCHAR2) IS BEGIN RAISE_APPLICATION_ERROR(c_err, p_msg); END;

  FUNCTION money (p NUMBER) RETURN VARCHAR2 IS
  BEGIN RETURN TO_CHAR(p, 'FM999G999G990D000', 'NLS_NUMERIC_CHARACTERS=''.,'''); END;

  FUNCTION bnpl_wallet RETURN NUMBER IS
    l NUMBER;
  BEGIN
    SELECT TO_NUMBER(setting_value) INTO l FROM wlt_app_settings WHERE setting_key = 'BNPL_WALLET_ID';
    RETURN l;
  END bnpl_wallet;

  -- الأهلية من تاريخ الحركات: عمر الحساب، النشاط، الدخل، والالتزام بالأقساط
  FUNCTION eligibility (p_user_id NUMBER) RETURN t_elig IS
    e      t_elig;
    l_w    NUMBER;
    l_tier VARCHAR2(10);
    l_kid  BOOLEAN := wallet_family_pkg.is_child(p_user_id);
  BEGIN
    SELECT w.wallet_id, u.kyc_tier, TRUNC(SYSDATE - CAST(u.created_at AS DATE))
      INTO l_w, l_tier, e.age_days
      FROM wlt_users u JOIN wlt_wallets w ON w.user_id = u.user_id AND w.wallet_type = 'MAIN' AND w.currency_code = 'JOD'
     WHERE u.user_id = p_user_id;

    -- دوال تحليلية: مجموع ونشاط الأشهر في مرور واحد على الحركات
    SELECT NVL(MAX(t90), 0), NVL(MAX(in90), 0), NVL(MAX(months), 0)
      INTO e.txns_90, e.inflow_90, e.active_months
      FROM (SELECT COUNT(*) OVER () AS t90,
                   SUM(CASE WHEN x.to_wallet_id = l_w THEN x.amount ELSE 0 END) OVER () AS in90,
                   DENSE_RANK() OVER (ORDER BY TRUNC(x.created_at, 'MM')) +
                   DENSE_RANK() OVER (ORDER BY TRUNC(x.created_at, 'MM') DESC) - 1 AS months
              FROM wlt_transactions x
             WHERE (x.from_wallet_id = l_w OR x.to_wallet_id = l_w)
               AND x.status = 'COMPLETED' AND x.created_at >= SYSDATE - 90
               AND x.txn_type NOT IN ('SAVE','SAVE_OUT','ROUNDUP','FX','BNPL_PAY'));

    SELECT COUNT(*) INTO e.late_count FROM wlt_bnpl_installments i JOIN wlt_bnpl_loans l ON l.loan_id = i.loan_id
     WHERE l.user_id = p_user_id AND i.status = 'LATE';

    e.p_age      := ROUND(LEAST(e.age_days / 60, 1) * 20);
    e.p_activity := ROUND(LEAST(e.txns_90 / 15, 1) * 30);
    e.p_inflow   := ROUND(LEAST(e.inflow_90 / 200, 1) * 40);
    e.p_punctual := GREATEST(10 - e.late_count * 5, 0);
    e.score      := e.p_age + e.p_activity + e.p_inflow + e.p_punctual;
    e.cap        := CASE l_tier WHEN 'PREMIUM' THEN 500 WHEN 'VERIFIED' THEN 200 ELSE 60 END;
    e.credit_limit := FLOOR(e.cap * e.score / 100 / 5) * 5;

    SELECT NVL(SUM(i.amount), 0) INTO e.used FROM wlt_bnpl_installments i JOIN wlt_bnpl_loans l ON l.loan_id = i.loan_id
     WHERE l.user_id = p_user_id AND i.status <> 'PAID';
    e.available := GREATEST(e.credit_limit - e.used, 0);

    e.eligible := 'Y';
    IF l_kid THEN e.eligible := 'N'; e.reason := 'غير متاح لمحافظ الأبناء';
    ELSIF e.late_count > 0 THEN e.eligible := 'N'; e.reason := 'عليك قسط متأخر. سدّده لتعود الخدمة';
    ELSIF e.score < c_min_score THEN e.eligible := 'N'; e.reason := 'استخدم المحفظة أكثر لترتفع أهليتك (المطلوب ' || c_min_score || ' نقطة)';
    ELSIF e.available < c_min_amount THEN e.eligible := 'N'; e.reason := 'استنفدت حدّك. سدّد أقساطاً لتحرير الحد';
    END IF;
    RETURN e;
  END eligibility;

  FUNCTION purchase (p_phone VARCHAR2, p_merchant VARCHAR2, p_amount NUMBER, p_installments NUMBER,
                     p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
    l_u    wlt_v_wallets%ROWTYPE;
    l_m    NUMBER;
    l_mw   NUMBER;
    l_mn   VARCHAR2(200);
    e      t_elig;
    l_ref  VARCHAR2(20);
    l_id   NUMBER;
    l_part NUMBER;
  BEGIN
    IF p_idem IS NOT NULL THEN
      SELECT MAX(txn_ref) INTO l_ref FROM wlt_transactions WHERE idempotency_key = p_idem;
      IF l_ref IS NOT NULL THEN RETURN l_ref; END IF;
    END IF;
    BEGIN
      SELECT * INTO l_u FROM wlt_v_wallets WHERE phone = p_phone AND wallet_type = 'MAIN' AND currency_code = 'JOD';
      SELECT m.user_id, w.wallet_id, w.shown_name INTO l_m, l_mw, l_mn
        FROM wlt_merchant_profiles m JOIN wlt_v_wallets w ON w.user_id = m.user_id AND w.wallet_type = 'MAIN'
       WHERE m.merchant_code = UPPER(TRIM(p_merchant));
    EXCEPTION WHEN NO_DATA_FOUND THEN fail('كود التاجر غير صحيح');
    END;
    IF p_installments NOT IN (3, 4) THEN fail('اختر 3 أو 4 أقساط'); END IF;
    IF p_amount IS NULL OR p_amount < c_min_amount OR p_amount <> ROUND(p_amount, 3) THEN
      fail('أقل مبلغ للتقسيط ' || c_min_amount || ' د.أ');
    END IF;

    -- قفل المستخدم يمنع شراءين متزامنين يتجاوزان الحد
    SELECT wallet_id INTO l_id FROM wlt_wallets WHERE wallet_id = l_u.wallet_id FOR UPDATE;
    e := eligibility(l_u.user_id);
    IF e.eligible = 'N' THEN fail(e.reason); END IF;
    IF p_amount > e.available THEN fail('حدّك المتاح للتقسيط ' || money(e.available) || ' د.أ'); END IF;

    l_ref := wallet_core_pkg.transfer(p_from_wallet => bnpl_wallet, p_to_wallet => l_mw, p_amount => p_amount,
               p_txn_type => 'BNPL_PAY', p_idem_key => p_idem, p_description => 'تقسيط ' || p_installments || ' دفعات · ' || l_u.shown_name,
               p_actor_user => l_u.user_id, p_commit => FALSE);
    INSERT INTO wlt_bnpl_loans (user_id, merchant_user_id, amount, installments, score_at_purchase, txn_id)
    VALUES (l_u.user_id, l_m, p_amount, p_installments, e.score, (SELECT txn_id FROM wlt_transactions WHERE txn_ref = l_ref))
    RETURNING loan_id INTO l_id;
    l_part := TRUNC(p_amount / p_installments, 3);
    FOR i IN 1 .. p_installments LOOP
      INSERT INTO wlt_bnpl_installments (loan_id, inst_no, due_date, amount)
      VALUES (l_id, i, ADD_MONTHS(TRUNC(SYSDATE), i),
              CASE WHEN i = p_installments THEN p_amount - l_part * (p_installments - 1) ELSE l_part END);
    END LOOP;
    wallet_social_pkg.notify(l_u.user_id, 'BNPL', '🛍️ اشتريت من ' || l_mn || ' بالتقسيط',
      p_installments || ' أقساط شهرية بدون فوائد، أولها ' || TO_CHAR(ADD_MONTHS(TRUNC(SYSDATE), 1), 'DD/MM'), 18);
    COMMIT;
    RETURN l_ref;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END purchase;

  FUNCTION collect (p_loan NUMBER, p_no NUMBER, p_auto BOOLEAN) RETURN VARCHAR2 IS
    l_i   wlt_bnpl_installments%ROWTYPE;
    l_l   wlt_bnpl_loans%ROWTYPE;
    l_w   NUMBER;
    l_ref VARCHAR2(20);
    l_n   NUMBER;
  BEGIN
    SELECT * INTO l_i FROM wlt_bnpl_installments WHERE loan_id = p_loan AND inst_no = p_no FOR UPDATE;
    SELECT * INTO l_l FROM wlt_bnpl_loans WHERE loan_id = p_loan;
    SELECT wallet_id INTO l_w FROM wlt_wallets WHERE user_id = l_l.user_id AND wallet_type = 'MAIN' AND currency_code = 'JOD';
    l_ref := wallet_core_pkg.transfer(p_from_wallet => l_w, p_to_wallet => bnpl_wallet, p_amount => l_i.amount,
               p_txn_type => 'BNPL_REPAY', p_idem_key => 'BNPL-' || p_loan || '-' || p_no,
               p_description => 'قسط ' || p_no || ' من ' || l_l.installments, p_commit => FALSE);
    UPDATE wlt_bnpl_installments SET status = 'PAID', paid_at = SYSTIMESTAMP, last_try = SYSDATE,
           paid_txn_id = (SELECT txn_id FROM wlt_transactions WHERE txn_ref = l_ref)
     WHERE loan_id = p_loan AND inst_no = p_no;
    SELECT COUNT(*) INTO l_n FROM wlt_bnpl_installments WHERE loan_id = p_loan AND status <> 'PAID';
    IF l_n = 0 THEN
      UPDATE wlt_bnpl_loans SET status = 'PAID' WHERE loan_id = p_loan;
      wallet_social_pkg.notify(l_l.user_id, 'BNPL', '🎉 سدّدت التقسيط كاملاً', 'شكراً لالتزامك، أهليتك ترتفع مع كل سداد', 18);
    ELSIF p_auto THEN
      wallet_social_pkg.notify(l_l.user_id, 'BNPL', 'خُصم قسط ' || money(l_i.amount) || ' د.أ', 'باقي ' || l_n || ' أقساط', 18);
    END IF;
    RETURN l_ref;
  END collect;

  FUNCTION pay_next (p_phone VARCHAR2, p_loan_id NUMBER) RETURN VARCHAR2 IS
    l_u   NUMBER;
    l_no  NUMBER;
    l_ref VARCHAR2(20);
  BEGIN
    SELECT user_id INTO l_u FROM wlt_users WHERE phone = p_phone;
    SELECT MIN(i.inst_no) INTO l_no FROM wlt_bnpl_installments i JOIN wlt_bnpl_loans l ON l.loan_id = i.loan_id
     WHERE i.loan_id = p_loan_id AND l.user_id = l_u AND i.status <> 'PAID';
    IF l_no IS NULL THEN fail('لا توجد أقساط مستحقة على هذا التقسيط'); END IF;
    l_ref := collect(p_loan_id, l_no, FALSE);
    COMMIT;
    RETURN l_ref;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END pay_next;

  -- مرة يومياً لكل قسط مستحق: نحاول الخصم، وإن لم يكفِ الرصيد يصبح متأخراً بلا غرامة
  FUNCTION run_due RETURN NUMBER IS
    l_n   NUMBER := 0;
    l_ref VARCHAR2(20);
    l_u   NUMBER;
  BEGIN
    FOR x IN (SELECT i.loan_id, i.inst_no, i.amount, l.user_id FROM wlt_bnpl_installments i JOIN wlt_bnpl_loans l ON l.loan_id = i.loan_id
               WHERE i.status IN ('DUE','LATE') AND i.due_date <= SYSDATE
                 AND (i.last_try IS NULL OR i.last_try < TRUNC(SYSDATE))) LOOP
      BEGIN
        l_ref := collect(x.loan_id, x.inst_no, TRUE);
        COMMIT;
        l_n := l_n + 1;
      EXCEPTION WHEN OTHERS THEN
        ROLLBACK;
        UPDATE wlt_bnpl_installments SET status = 'LATE', last_try = SYSDATE WHERE loan_id = x.loan_id AND inst_no = x.inst_no;
        wallet_social_pkg.notify(x.user_id, 'BNPL', '⏰ قسط ' || money(x.amount) || ' د.أ لم يُخصم',
          'رصيدك لا يكفي. اشحن وسدّد من «ادفع لاحقاً»، بدون أي غرامة', 18);
        COMMIT;
      END;
    END LOOP;
    RETURN l_n;
  END run_due;

END wallet_bnpl_pkg;

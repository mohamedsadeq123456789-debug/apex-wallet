-- =====================================================================
-- الربط مع طابور الأحداث (الجلسة 7): مدفوعات التجار تمر على النقاط والكاش باك
-- =====================================================================
CREATE OR REPLACE TRIGGER wlt_txn_rules_trg
  AFTER UPDATE OF status ON wlt_transactions
  FOR EACH ROW
  WHEN (NEW.status = 'COMPLETED' AND OLD.status = 'PENDING'
        AND NEW.txn_type NOT IN ('SAVE','SAVE_OUT','ROUNDUP','FEE','REVERSAL','FX','CASHBACK','REWARD','BNPL_PAY','BNPL_REPAY'))
BEGIN
  INSERT INTO wlt_rule_events (txn_id)
  SELECT :NEW.txn_id FROM dual
   WHERE :NEW.txn_type IN ('MERCHANT_PAY','BILL_PAY','RECHARGE')
      OR EXISTS (SELECT 1 FROM wlt_wallets w JOIN wlt_smart_rules r ON r.user_id = w.user_id AND r.is_active = 'Y'
                  WHERE w.wallet_type = 'MAIN' AND w.wallet_id IN (:NEW.from_wallet_id, :NEW.to_wallet_id))
      OR EXISTS (SELECT 1 FROM wlt_wallets w JOIN wlt_child_links c ON c.child_user_id = w.user_id
                  WHERE w.wallet_type = 'MAIN' AND w.wallet_id = :NEW.from_wallet_id);
END;

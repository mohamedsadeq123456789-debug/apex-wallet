  FUNCTION quote (p_from VARCHAR2, p_to VARCHAR2, p_amount NUMBER) RETURN NUMBER;
  FUNCTION wallet_of (p_user_id NUMBER, p_cur VARCHAR2, p_create BOOLEAN DEFAULT FALSE) RETURN NUMBER;

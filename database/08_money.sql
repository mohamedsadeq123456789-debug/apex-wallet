  PROCEDURE set_rate (p_admin_phone VARCHAR2, p_cur VARCHAR2, p_per_jod NUMBER);
END wallet_fx_pkg;
/

CREATE OR REPLACE PACKAGE BODY wallet_fx_pkg AS

  PROCEDURE fail (p_msg VARCHAR2) IS BEGIN RAISE_APPLICATION_ERROR(c_err, p_msg); END;

  FUNCTION rate (p_cur VARCHAR2) RETURN NUMBER IS
    l NUMBER;
  BEGIN
    SELECT per_jod INTO l FROM wlt_fx_rates WHERE currency_code = p_cur;
    RETURN l;
  EXCEPTION WHEN NO_DATA_FOUND THEN fail('العملة غير مدعومة'); RETURN NULL;
  END rate;

  FUNCTION decs (p_cur VARCHAR2) RETURN NUMBER IS
    l NUMBER;
  BEGIN
    SELECT decimals INTO l FROM wlt_currencies WHERE currency_code = p_cur;
    RETURN l;
  END decs;

  FUNCTION spread RETURN NUMBER IS
    l NUMBER;
  BEGIN
    SELECT TO_NUMBER(setting_value, '990D99', 'NLS_NUMERIC_CHARACTERS=''.,''') INTO l FROM wlt_app_settings WHERE setting_key = 'FX_SPREAD_PCT';
    RETURN l / 100;
  END spread;

  -- عبر الدينار دائماً: من → دينار → إلى، ناقص هامش الصرافة، مقرّباً لأسفل لخانات العملة
  FUNCTION quote (p_from VARCHAR2, p_to VARCHAR2, p_amount NUMBER) RETURN NUMBER IS
  BEGIN
    IF p_from = p_to THEN fail('اختر عملتين مختلفتين'); END IF;
    RETURN TRUNC(p_amount / rate(p_from) * rate(p_to) * (1 - spread), decs(p_to));
  END quote;

  FUNCTION wallet_of (p_user_id NUMBER, p_cur VARCHAR2, p_create BOOLEAN DEFAULT FALSE) RETURN NUMBER IS
    l NUMBER;
  BEGIN
    IF p_cur = 'JOD' THEN
      SELECT wallet_id INTO l FROM wlt_wallets WHERE user_id = p_user_id AND wallet_type = 'MAIN' AND currency_code = 'JOD';
    ELSE
      SELECT MAX(wallet_id) INTO l FROM wlt_wallets WHERE user_id = p_user_id AND wallet_type = 'FX' AND currency_code = p_cur;
      IF l IS NULL AND p_create THEN
        INSERT INTO wlt_wallets (user_id, wallet_type, currency_code, label)
        VALUES (p_user_id, 'FX', p_cur, 'محفظة ' || p_cur) RETURNING wallet_id INTO l;
      END IF;
    END IF;
    RETURN l;
  END wallet_of;

  FUNCTION sys_wallet (p_cur VARCHAR2) RETURN NUMBER IS
    l NUMBER;
  BEGIN
    SELECT TO_NUMBER(setting_value) INTO l FROM wlt_app_settings WHERE setting_key = 'FX_WALLET_' || p_cur;
    RETURN l;
  END sys_wallet;

  FUNCTION exchange (p_phone VARCHAR2, p_from VARCHAR2, p_to VARCHAR2, p_amount NUMBER, p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
    l_u   NUMBER;
    l_fw  NUMBER;
    l_tw  NUMBER;
    l_out NUMBER;
    l_ref VARCHAR2(20);
    l_r2  VARCHAR2(20);
  BEGIN
    IF p_idem IS NOT NULL THEN
      SELECT MAX(txn_ref) INTO l_ref FROM wlt_transactions WHERE idempotency_key = p_idem || '-A';
      IF l_ref IS NOT NULL THEN RETURN l_ref; END IF;
    END IF;
    SELECT user_id INTO l_u FROM wlt_users WHERE phone = p_phone AND user_type <> 'SYSTEM';
    IF wallet_family_pkg.is_child(l_u) THEN fail('الصرافة غير متاحة لمحافظ الأبناء'); END IF;
    IF p_amount IS NULL OR p_amount <= 0 OR p_amount <> ROUND(p_amount, decs(p_from)) THEN
      fail('المبلغ بخانات عشرية أكثر من المسموح لهذه العملة');
    END IF;
    l_out := quote(p_from, p_to, p_amount);
    IF l_out <= 0 THEN fail('المبلغ صغير جداً'); END IF;
    l_fw := wallet_of(l_u, p_from);
    IF l_fw IS NULL THEN fail('ليس لديك رصيد بهذه العملة'); END IF;
    l_tw := wallet_of(l_u, p_to, TRUE);

    -- ساقان في معاملة واحدة: لا يمكن أن تُخصم عملة دون أن تصل الأخرى
    l_ref := wallet_core_pkg.transfer(p_from_wallet => l_fw, p_to_wallet => sys_wallet(p_from), p_amount => p_amount,
               p_txn_type => 'FX', p_idem_key => CASE WHEN p_idem IS NOT NULL THEN p_idem || '-A' END,
               p_description => p_from || ' → ' || p_to, p_commit => FALSE);
    l_r2 := wallet_core_pkg.transfer(p_from_wallet => sys_wallet(p_to), p_to_wallet => l_tw, p_amount => l_out,
               p_txn_type => 'FX', p_idem_key => CASE WHEN p_idem IS NOT NULL THEN p_idem || '-B' END,
               p_description => p_from || ' → ' || p_to || ' · ' || l_ref, p_actor_user => l_u, p_commit => FALSE);
    COMMIT;
    RETURN l_ref;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END exchange;

  PROCEDURE set_rate (p_admin_phone VARCHAR2, p_cur VARCHAR2, p_per_jod NUMBER) IS
    l_t VARCHAR2(10);
  BEGIN
    SELECT user_type INTO l_t FROM wlt_users WHERE phone = p_admin_phone;
    IF l_t <> 'ADMIN' THEN fail('للإدارة فقط'); END IF;
    IF p_cur = 'JOD' OR p_per_jod IS NULL OR p_per_jod <= 0 THEN fail('سعر غير صالح'); END IF;
    UPDATE wlt_fx_rates SET per_jod = p_per_jod, updated_at = SYSTIMESTAMP WHERE currency_code = p_cur;
    IF SQL%ROWCOUNT = 0 THEN fail('العملة غير مدعومة'); END IF;
    INSERT INTO wlt_fx_history (currency_code, per_jod) VALUES (p_cur, p_per_jod);
    COMMIT;
  END set_rate;

END wallet_fx_pkg;

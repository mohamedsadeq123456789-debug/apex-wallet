CREATE OR REPLACE PACKAGE BODY wallet_reward_pkg AS

  PROCEDURE fail (p_msg VARCHAR2) IS BEGIN RAISE_APPLICATION_ERROR(c_err, p_msg); END;

  FUNCTION balance_of (p_user_id NUMBER) RETURN NUMBER IS
    l NUMBER;
  BEGIN
    SELECT NVL(SUM(points), 0) INTO l FROM wlt_points_ledger WHERE user_id = p_user_id;
    RETURN l;
  END balance_of;

  FUNCTION earned_90 (p_user_id NUMBER) RETURN NUMBER IS
    l NUMBER;
  BEGIN
    SELECT NVL(SUM(points), 0) INTO l FROM wlt_points_ledger
     WHERE user_id = p_user_id AND reason IN ('EARN','BONUS') AND created_at >= SYSDATE - 90;
    RETURN l;
  END earned_90;

  FUNCTION level_of (p_user_id NUMBER) RETURN VARCHAR2 IS
    l NUMBER := earned_90(p_user_id);
  BEGIN
    RETURN CASE WHEN l >= 200 THEN 'GOLD' WHEN l >= 50 THEN 'SILVER' ELSE 'BRONZE' END;
  END level_of;

  -- كل دينار مدفوع لتاجر أو فاتورة = نقطة، مضروبة بمعامل المستوى. والكاش باك فوري من عروض التجار
  PROCEDURE on_txn (p_txn_id NUMBER) IS
    t     wlt_transactions%ROWTYPE;
    l_u   NUMBER;
    l_t   VARCHAR2(10);
    l_mu  NUMBER;
    l_pts NUMBER;
    l_cb  NUMBER;
    l_rw  NUMBER;
    l_ref VARCHAR2(20);
  BEGIN
    SELECT * INTO t FROM wlt_transactions WHERE txn_id = p_txn_id;
    IF t.status <> 'COMPLETED' OR t.txn_type NOT IN ('MERCHANT_PAY','BILL_PAY','RECHARGE') THEN RETURN; END IF;
    SELECT w.user_id, w.wallet_type INTO l_u, l_t FROM wlt_wallets w WHERE w.wallet_id = t.from_wallet_id;
    IF l_t <> 'MAIN' THEN RETURN; END IF;
    SELECT user_id INTO l_mu FROM wlt_wallets WHERE wallet_id = t.to_wallet_id;

    l_pts := FLOOR(t.amount * CASE level_of(l_u) WHEN 'GOLD' THEN 1.5 WHEN 'SILVER' THEN 1.25 ELSE 1 END);
    IF l_pts > 0 THEN
      BEGIN
        INSERT INTO wlt_points_ledger (user_id, points, reason, note, txn_id)
        VALUES (l_u, l_pts, 'EARN', NVL(t.description, 'دفع ' || t.txn_ref), t.txn_id);
      EXCEPTION WHEN DUP_VAL_ON_INDEX THEN NULL;
      END;
    END IF;

    IF t.txn_type = 'MERCHANT_PAY' THEN
      FOR o IN (SELECT * FROM wlt_cashback_offers
                 WHERE merchant_user_id = l_mu AND is_active = 'Y' AND SYSDATE BETWEEN starts_at AND ends_at + 1
                 ORDER BY pct DESC FETCH FIRST 1 ROWS ONLY) LOOP
        l_cb := LEAST(TRUNC(t.amount * o.pct / 100, 3), o.max_amount);
        IF l_cb >= 0.001 THEN
          SELECT TO_NUMBER(setting_value) INTO l_rw FROM wlt_app_settings WHERE setting_key = 'REWARDS_WALLET_ID';
          BEGIN
            l_ref := wallet_core_pkg.transfer(p_from_wallet => l_rw, p_to_wallet => t.from_wallet_id, p_amount => l_cb,
                       p_txn_type => 'CASHBACK', p_idem_key => 'CB-' || t.txn_id,
                       p_description => o.title, p_actor_user => l_u, p_commit => FALSE);
          EXCEPTION WHEN OTHERS THEN NULL;   -- مثلاً تجاوز أقصى رصيد: نتجاوز الكاش باك بصمت
          END;
        END IF;
      END LOOP;
    END IF;
  END on_txn;

  FUNCTION redeem (p_phone VARCHAR2, p_points NUMBER, p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
    l_u   NUMBER;
    l_w   NUMBER;
    l_rw  NUMBER;
    l_ref VARCHAR2(20);
    l_b   NUMBER;
  BEGIN
    IF p_idem IS NOT NULL THEN
      SELECT MAX(txn_ref) INTO l_ref FROM wlt_transactions WHERE idempotency_key = p_idem;
      IF l_ref IS NOT NULL THEN RETURN l_ref; END IF;
    END IF;
    SELECT u.user_id, w.wallet_id INTO l_u, l_w FROM wlt_users u
      JOIN wlt_wallets w ON w.user_id = u.user_id AND w.wallet_type = 'MAIN' AND w.currency_code = 'JOD'
     WHERE u.phone = p_phone
       FOR UPDATE OF w.balance;   -- يمنع استبدال نفس النقاط مرتين بالتوازي
    IF p_points IS NULL OR p_points < c_points_per_jod OR MOD(p_points, c_points_per_jod) <> 0 THEN
      fail('الاستبدال بمضاعفات ' || c_points_per_jod || ' نقطة');
    END IF;
    l_b := balance_of(l_u);
    IF p_points > l_b THEN fail('رصيد نقاطك ' || l_b || ' فقط'); END IF;
    SELECT TO_NUMBER(setting_value) INTO l_rw FROM wlt_app_settings WHERE setting_key = 'REWARDS_WALLET_ID';
    l_ref := wallet_core_pkg.transfer(p_from_wallet => l_rw, p_to_wallet => l_w, p_amount => p_points / c_points_per_jod,
               p_txn_type => 'REWARD', p_idem_key => p_idem, p_description => 'استبدال ' || p_points || ' نقطة',
               p_actor_user => l_u, p_commit => FALSE);
    INSERT INTO wlt_points_ledger (user_id, points, reason, note, txn_id)
    VALUES (l_u, -p_points, 'REDEEM', 'استبدال برصيد', (SELECT txn_id FROM wlt_transactions WHERE txn_ref = l_ref));
    COMMIT;
    RETURN l_ref;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END redeem;

END wallet_reward_pkg;

CREATE OR REPLACE PACKAGE wallet_sms_pkg AS
  FUNCTION send (p_phone VARCHAR2, p_body VARCHAR2) RETURN NUMBER;
  FUNCTION is_demo RETURN BOOLEAN;
END wallet_sms_pkg;
/

CREATE OR REPLACE PACKAGE BODY wallet_sms_pkg AS
  FUNCTION setting (p_key VARCHAR2) RETURN VARCHAR2 IS
    l VARCHAR2(400);
  BEGIN
    SELECT setting_value INTO l FROM wlt_app_settings WHERE setting_key = p_key;
    RETURN l;
  EXCEPTION WHEN NO_DATA_FOUND THEN RETURN NULL;
  END setting;

  FUNCTION is_demo RETURN BOOLEAN IS
  BEGIN
    RETURN NVL(setting('SMS_MODE'), 'DEMO') <> 'LIVE';
  END is_demo;

  FUNCTION send (p_phone VARCHAR2, p_body VARCHAR2) RETURN NUMBER IS
    l_id   NUMBER;
    l_resp CLOB;
    l_stat VARCHAR2(10);
    l_code NUMBER;
    l_info VARCHAR2(400);
  BEGIN
    INSERT INTO wlt_sms_outbox (phone, body) VALUES (p_phone, SUBSTR(p_body, 1, 400))
    RETURNING sms_id INTO l_id;

    IF is_demo THEN
      UPDATE wlt_sms_outbox SET status = 'DEMO', sent_at = SYSTIMESTAMP WHERE sms_id = l_id;
      RETURN l_id;
    END IF;

    BEGIN
      apex_web_service.g_request_headers.DELETE;
      apex_web_service.g_request_headers(1).name  := 'Content-Type';
      apex_web_service.g_request_headers(1).value := 'application/x-www-form-urlencoded';
      l_resp := apex_web_service.make_rest_request(
                  p_url                  => setting('SMS_PROVIDER_URL'),
                  p_http_method          => 'POST',
                  p_body                 => 'To=' || UTL_URL.ESCAPE('+962' || SUBSTR(p_phone, 2), TRUE)
                                         || '&From=' || UTL_URL.ESCAPE(setting('SMS_FROM'), TRUE)
                                         || '&Body=' || UTL_URL.ESCAPE(p_body, TRUE, 'AL32UTF8'),
                  p_credential_static_id => 'WLT_SMS');
      -- متغيرات الحزم و SQLERRM لا تُستخدم داخل SQL مباشرة، لذلك ننسخها لمتغيرات أولاً
      l_code := apex_web_service.g_status_code;
      l_stat := CASE WHEN l_code BETWEEN 200 AND 299 THEN 'SENT' ELSE 'FAILED' END;
      l_info := SUBSTR(l_code || ' ' || DBMS_LOB.SUBSTR(l_resp, 300, 1), 1, 400);
    EXCEPTION WHEN OTHERS THEN
      l_stat := 'FAILED';
      l_info := SUBSTR(SQLERRM, 1, 400);
    END;
    UPDATE wlt_sms_outbox SET status = l_stat, sent_at = SYSTIMESTAMP, provider_ref = l_info WHERE sms_id = l_id;
    RETURN l_id;
  END send;
END wallet_sms_pkg;
/


CREATE OR REPLACE PACKAGE wallet_otp_pkg AS
  c_err CONSTANT PLS_INTEGER := -20150;
  FUNCTION normalize_phone (p VARCHAR2) RETURN VARCHAR2;
  FUNCTION sha (p VARCHAR2) RETURN VARCHAR2;
  PROCEDURE request_code (p_phone VARCHAR2, p_purpose VARCHAR2, p_demo_code OUT VARCHAR2, p_sms OUT VARCHAR2);
  FUNCTION verify_code (p_phone VARCHAR2, p_purpose VARCHAR2, p_code VARCHAR2) RETURN VARCHAR2;
  PROCEDURE register (p_phone VARCHAR2, p_ticket VARCHAR2, p_name VARCHAR2, p_pin VARCHAR2);
  PROCEDURE reset_pin (p_phone VARCHAR2, p_ticket VARCHAR2, p_pin VARCHAR2);
  PROCEDURE api;
END wallet_otp_pkg;
/

CREATE OR REPLACE PACKAGE BODY wallet_otp_pkg AS
  c_ttl_min      CONSTANT PLS_INTEGER := 5;
  c_max_attempts CONSTANT PLS_INTEGER := 5;
  c_resend_sec   CONSTANT PLS_INTEGER := 60;
  c_max_per_hour CONSTANT PLS_INTEGER := 5;

  PROCEDURE fail (p_msg VARCHAR2) IS BEGIN RAISE_APPLICATION_ERROR(c_err, p_msg); END;

  FUNCTION sha (p VARCHAR2) RETURN VARCHAR2 IS
    l VARCHAR2(64);
  BEGIN
    SELECT RAWTOHEX(STANDARD_HASH(p, 'SHA256')) INTO l FROM dual;
    RETURN l;
  END sha;

  -- يقبل: 0791234567 · 791234567 · +962791234567 · 00962 79 123 4567 · ٠٧٩١٢٣٤٥٦٧
  FUNCTION normalize_phone (p VARCHAR2) RETURN VARCHAR2 IS
    l VARCHAR2(40) := TRANSLATE(p, '٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹', '01234567890123456789');
  BEGIN
    l := REGEXP_REPLACE(l, '[^0-9]', '');
    IF l LIKE '00962%' THEN l := SUBSTR(l, 6);
    ELSIF l LIKE '962%' AND LENGTH(l) = 12 THEN l := SUBSTR(l, 4);
    END IF;
    IF LENGTH(l) = 9 AND l LIKE '7%' THEN l := '0' || l; END IF;
    RETURN CASE WHEN REGEXP_LIKE(l, '^07[789][0-9]{7}$') THEN l END;
  END normalize_phone;

  FUNCTION phone_ok (p VARCHAR2) RETURN VARCHAR2 IS
    l VARCHAR2(15) := normalize_phone(p);
  BEGIN
    IF l IS NULL THEN fail('رقم الهاتف غير صحيح. مثال: 079 123 4567'); END IF;
    RETURN l;
  END phone_ok;

  FUNCTION registered (p_phone VARCHAR2) RETURN BOOLEAN IS
    n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM wlt_users WHERE phone = p_phone;
    RETURN n > 0;
  END registered;

  PROCEDURE check_pin (p_pin VARCHAR2) IS
  BEGIN
    IF NOT REGEXP_LIKE(NVL(p_pin, 'x'), '^[0-9]{4}$') THEN fail('الرمز السري 4 أرقام'); END IF;
    IF REGEXP_LIKE(p_pin, '^(.)\1{3}$') OR p_pin IN ('1234','4321','0123','3210','2345','5432','6789','9876','1212','2580') THEN
      fail('هذا الرمز سهل التخمين، اختر رمزاً آخر');
    END IF;
  END check_pin;

  PROCEDURE request_code (p_phone VARCHAR2, p_purpose VARCHAR2, p_demo_code OUT VARCHAR2, p_sms OUT VARCHAR2) IS
    l_phone VARCHAR2(15) := phone_ok(p_phone);
    l_last  TIMESTAMP;
    l_n     NUMBER;
    l_code  VARCHAR2(6);
    l_sms   NUMBER;
    l_wait  NUMBER;
  BEGIN
    IF p_purpose = 'REGISTER' AND registered(l_phone) THEN
      fail('هذا الرقم مسجّل مسبقاً. ادخل به، أو استخدم «نسيت الرمز»');
    ELSIF p_purpose = 'RESET' AND NOT registered(l_phone) THEN
      fail('هذا الرقم غير مسجّل. أنشئ حساباً جديداً');
    ELSIF p_purpose NOT IN ('REGISTER','RESET') THEN
      fail('طلب غير صالح');
    END IF;

    SELECT MAX(created_at), COUNT(CASE WHEN created_at > SYSTIMESTAMP - INTERVAL '1' HOUR THEN 1 END)
      INTO l_last, l_n
      FROM wlt_otp_codes WHERE phone = l_phone;
    IF l_n >= c_max_per_hour THEN fail('طلبت رموزاً كثيرة. حاول بعد ساعة'); END IF;
    IF l_last > SYSTIMESTAMP - NUMTODSINTERVAL(c_resend_sec, 'SECOND') THEN
      l_wait := c_resend_sec - ROUND((CAST(SYSTIMESTAMP AS DATE) - CAST(l_last AS DATE)) * 86400);
      fail('انتظر ' || GREATEST(l_wait, 1) || ' ثانية قبل طلب رمز جديد');
    END IF;

    UPDATE wlt_otp_codes SET status = 'REPLACED'
     WHERE phone = l_phone AND purpose = p_purpose AND status IN ('SENT','VERIFIED');

    l_code := LPAD(TRUNC(DBMS_RANDOM.VALUE(0, 1000000)), 6, '0');
    p_sms := 'محفظتي: رمز ' || CASE p_purpose WHEN 'REGISTER' THEN 'التفعيل' ELSE 'استعادة الحساب' END
          || ' ' || l_code || '. صالح ' || c_ttl_min || ' دقائق. لا تشاركه مع أي شخص.';
    l_sms := wallet_sms_pkg.send(l_phone, p_sms);
    INSERT INTO wlt_otp_codes (phone, purpose, code_hash, expires_at, sms_id)
    VALUES (l_phone, p_purpose, sha(l_phone || ':' || p_purpose || ':' || l_code),
            SYSTIMESTAMP + NUMTODSINTERVAL(c_ttl_min, 'MINUTE'), l_sms);
    COMMIT;
    p_demo_code := CASE WHEN wallet_sms_pkg.is_demo THEN l_code END;
    IF NOT wallet_sms_pkg.is_demo THEN p_sms := NULL; END IF;
  END request_code;

  FUNCTION verify_code (p_phone VARCHAR2, p_purpose VARCHAR2, p_code VARCHAR2) RETURN VARCHAR2 IS
    l_phone  VARCHAR2(15) := phone_ok(p_phone);
    l_o      wlt_otp_codes%ROWTYPE;
    l_ticket VARCHAR2(32) := DBMS_RANDOM.STRING('X', 32);
  BEGIN
    BEGIN
      SELECT * INTO l_o FROM wlt_otp_codes
       WHERE otp_id = (SELECT MAX(otp_id) FROM wlt_otp_codes WHERE phone = l_phone AND purpose = p_purpose AND status = 'SENT')
         FOR UPDATE;
    EXCEPTION WHEN NO_DATA_FOUND THEN
      fail('اطلب رمزاً جديداً');
    END;
    IF l_o.expires_at < SYSTIMESTAMP THEN fail('انتهت صلاحية الرمز. اطلب رمزاً جديداً'); END IF;

    IF sha(l_phone || ':' || p_purpose || ':' || REGEXP_REPLACE(p_code, '[^0-9]', '')) <> l_o.code_hash THEN
      UPDATE wlt_otp_codes
         SET attempts = attempts + 1,
             status = CASE WHEN attempts + 1 >= c_max_attempts THEN 'BLOCKED' ELSE status END
       WHERE otp_id = l_o.otp_id;
      COMMIT;
      IF l_o.attempts + 1 >= c_max_attempts THEN fail('محاولات كثيرة خاطئة. اطلب رمزاً جديداً'); END IF;
      fail('الرمز غير صحيح. بقيت ' || (c_max_attempts - l_o.attempts - 1) || ' محاولات');
    END IF;

    UPDATE wlt_otp_codes
       SET status = 'VERIFIED', ticket_hash = sha(l_ticket), expires_at = SYSTIMESTAMP + INTERVAL '10' MINUTE
     WHERE otp_id = l_o.otp_id;
    COMMIT;
    RETURN l_ticket;
  END verify_code;

  FUNCTION use_ticket (p_phone VARCHAR2, p_purpose VARCHAR2, p_ticket VARCHAR2) RETURN NUMBER IS
    l_id NUMBER;
    l_h  VARCHAR2(64) := sha(p_ticket);
  BEGIN
    SELECT otp_id INTO l_id FROM wlt_otp_codes
     WHERE phone = p_phone AND purpose = p_purpose AND status = 'VERIFIED'
       AND ticket_hash = l_h AND expires_at > SYSTIMESTAMP
       FOR UPDATE;
    UPDATE wlt_otp_codes SET status = 'USED' WHERE otp_id = l_id;
    RETURN l_id;
  EXCEPTION WHEN NO_DATA_FOUND THEN
    fail('انتهت الجلسة. ابدأ من جديد');
    RETURN NULL;
  END use_ticket;

  PROCEDURE register (p_phone VARCHAR2, p_ticket VARCHAR2, p_name VARCHAR2, p_pin VARCHAR2) IS
    l_phone VARCHAR2(15) := phone_ok(p_phone);
    l_id    NUMBER;
    l_salt  VARCHAR2(16) := DBMS_RANDOM.STRING('X', 16);
    l_uid   NUMBER;
    l_name  VARCHAR2(60) := SUBSTR(TRIM(REGEXP_REPLACE(p_name, '[<>"]', '')), 1, 60);
  BEGIN
    check_pin(p_pin);
    l_id := use_ticket(l_phone, 'REGISTER', p_ticket);
    IF registered(l_phone) THEN fail('هذا الرقم مسجّل مسبقاً'); END IF;
    INSERT INTO wlt_users (phone, display_name, user_type, kyc_tier, pin_hash, pin_salt)
    VALUES (l_phone, l_name, 'CUSTOMER', 'BASIC', sha(l_salt || p_pin), l_salt)
    RETURNING user_id INTO l_uid;
    INSERT INTO wlt_wallets (user_id, wallet_type, label) VALUES (l_uid, 'MAIN', 'المحفظة الرئيسية');
    INSERT INTO wlt_audit_log (actor_user_id, action, entity, entity_id, details)
    VALUES (l_uid, 'REGISTER', 'USER', l_uid, 'تسجيل برمز تفعيل');
    wallet_social_pkg.notify(l_uid, 'WELCOME', 'أهلاً بك في المحفظة 👋',
      'حسابك جاهز. اشحن رصيدك من أي وكيل وابدأ التحويل والدفع.', 1);
    COMMIT;
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
  END register;

  PROCEDURE reset_pin (p_phone VARCHAR2, p_ticket VARCHAR2, p_pin VARCHAR2) IS
    l_phone VARCHAR2(15) := phone_ok(p_phone);
    l_id    NUMBER;
    l_salt  VARCHAR2(16) := DBMS_RANDOM.STRING('X', 16);
    l_uid   NUMBER;
  BEGIN
    check_pin(p_pin);
    l_id := use_ticket(l_phone, 'RESET', p_ticket);
    UPDATE wlt_users SET pin_salt = l_salt, pin_hash = sha(l_salt || p_pin), failed_pin_attempts = 0, locked_until = NULL
     WHERE phone = l_phone AND user_type <> 'SYSTEM'
    RETURNING user_id INTO l_uid;
    INSERT INTO wlt_audit_log (actor_user_id, action, entity, entity_id, details)
    VALUES (l_uid, 'PIN_RESET', 'USER', l_uid, 'تغيير الرمز برمز تفعيل');
    wallet_social_pkg.notify(l_uid, 'SECURITY', 'تمّ تغيير رمزك السري',
      'إذا لم تكن أنت، تواصل مع الدعم فوراً.', 1);
    COMMIT;
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
  END reset_pin;

  -- عملية Ajax عامة (قبل تسجيل الدخول)
  PROCEDURE api IS
    a      VARCHAR2(20)  := apex_application.g_x01;
    l_ph   VARCHAR2(15);
    l_code VARCHAR2(10);
    l_sms  VARCHAR2(400);
    l_t    VARCHAR2(40);
    l_msg  VARCHAR2(4000);
  BEGIN
    l_ph := phone_ok(apex_application.g_x02);
    CASE a
      WHEN 'send'     THEN request_code(l_ph, apex_application.g_x03, l_code, l_sms);
      WHEN 'verify'   THEN l_t := verify_code(l_ph, apex_application.g_x03, apex_application.g_x04);
      WHEN 'register' THEN register(l_ph, apex_application.g_x03, apex_application.g_x04, apex_application.g_x05);
      WHEN 'reset'    THEN reset_pin(l_ph, apex_application.g_x03, apex_application.g_x05);
      ELSE fail('طلب غير صالح');
    END CASE;
    -- لا نكتب أي JSON إلا بعد نجاح العملية كاملة
    apex_json.open_object;
    apex_json.write('ok', TRUE);
    apex_json.write('phone', l_ph);
    IF a = 'send' THEN
      apex_json.write('demo', l_code IS NOT NULL);
      IF l_code IS NOT NULL THEN
        apex_json.write('code', l_code);
        apex_json.write('sms', l_sms);
      END IF;
    ELSIF a = 'verify' THEN
      apex_json.write('ticket', l_t);
    END IF;
    apex_json.close_object;
  EXCEPTION WHEN OTHERS THEN
    l_msg := CASE WHEN SQLCODE BETWEEN -20999 AND -20000
                  THEN REGEXP_REPLACE(REGEXP_SUBSTR(SQLERRM, '^[^' || CHR(10) || ']+'), '^ORA-\d+: ', '')
                  ELSE 'حدث خطأ غير متوقع، حاول مرة أخرى' END;
    apex_json.open_object;
    apex_json.write('ok', FALSE);
    apex_json.write('msg', l_msg);
    apex_json.close_object;
  END api;
END wallet_otp_pkg;

-- =====================================================================
--  محفظتي · الجلسة 6 · تسجيل أي رقم برمز تفعيل SMS + نسيت الرمز
--  الرسائل تمر من صندوق صادر (outbox). وضع التجربة يعرض الرمز على الشاشة،
--  ووضع LIVE يرسله عبر مزوّد SMS (مثل Twilio) باستخدام Web Credential اسمها WLT_SMS
-- =====================================================================

CREATE TABLE wlt_sms_outbox (
  sms_id        NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_sms PRIMARY KEY,
  phone         VARCHAR2(15)  NOT NULL,
  body          VARCHAR2(400) NOT NULL,
  status        VARCHAR2(10)  DEFAULT 'QUEUED' NOT NULL
                CONSTRAINT ck_wlt_sms_status CHECK (status IN ('QUEUED','SENT','FAILED','DEMO')),
  provider_ref  VARCHAR2(400),
  created_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  sent_at       TIMESTAMP
);
CREATE INDEX ix_wlt_sms_phone ON wlt_sms_outbox (phone, created_at);

CREATE TABLE wlt_otp_codes (
  otp_id       NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_otp PRIMARY KEY,
  phone        VARCHAR2(15)  NOT NULL,
  purpose      VARCHAR2(10)  NOT NULL CONSTRAINT ck_wlt_otp_purpose CHECK (purpose IN ('REGISTER','RESET')),
  code_hash    VARCHAR2(64)  NOT NULL,
  attempts     NUMBER(2)     DEFAULT 0 NOT NULL,
  expires_at   TIMESTAMP     NOT NULL,
  status       VARCHAR2(10)  DEFAULT 'SENT' NOT NULL
               CONSTRAINT ck_wlt_otp_status CHECK (status IN ('SENT','VERIFIED','USED','BLOCKED','REPLACED')),
  ticket_hash  VARCHAR2(64),
  sms_id       NUMBER        CONSTRAINT fk_wlt_otp_sms REFERENCES wlt_sms_outbox,
  created_at   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_wlt_otp_phone ON wlt_otp_codes (phone, purpose, created_at);
CREATE INDEX ix_wlt_otp_sms   ON wlt_otp_codes (sms_id);


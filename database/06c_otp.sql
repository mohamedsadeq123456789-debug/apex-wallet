-- الدخول يقبل الرقم بأي صيغة
DECLARE
  l CLOB;
  c_old CONSTANT VARCHAR2(100) := 'WHERE phone = TRIM(p_username) AND user_type <> ''SYSTEM''';
  c_new CONSTANT VARCHAR2(200) := 'WHERE phone = NVL(l_phone, TRIM(p_username)) AND user_type <> ''SYSTEM''';
BEGIN
  FOR r IN (SELECT text FROM user_source WHERE name = 'WALLET_AUTH_PKG' AND type = 'PACKAGE BODY' ORDER BY line) LOOP
    l := l || r.text;
  END LOOP;
  IF INSTR(l, c_new) = 0 THEN
    l := REPLACE(l, c_old, c_new);
    l := REPLACE(l, '    l_left  PLS_INTEGER;', '    l_left  PLS_INTEGER;' || CHR(10) || '    l_phone VARCHAR2(15) := wallet_otp_pkg.normalize_phone(p_username);');
    EXECUTE IMMEDIATE 'CREATE OR REPLACE ' || l;
  END IF;
END;

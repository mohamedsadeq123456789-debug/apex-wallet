CREATE TABLE wlt_merchant_profiles (
  user_id        NUMBER        CONSTRAINT pk_wlt_merch PRIMARY KEY
                 CONSTRAINT fk_wlt_merch_user REFERENCES wlt_users,
  merchant_code  VARCHAR2(10)  NOT NULL CONSTRAINT uq_wlt_merch_code UNIQUE,
  category       VARCHAR2(30)  NOT NULL,
  created_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

-- QR ديناميكي: التاجر يولّد كوداً بمبلغ محدد، يُستخدم مرة واحدة وينتهي بعد دقائق
CREATE TABLE wlt_qr_codes (
  qr_id             NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_qr PRIMARY KEY,
  token             VARCHAR2(32)  NOT NULL CONSTRAINT uq_wlt_qr_token UNIQUE,
  merchant_user_id  NUMBER        NOT NULL CONSTRAINT fk_wlt_qr_user REFERENCES wlt_users,
  amount            NUMBER(15,3)  CONSTRAINT ck_wlt_qr_amount CHECK (amount IS NULL OR amount > 0),
  note              VARCHAR2(100),
  expires_at        TIMESTAMP     NOT NULL,
  status            VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL
                    CONSTRAINT ck_wlt_qr_status CHECK (status IN ('ACTIVE','USED','CANCELLED')),
  paid_txn_id       NUMBER        CONSTRAINT fk_wlt_qr_txn REFERENCES wlt_transactions,
  paid_by           NUMBER        CONSTRAINT fk_wlt_qr_payer REFERENCES wlt_users,
  created_at        TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_wlt_qr_merchant ON wlt_qr_codes (merchant_user_id, created_at);
CREATE INDEX ix_wlt_qr_txn      ON wlt_qr_codes (paid_txn_id);
CREATE INDEX ix_wlt_qr_payer    ON wlt_qr_codes (paid_by);

CREATE TABLE wlt_billers (
  biller_code  VARCHAR2(20)  CONSTRAINT pk_wlt_billers PRIMARY KEY,
  name_ar      VARCHAR2(60)  NOT NULL,
  category     VARCHAR2(20)  NOT NULL
               CONSTRAINT ck_wlt_biller_cat CHECK (category IN ('ELECTRICITY','WATER','INTERNET','TELECOM')),
  pay_mode     VARCHAR2(10)  NOT NULL
               CONSTRAINT ck_wlt_biller_mode CHECK (pay_mode IN ('BILLS','OPEN')),
  account_hint VARCHAR2(60),
  user_id      NUMBER        NOT NULL CONSTRAINT fk_wlt_biller_user REFERENCES wlt_users,
  sort_order   NUMBER(3)     DEFAULT 1 NOT NULL
);
CREATE INDEX ix_wlt_biller_user ON wlt_billers (user_id);

CREATE TABLE wlt_bills (
  bill_id      NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_bills PRIMARY KEY,
  biller_code  VARCHAR2(20)  NOT NULL CONSTRAINT fk_wlt_bills_biller REFERENCES wlt_billers,
  account_no   VARCHAR2(20)  NOT NULL,
  period_ar    VARCHAR2(30)  NOT NULL,
  amount       NUMBER(15,3)  NOT NULL CONSTRAINT ck_wlt_bills_amount CHECK (amount > 0),
  due_date     DATE          NOT NULL,
  status       VARCHAR2(10)  DEFAULT 'UNPAID' NOT NULL
               CONSTRAINT ck_wlt_bills_status CHECK (status IN ('UNPAID','PAID')),
  paid_txn_id  NUMBER        CONSTRAINT fk_wlt_bills_txn REFERENCES wlt_transactions,
  paid_by      NUMBER        CONSTRAINT fk_wlt_bills_payer REFERENCES wlt_users,
  paid_at      TIMESTAMP
);
CREATE INDEX ix_wlt_bills_acct  ON wlt_bills (biller_code, account_no, status);
CREATE INDEX ix_wlt_bills_txn   ON wlt_bills (paid_txn_id);
CREATE INDEX ix_wlt_bills_payer ON wlt_bills (paid_by);

-- كود سحب نقدي لمرة واحدة: العميل يولّده، والوكيل يصرفه. الكود نفسه لا يُخزَّن، فقط بصمته
CREATE TABLE wlt_cashout_codes (
  code_id        NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_cashout PRIMARY KEY,
  user_id        NUMBER        NOT NULL CONSTRAINT fk_wlt_cashout_user REFERENCES wlt_users,
  code_hash      VARCHAR2(64)  NOT NULL,
  amount         NUMBER(15,3)  NOT NULL CONSTRAINT ck_wlt_cashout_amount CHECK (amount > 0),
  expires_at     TIMESTAMP     NOT NULL,
  status         VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL
                 CONSTRAINT ck_wlt_cashout_status CHECK (status IN ('ACTIVE','USED','CANCELLED')),
  agent_user_id  NUMBER        CONSTRAINT fk_wlt_cashout_agent REFERENCES wlt_users,
  txn_id         NUMBER        CONSTRAINT fk_wlt_cashout_txn REFERENCES wlt_transactions,
  created_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_wlt_cashout_hash  ON wlt_cashout_codes (code_hash, status);
CREATE INDEX ix_wlt_cashout_user  ON wlt_cashout_codes (user_id, status);
CREATE INDEX ix_wlt_cashout_agent ON wlt_cashout_codes (agent_user_id);
CREATE INDEX ix_wlt_cashout_txn   ON wlt_cashout_codes (txn_id);


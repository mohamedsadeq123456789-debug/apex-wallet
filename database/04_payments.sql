CREATE OR REPLACE PACKAGE wallet_pay_pkg AS
  c_err_qr        CONSTANT PLS_INTEGER := -20120;
  c_err_merchant  CONSTANT PLS_INTEGER := -20121;
  c_err_bill      CONSTANT PLS_INTEGER := -20122;
  c_err_role      CONSTANT PLS_INTEGER := -20123;
  c_err_code      CONSTANT PLS_INTEGER := -20124;

  FUNCTION create_qr (p_merchant_phone VARCHAR2, p_amount NUMBER, p_note VARCHAR2 DEFAULT NULL,
                      p_minutes NUMBER DEFAULT 15) RETURN VARCHAR2;
  FUNCTION pay_merchant (p_payer_phone VARCHAR2, p_target VARCHAR2, p_amount NUMBER DEFAULT NULL,
                         p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2;
  FUNCTION pay_bill (p_payer_phone VARCHAR2, p_bill_id NUMBER, p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2;
  FUNCTION recharge (p_payer_phone VARCHAR2, p_biller VARCHAR2, p_line VARCHAR2, p_amount NUMBER,
                     p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2;
  FUNCTION cash_in (p_agent_phone VARCHAR2, p_customer_phone VARCHAR2, p_amount NUMBER,
                    p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2;
  FUNCTION new_cashout_code (p_customer_phone VARCHAR2, p_amount NUMBER) RETURN VARCHAR2;
  FUNCTION redeem_cashout (p_agent_phone VARCHAR2, p_code VARCHAR2, p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2;
END wallet_pay_pkg;
/

CREATE OR REPLACE PACKAGE BODY wallet_pay_pkg AS

  PROCEDURE fail (p_code PLS_INTEGER, p_msg VARCHAR2) IS
  BEGIN
    RAISE_APPLICATION_ERROR(p_code, p_msg);
  END fail;

  FUNCTION user_of (p_phone VARCHAR2, p_role VARCHAR2 DEFAULT NULL) RETURN wlt_users%ROWTYPE IS
    l wlt_users%ROWTYPE;
  BEGIN
    SELECT * INTO l FROM wlt_users WHERE phone = p_phone;
    IF p_role IS NOT NULL AND l.user_type <> p_role THEN
      fail(c_err_role, 'هذه العملية متاحة لحسابات ' ||
           CASE p_role WHEN 'AGENT' THEN 'الوكلاء' WHEN 'MERCHANT' THEN 'التجار' ELSE 'العملاء' END || ' فقط');
    END IF;
    RETURN l;
  EXCEPTION WHEN NO_DATA_FOUND THEN
    fail(wallet_core_pkg.c_err_not_found, 'الرقم ' || p_phone || ' غير مسجّل في المحفظة');
    RETURN l;
  END user_of;

  FUNCTION wallet_of (p_user_id NUMBER) RETURN NUMBER IS
    l NUMBER;
  BEGIN
    SELECT wallet_id INTO l FROM wlt_wallets
     WHERE user_id = p_user_id AND wallet_type = 'MAIN' AND currency_code = 'JOD';
    RETURN l;
  END wallet_of;

  FUNCTION ref_of (p_txn_id NUMBER) RETURN VARCHAR2 IS
    l VARCHAR2(20);
  BEGIN
    SELECT txn_ref INTO l FROM wlt_transactions WHERE txn_id = p_txn_id;
    RETURN l;
  END ref_of;

  FUNCTION hash_code (p_code VARCHAR2) RETURN VARCHAR2 IS
    l VARCHAR2(64);
  BEGIN
    SELECT RAWTOHEX(STANDARD_HASH('WLT-CASHOUT:' || p_code, 'SHA256')) INTO l FROM dual;
    RETURN l;
  END hash_code;

  -- -----------------------------------------------------------------
  FUNCTION create_qr (p_merchant_phone VARCHAR2, p_amount NUMBER, p_note VARCHAR2 DEFAULT NULL,
                      p_minutes NUMBER DEFAULT 15) RETURN VARCHAR2 IS
    l_u     wlt_users%ROWTYPE := user_of(p_merchant_phone, 'MERCHANT');
    l_token VARCHAR2(32) := LOWER(DBMS_RANDOM.STRING('X', 20));
  BEGIN
    IF p_amount IS NULL OR p_amount <= 0 OR p_amount <> ROUND(p_amount, 3) THEN
      fail(wallet_core_pkg.c_err_bad_amount, 'أدخل مبلغاً صحيحاً للكود');
    END IF;
    INSERT INTO wlt_qr_codes (token, merchant_user_id, amount, note, expires_at)
    VALUES (l_token, l_u.user_id, p_amount, SUBSTR(p_note, 1, 100),
            SYSTIMESTAMP + NUMTODSINTERVAL(p_minutes, 'MINUTE'));
    COMMIT;
    RETURN l_token;
  END create_qr;

  -- الهدف إما كود تاجر ثابت (M2041) مع مبلغ، أو توكن QR ديناميكي بمبلغه
  FUNCTION pay_merchant (p_payer_phone VARCHAR2, p_target VARCHAR2, p_amount NUMBER DEFAULT NULL,
                         p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
    l_target VARCHAR2(40) := UPPER(TRIM(REGEXP_REPLACE(p_target, '^WLT:', '', 1, 1, 'i')));
    l_merch  NUMBER;
    l_qr     wlt_qr_codes%ROWTYPE;
    l_ref    VARCHAR2(20);
    l_txn    NUMBER;
    l_payer  wlt_users%ROWTYPE := user_of(p_payer_phone);
  BEGIN
    IF REGEXP_LIKE(l_target, '^M[0-9]{4}$') THEN
      BEGIN
        SELECT user_id INTO l_merch FROM wlt_merchant_profiles WHERE merchant_code = l_target;
      EXCEPTION WHEN NO_DATA_FOUND THEN
        fail(c_err_merchant, 'لا يوجد تاجر بالكود ' || l_target);
      END;
      RETURN wallet_core_pkg.transfer(
               p_from_wallet => wallet_core_pkg.main_wallet(p_payer_phone),
               p_to_wallet   => wallet_of(l_merch),
               p_amount      => p_amount, p_txn_type => 'MERCHANT_PAY',
               p_idem_key    => p_idem, p_description => 'دفع ' || l_target);
    END IF;

    BEGIN
      SELECT * INTO l_qr FROM wlt_qr_codes WHERE token = LOWER(l_target) FOR UPDATE;
    EXCEPTION WHEN NO_DATA_FOUND THEN
      fail(c_err_qr, 'الكود غير صالح');
    END;
    IF l_qr.status = 'USED' THEN
      -- نفس الدافع أعاد المحاولة بعد نجاحها؟ نرجع نفس الإيصال
      IF l_qr.paid_by = l_payer.user_id THEN
        RETURN ref_of(l_qr.paid_txn_id);
      END IF;
      fail(c_err_qr, 'هذا الكود دُفع مسبقاً');
    END IF;
    IF l_qr.status <> 'ACTIVE' OR l_qr.expires_at < SYSTIMESTAMP THEN
      fail(c_err_qr, 'انتهت صلاحية الكود. اطلب من التاجر كوداً جديداً');
    END IF;

    l_ref := wallet_core_pkg.transfer(
               p_from_wallet => wallet_core_pkg.main_wallet(p_payer_phone),
               p_to_wallet   => wallet_of(l_qr.merchant_user_id),
               p_amount      => l_qr.amount, p_txn_type => 'MERCHANT_PAY',
               p_idem_key    => p_idem, p_description => NVL(l_qr.note, 'دفع بكود QR'),
               p_commit      => FALSE);
    SELECT txn_id INTO l_txn FROM wlt_transactions WHERE txn_ref = l_ref;
    UPDATE wlt_qr_codes SET status = 'USED', paid_txn_id = l_txn, paid_by = l_payer.user_id
     WHERE qr_id = l_qr.qr_id;
    COMMIT;
    RETURN l_ref;
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
  END pay_merchant;

  -- -----------------------------------------------------------------
  FUNCTION pay_bill (p_payer_phone VARCHAR2, p_bill_id NUMBER, p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
    l_bill  wlt_bills%ROWTYPE;
    l_b     wlt_billers%ROWTYPE;
    l_payer wlt_users%ROWTYPE := user_of(p_payer_phone);
    l_ref   VARCHAR2(20);
    l_txn   NUMBER;
  BEGIN
    BEGIN
      SELECT * INTO l_bill FROM wlt_bills WHERE bill_id = p_bill_id FOR UPDATE;
    EXCEPTION WHEN NO_DATA_FOUND THEN
      fail(c_err_bill, 'الفاتورة غير موجودة');
    END;
    IF l_bill.status = 'PAID' THEN
      IF l_bill.paid_by = l_payer.user_id THEN
        RETURN ref_of(l_bill.paid_txn_id);
      END IF;
      fail(c_err_bill, 'هذه الفاتورة مدفوعة مسبقاً');
    END IF;
    SELECT * INTO l_b FROM wlt_billers WHERE biller_code = l_bill.biller_code;

    l_ref := wallet_core_pkg.transfer(
               p_from_wallet => wallet_core_pkg.main_wallet(p_payer_phone),
               p_to_wallet   => wallet_of(l_b.user_id),
               p_amount      => l_bill.amount, p_txn_type => 'BILL_PAY', p_idem_key => p_idem,
               p_description => l_b.name_ar || ' ' || l_bill.account_no || ' · ' || l_bill.period_ar,
               p_commit      => FALSE);
    SELECT txn_id INTO l_txn FROM wlt_transactions WHERE txn_ref = l_ref;
    UPDATE wlt_bills SET status = 'PAID', paid_txn_id = l_txn, paid_by = l_payer.user_id, paid_at = SYSTIMESTAMP
     WHERE bill_id = l_bill.bill_id;
    COMMIT;
    RETURN l_ref;
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
  END pay_bill;

  FUNCTION recharge (p_payer_phone VARCHAR2, p_biller VARCHAR2, p_line VARCHAR2, p_amount NUMBER,
                     p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
    l_b wlt_billers%ROWTYPE;
  BEGIN
    BEGIN
      SELECT * INTO l_b FROM wlt_billers WHERE biller_code = p_biller AND pay_mode = 'OPEN';
    EXCEPTION WHEN NO_DATA_FOUND THEN
      fail(c_err_bill, 'جهة الشحن غير معروفة');
    END;
    IF NOT REGEXP_LIKE(p_line, '^07[789][0-9]{7}$') THEN
      fail(c_err_bill, 'رقم الخط غير صحيح');
    END IF;
    IF p_amount NOT IN (1, 2, 5, 10, 15, 20) THEN
      fail(wallet_core_pkg.c_err_bad_amount, 'اختر قيمة شحن من القيم المتاحة');
    END IF;
    RETURN wallet_core_pkg.transfer(
             p_from_wallet => wallet_core_pkg.main_wallet(p_payer_phone),
             p_to_wallet   => wallet_of(l_b.user_id),
             p_amount      => p_amount, p_txn_type => 'RECHARGE', p_idem_key => p_idem,
             p_description => 'شحن خط ' || p_line);
  END recharge;

  -- -----------------------------------------------------------------
  FUNCTION cash_in (p_agent_phone VARCHAR2, p_customer_phone VARCHAR2, p_amount NUMBER,
                    p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
    l_agent wlt_users%ROWTYPE := user_of(p_agent_phone, 'AGENT');
    l_cust  wlt_users%ROWTYPE := user_of(p_customer_phone, 'CUSTOMER');
  BEGIN
    RETURN wallet_core_pkg.transfer(
             p_from_wallet => wallet_core_pkg.main_wallet(p_agent_phone),
             p_to_wallet   => wallet_core_pkg.main_wallet(p_customer_phone),
             p_amount      => p_amount, p_txn_type => 'CASH_IN', p_idem_key => p_idem,
             p_description => 'إيداع نقدي عند وكيل');
  END cash_in;

  FUNCTION new_cashout_code (p_customer_phone VARCHAR2, p_amount NUMBER) RETURN VARCHAR2 IS
    l_cust  wlt_users%ROWTYPE := user_of(p_customer_phone, 'CUSTOMER');
    l_v     wlt_v_wallets%ROWTYPE;
    l_fee   NUMBER;
    l_code  VARCHAR2(6);
    l_hash  VARCHAR2(64);
    l_n     NUMBER;
  BEGIN
    IF p_amount IS NULL OR p_amount <= 0 OR p_amount <> ROUND(p_amount) THEN
      fail(wallet_core_pkg.c_err_bad_amount, 'مبلغ السحب يجب أن يكون بالدينار الكامل');
    END IF;
    SELECT * INTO l_v FROM wlt_v_wallets WHERE wallet_id = wallet_core_pkg.main_wallet(p_customer_phone);
    l_fee := wallet_core_pkg.calc_fee('CASH_OUT', p_amount);
    IF l_v.available_balance < p_amount + l_fee THEN
      fail(wallet_core_pkg.c_err_insufficient, 'رصيدك لا يكفي. تحتاج ' ||
           TO_CHAR(p_amount + l_fee, 'FM999G990D000') || ' مع الرسوم');
    END IF;

    UPDATE wlt_cashout_codes SET status = 'CANCELLED'
     WHERE user_id = l_cust.user_id AND status = 'ACTIVE';

    LOOP
      l_code := LPAD(TRUNC(DBMS_RANDOM.VALUE(0, 1000000)), 6, '0');
      l_hash := hash_code(l_code);
      SELECT COUNT(*) INTO l_n FROM wlt_cashout_codes
       WHERE code_hash = l_hash AND status = 'ACTIVE' AND expires_at > SYSTIMESTAMP;
      EXIT WHEN l_n = 0;
    END LOOP;

    INSERT INTO wlt_cashout_codes (user_id, code_hash, amount, expires_at)
    VALUES (l_cust.user_id, l_hash, p_amount, SYSTIMESTAMP + INTERVAL '10' MINUTE);
    COMMIT;
    RETURN l_code;
  END new_cashout_code;

  FUNCTION redeem_cashout (p_agent_phone VARCHAR2, p_code VARCHAR2, p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
    l_agent wlt_users%ROWTYPE := user_of(p_agent_phone, 'AGENT');
    l_c     wlt_cashout_codes%ROWTYPE;
    l_ref   VARCHAR2(20);
    l_txn   NUMBER;
    l_hash  VARCHAR2(64) := hash_code(REGEXP_REPLACE(p_code, '[^0-9]', ''));
  BEGIN
    BEGIN
      SELECT * INTO l_c FROM wlt_cashout_codes
       WHERE code_hash = l_hash
         AND status = 'ACTIVE' AND expires_at > SYSTIMESTAMP
         FOR UPDATE;
    EXCEPTION WHEN NO_DATA_FOUND THEN
      INSERT INTO wlt_audit_log (actor_user_id, action, entity, details)
      VALUES (l_agent.user_id, 'CASHOUT_BAD_CODE', 'CASHOUT', 'كود خاطئ أو منتهي');
      COMMIT;
      fail(c_err_code, 'الكود غير صحيح أو انتهت صلاحيته');
    END;

    l_ref := wallet_core_pkg.transfer(
               p_from_wallet => wallet_of(l_c.user_id),
               p_to_wallet   => wallet_core_pkg.main_wallet(p_agent_phone),
               p_amount      => l_c.amount, p_txn_type => 'CASH_OUT', p_idem_key => p_idem,
               p_description => 'سحب نقدي عند وكيل', p_actor_user => l_agent.user_id,
               p_commit      => FALSE);
    SELECT txn_id INTO l_txn FROM wlt_transactions WHERE txn_ref = l_ref;
    UPDATE wlt_cashout_codes SET status = 'USED', agent_user_id = l_agent.user_id, txn_id = l_txn
     WHERE code_id = l_c.code_id;
    COMMIT;
    RETURN l_ref;
  EXCEPTION WHEN OTHERS THEN
    IF SQLCODE <> c_err_code THEN ROLLBACK; END IF;
    RAISE;
  END redeem_cashout;

END wallet_pay_pkg;

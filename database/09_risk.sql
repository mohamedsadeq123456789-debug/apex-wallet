CREATE OR REPLACE PACKAGE wallet_risk_pkg AS
  c_err CONSTANT PLS_INTEGER := -20180;
  g_bypass BOOLEAN := FALSE;   -- تُفعَّل فقط عند تنفيذ عملية وافقت عليها الإدارة
  TYPE t_score IS RECORD (score NUMBER, reasons VARCHAR2(1000));
  FUNCTION assess (p_from NUMBER, p_to NUMBER, p_amount NUMBER, p_type VARCHAR2) RETURN t_score;
  PROCEDURE screen (p_from NUMBER, p_to NUMBER, p_amount NUMBER, p_type VARCHAR2, p_desc VARCHAR2);
  FUNCTION approve (p_admin_phone VARCHAR2, p_case_id NUMBER) RETURN VARCHAR2;
  PROCEDURE reject (p_admin_phone VARCHAR2, p_case_id NUMBER, p_freeze VARCHAR2 DEFAULT 'N');
  PROCEDURE set_user_status (p_admin_phone VARCHAR2, p_phone VARCHAR2, p_status VARCHAR2);
  PROCEDURE set_user_tier (p_admin_phone VARCHAR2, p_phone VARCHAR2, p_tier VARCHAR2);
END wallet_risk_pkg;
/

CREATE OR REPLACE PACKAGE BODY wallet_risk_pkg AS

  PROCEDURE fail (p_msg VARCHAR2) IS BEGIN RAISE_APPLICATION_ERROR(c_err, p_msg); END;

  FUNCTION money (p NUMBER) RETURN VARCHAR2 IS
  BEGIN RETURN TO_CHAR(p, 'FM999G999G990D000', 'NLS_NUMERIC_CHARACTERS=''.,'''); END;

  FUNCTION setting_num (p VARCHAR2) RETURN NUMBER IS
    l NUMBER;
  BEGIN
    SELECT TO_NUMBER(setting_value) INTO l FROM wlt_app_settings WHERE setting_key = p;
    RETURN l;
  END setting_num;

  FUNCTION admin_id (p_phone VARCHAR2) RETURN NUMBER IS
    l NUMBER;
  BEGIN
    SELECT user_id INTO l FROM wlt_users WHERE phone = p_phone AND user_type = 'ADMIN' AND status = 'ACTIVE';
    RETURN l;
  EXCEPTION WHEN NO_DATA_FOUND THEN fail('للإدارة فقط'); RETURN NULL;
  END admin_id;

  -- درجة الخطورة من سلوك المرسل: سرعة، مبلغ غير مألوف، مستلم جديد، حساب جديد، تشتيت، توقيت، مستلم مشبوه
  FUNCTION assess (p_from NUMBER, p_to NUMBER, p_amount NUMBER, p_type VARCHAR2) RETURN t_score IS
    s       t_score;
    l_fu    NUMBER;
    l_tu    NUMBER;
    l_v10   NUMBER; l_fan NUMBER; l_avg NUMBER; l_max NUMBER; l_cnt NUMBER; l_seen NUMBER;
    l_age   NUMBER;
    l_flag  NUMBER;
    l_hour  NUMBER := TO_NUMBER(TO_CHAR(wlt_local(SYSTIMESTAMP), 'HH24'));
    PROCEDURE add (p_pts NUMBER, p_why VARCHAR2) IS
    BEGIN
      s.score := s.score + p_pts;
      s.reasons := s.reasons || CASE WHEN s.reasons IS NOT NULL THEN ' · ' END || p_why || ' (+' || p_pts || ')';
    END add;
  BEGIN
    s.score := 0;
    SELECT user_id INTO l_fu FROM wlt_wallets WHERE wallet_id = p_from;
    SELECT user_id INTO l_tu FROM wlt_wallets WHERE wallet_id = p_to;
    SELECT TRUNC(SYSDATE - CAST(created_at AS DATE), 2) INTO l_age FROM wlt_users WHERE user_id = l_fu;

    SELECT COUNT(CASE WHEN created_at > SYSTIMESTAMP - INTERVAL '10' MINUTE THEN 1 END),
           COUNT(DISTINCT CASE WHEN created_at > SYSTIMESTAMP - INTERVAL '1' HOUR THEN to_wallet_id END),
           AVG(amount), MAX(amount), COUNT(*),
           COUNT(CASE WHEN to_wallet_id = p_to THEN 1 END)
      INTO l_v10, l_fan, l_avg, l_max, l_cnt, l_seen
      FROM wlt_transactions
     WHERE from_wallet_id = p_from AND status = 'COMPLETED' AND created_at > SYSDATE - 30
       AND txn_type IN ('TRANSFER','MERCHANT_PAY','BILL_PAY','CASH_OUT','RECHARGE');

    IF l_v10 >= 5 THEN add(30, 'عمليات متتالية بسرعة');
    ELSIF l_v10 >= 3 THEN add(15, 'نشاط سريع');
    END IF;
    IF l_cnt >= 3 AND p_amount >= 50 AND p_amount > 3 * l_avg THEN add(25, 'مبلغ أكبر بكثير من المعتاد'); END IF;
    IF l_cnt >= 3 AND p_amount >= 50 AND p_amount > 2 * l_max THEN add(10, 'أعلى مبلغ في تاريخ الحساب'); END IF;
    IF l_seen = 0 AND p_amount >= 100 THEN add(20, 'مستلم جديد بمبلغ كبير'); END IF;
    IF l_age < 1 AND p_amount >= 100 THEN add(20, 'حساب عمره أقل من يوم'); END IF;
    IF l_fan >= 5 THEN add(20, 'تحويل لأشخاص كثيرين خلال ساعة'); END IF;
    IF l_hour < 5 AND p_amount >= 100 THEN add(10, 'وقت غير معتاد'); END IF;
    SELECT COUNT(*) INTO l_flag FROM wlt_risk_cases WHERE to_user_id = l_tu AND status IN ('OPEN','REJECTED');
    IF l_flag > 0 THEN add(25, 'المستلم عليه بلاغات سابقة'); END IF;
    IF p_type = 'CASH_OUT' AND l_age < 3 AND p_amount >= 100 THEN add(15, 'سحب نقدي كبير من حساب جديد'); END IF;
    s.score := LEAST(s.score, 100);
    RETURN s;
  END assess;

  -- معاملة مستقلة: الحالة والحجز يبقيان حتى لو أُلغيت عملية المستخدم
  PROCEDURE open_case (p_from NUMBER, p_to NUMBER, p_amount NUMBER, p_type VARCHAR2, p_desc VARCHAR2,
                       s t_score, p_hold BOOLEAN) IS
    PRAGMA AUTONOMOUS_TRANSACTION;
    l_fu NUMBER; l_tu NUMBER; l_av NUMBER;
    l_held CHAR(1) := 'N';
    l_msg  VARCHAR2(300) := 'تحويل ' || money(p_amount) || ' د.أ ينتظر تأكيد فريق الأمان. المبلغ محجوز ولم يخرج من محفظتك.';
  BEGIN
    SELECT user_id INTO l_fu FROM wlt_wallets WHERE wallet_id = p_from;
    SELECT user_id INTO l_tu FROM wlt_wallets WHERE wallet_id = p_to;
    IF p_hold THEN
      BEGIN
        -- NOWAIT: إن كانت العملية الأصلية قد قفلت المحفظة لا ننتظر أنفسنا؛ نفتح الحالة بلا حجز
        SELECT balance - held_amount INTO l_av FROM wlt_wallets WHERE wallet_id = p_from FOR UPDATE NOWAIT;
        IF l_av >= p_amount THEN
          UPDATE wlt_wallets SET held_amount = held_amount + p_amount WHERE wallet_id = p_from;
          l_held := 'Y';
        END IF;
      EXCEPTION WHEN OTHERS THEN l_held := 'N';
      END;
    END IF;
    INSERT INTO wlt_risk_cases (from_wallet_id, to_wallet_id, from_user_id, to_user_id, amount, txn_type, description,
                                score, reasons, status, held)
    VALUES (p_from, p_to, l_fu, l_tu, p_amount, p_type, SUBSTR(p_desc, 1, 200), s.score, s.reasons,
            CASE WHEN p_hold THEN 'OPEN' ELSE 'WATCH' END, l_held);
    IF p_hold THEN
      INSERT INTO wlt_notifications (user_id, kind, title, body, link_page)
      VALUES (l_fu, 'SECURITY', '🛡️ أوقفنا تحويلاً للمراجعة',
              l_msg, 1);
    END IF;
    COMMIT;
  END open_case;

  PROCEDURE screen (p_from NUMBER, p_to NUMBER, p_amount NUMBER, p_type VARCHAR2, p_desc VARCHAR2) IS
    s     t_score;
    l_dup NUMBER;
  BEGIN
    IF g_bypass THEN RETURN; END IF;
    -- نفس الطلب أُوقف قبل قليل: لا نفتح حالة ثانية
    SELECT COUNT(*) INTO l_dup FROM wlt_risk_cases
     WHERE from_wallet_id = p_from AND to_wallet_id = p_to AND amount = p_amount AND status = 'OPEN'
       AND created_at > SYSTIMESTAMP - INTERVAL '30' MINUTE;
    IF l_dup > 0 THEN fail('هذه العملية قيد المراجعة الأمنية. سيصلك إشعار خلال وقت قصير'); END IF;

    s := assess(p_from, p_to, p_amount, p_type);
    IF s.score >= setting_num('RISK_HOLD_SCORE') THEN
      open_case(p_from, p_to, p_amount, p_type, p_desc, s, TRUE);
      fail('أوقفنا العملية للمراجعة الأمنية لحمايتك. المبلغ محجوز في محفظتك وسيصلك إشعار بالنتيجة');
    ELSIF s.score >= setting_num('RISK_WATCH_SCORE') THEN
      open_case(p_from, p_to, p_amount, p_type, p_desc, s, FALSE);
    END IF;
  END screen;

  FUNCTION approve (p_admin_phone VARCHAR2, p_case_id NUMBER) RETURN VARCHAR2 IS
    l_a   NUMBER := admin_id(p_admin_phone);
    c     wlt_risk_cases%ROWTYPE;
    l_ref VARCHAR2(20);
  BEGIN
    SELECT * INTO c FROM wlt_risk_cases WHERE case_id = p_case_id FOR UPDATE;
    IF c.status <> 'OPEN' THEN fail('الحالة مغلقة مسبقاً'); END IF;
    IF c.held = 'Y' THEN
      UPDATE wlt_wallets SET held_amount = held_amount - c.amount WHERE wallet_id = c.from_wallet_id;
    END IF;
    g_bypass := TRUE;
    BEGIN
      l_ref := wallet_core_pkg.transfer(p_from_wallet => c.from_wallet_id, p_to_wallet => c.to_wallet_id, p_amount => c.amount,
                 p_txn_type => c.txn_type, p_idem_key => 'RISK-' || c.case_id, p_description => c.description,
                 p_actor_user => c.from_user_id, p_commit => FALSE);
      g_bypass := FALSE;
    EXCEPTION WHEN OTHERS THEN g_bypass := FALSE; RAISE;
    END;
    UPDATE wlt_risk_cases SET status = 'APPROVED', decided_by = l_a, decided_at = SYSTIMESTAMP,
           txn_id = (SELECT txn_id FROM wlt_transactions WHERE txn_ref = l_ref)
     WHERE case_id = c.case_id;
    wallet_social_pkg.notify(c.from_user_id, 'SECURITY', '✅ تمّ تنفيذ تحويلك بعد المراجعة',
      money(c.amount) || ' د.أ · ' || l_ref, 1);
    INSERT INTO wlt_audit_log (actor_user_id, action, entity, entity_id, details)
    VALUES (l_a, 'RISK_APPROVE', 'RISK_CASE', c.case_id, 'score ' || c.score);
    COMMIT;
    RETURN l_ref;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END approve;

  PROCEDURE reject (p_admin_phone VARCHAR2, p_case_id NUMBER, p_freeze VARCHAR2 DEFAULT 'N') IS
    l_a NUMBER := admin_id(p_admin_phone);
    c   wlt_risk_cases%ROWTYPE;
  BEGIN
    SELECT * INTO c FROM wlt_risk_cases WHERE case_id = p_case_id FOR UPDATE;
    IF c.status <> 'OPEN' THEN fail('الحالة مغلقة مسبقاً'); END IF;
    IF c.held = 'Y' THEN
      UPDATE wlt_wallets SET held_amount = held_amount - c.amount WHERE wallet_id = c.from_wallet_id;
    END IF;
    UPDATE wlt_risk_cases SET status = 'REJECTED', decided_by = l_a, decided_at = SYSTIMESTAMP WHERE case_id = c.case_id;
    IF p_freeze = 'Y' THEN
      UPDATE wlt_users SET status = 'SUSPENDED' WHERE user_id = c.from_user_id;
    END IF;
    wallet_social_pkg.notify(c.from_user_id, 'SECURITY', '⛔ لم يُنفَّذ التحويل',
      'رفض فريق الأمان تحويل ' || money(c.amount) || ' د.أ وفُكّ الحجز عن المبلغ. تواصل مع الدعم إن كان التحويل منك.', 1);
    INSERT INTO wlt_audit_log (actor_user_id, action, entity, entity_id, details)
    VALUES (l_a, 'RISK_REJECT', 'RISK_CASE', c.case_id, 'freeze=' || p_freeze);
    COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END reject;

  PROCEDURE set_user_status (p_admin_phone VARCHAR2, p_phone VARCHAR2, p_status VARCHAR2) IS
    l_a NUMBER := admin_id(p_admin_phone);
    l_u NUMBER;
  BEGIN
    IF p_status NOT IN ('ACTIVE','SUSPENDED') THEN fail('حالة غير صالحة'); END IF;
    UPDATE wlt_users SET status = p_status, failed_pin_attempts = 0, locked_until = NULL
     WHERE phone = wallet_otp_pkg.normalize_phone(p_phone) AND user_type IN ('CUSTOMER','MERCHANT','AGENT')
    RETURNING user_id INTO l_u;
    IF l_u IS NULL THEN fail('المستخدم غير موجود'); END IF;
    INSERT INTO wlt_audit_log (actor_user_id, action, entity, entity_id, details)
    VALUES (l_a, 'USER_' || p_status, 'USER', l_u, NULL);
    COMMIT;
  END set_user_status;

  PROCEDURE set_user_tier (p_admin_phone VARCHAR2, p_phone VARCHAR2, p_tier VARCHAR2) IS
    l_a NUMBER := admin_id(p_admin_phone);
    l_u NUMBER;
    l_n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO l_n FROM wlt_kyc_tiers WHERE tier_code = p_tier;
    IF l_n = 0 THEN fail('مستوى غير معروف'); END IF;
    UPDATE wlt_users SET kyc_tier = p_tier
     WHERE phone = wallet_otp_pkg.normalize_phone(p_phone) AND user_type IN ('CUSTOMER','MERCHANT','AGENT')
    RETURNING user_id INTO l_u;
    IF l_u IS NULL THEN fail('المستخدم غير موجود'); END IF;
    INSERT INTO wlt_audit_log (actor_user_id, action, entity, entity_id, details)
    VALUES (l_a, 'USER_TIER', 'USER', l_u, p_tier);
    wallet_social_pkg.notify(l_u, 'SECURITY', '⭐ تمّ ترقية مستوى حسابك', 'حدود أعلى للتحويل والرصيد', 1);
    COMMIT;
  END set_user_tier;

END wallet_risk_pkg;
/


CREATE TABLE wlt_risk_cases (
  case_id         NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_risk PRIMARY KEY,
  from_wallet_id  NUMBER        NOT NULL CONSTRAINT fk_wlt_risk_from REFERENCES wlt_wallets,
  to_wallet_id    NUMBER        NOT NULL CONSTRAINT fk_wlt_risk_to   REFERENCES wlt_wallets,
  from_user_id    NUMBER        NOT NULL CONSTRAINT fk_wlt_risk_fu   REFERENCES wlt_users,
  to_user_id      NUMBER        NOT NULL CONSTRAINT fk_wlt_risk_tu   REFERENCES wlt_users,
  amount          NUMBER(15,3)  NOT NULL,
  txn_type        VARCHAR2(20)  NOT NULL,
  description     VARCHAR2(200),
  score           NUMBER(3)     NOT NULL,
  reasons         VARCHAR2(1000),
  status          VARCHAR2(10)  NOT NULL CONSTRAINT ck_wlt_risk_status CHECK (status IN ('OPEN','WATCH','APPROVED','REJECTED')),
  held            CHAR(1)       DEFAULT 'N' NOT NULL,
  decided_by      NUMBER        CONSTRAINT fk_wlt_risk_admin REFERENCES wlt_users,
  decided_at      TIMESTAMP,
  txn_id          NUMBER        CONSTRAINT fk_wlt_risk_txn REFERENCES wlt_transactions,
  created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_wlt_risk_status ON wlt_risk_cases (status, created_at);
CREATE INDEX ix_wlt_risk_from   ON wlt_risk_cases (from_wallet_id, status);
CREATE INDEX ix_wlt_risk_to     ON wlt_risk_cases (to_wallet_id);
CREATE INDEX ix_wlt_risk_fu     ON wlt_risk_cases (from_user_id);
CREATE INDEX ix_wlt_risk_tu     ON wlt_risk_cases (to_user_id, status);
CREATE INDEX ix_wlt_risk_admin  ON wlt_risk_cases (decided_by);
CREATE INDEX ix_wlt_risk_txn    ON wlt_risk_cases (txn_id);


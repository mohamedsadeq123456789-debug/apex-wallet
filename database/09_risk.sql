-- إحصاءات يومية مُجمَّعة مسبقاً للوحة الإدارة (بتوقيت عمّان)
CREATE MATERIALIZED VIEW wlt_mv_daily
  BUILD IMMEDIATE REFRESH COMPLETE ON DEMAND AS
SELECT TRUNC(CAST(created_at AS DATE) + 3/24) AS day, txn_type,
       COUNT(*) AS cnt, SUM(amount) AS volume, SUM(fee) AS fees
  FROM wlt_transactions
 WHERE status = 'COMPLETED'
 GROUP BY TRUNC(CAST(created_at AS DATE) + 3/24), txn_type;

BEGIN
  DBMS_SCHEDULER.CREATE_JOB(
    job_name        => 'WLT_REFRESH_STATS',
    job_type        => 'PLSQL_BLOCK',
    job_action      => 'BEGIN DBMS_MVIEW.REFRESH(''WLT_MV_DAILY'', ''C''); END;',
    start_date      => SYSTIMESTAMP,
    repeat_interval => 'FREQ=MINUTELY;INTERVAL=10',
    enabled         => TRUE,
    comments        => 'محفظتي: تحديث إحصاءات لوحة الإدارة');
END;

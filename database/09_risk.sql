DECLARE
  l CLOB;
  c_anch CONSTANT VARCHAR2(200) := 'lock_wallets(sys.odcinumberlist(p_from_wallet, p_to_wallet, CASE WHEN l_fee > 0 THEN l_fees_w END));';
BEGIN
  FOR r IN (SELECT text FROM user_source WHERE name = 'WALLET_CORE_PKG' AND type = 'PACKAGE BODY' ORDER BY line) LOOP
    l := l || r.text;
  END LOOP;
  IF INSTR(l, 'wallet_risk_pkg') = 0 THEN
    IF INSTR(l, c_anch) = 0 OR INSTR(l, c_anch, 1, 2) > 0 THEN RAISE_APPLICATION_ERROR(-20000, 'risk anchor'); END IF;
    l := REPLACE(l, c_anch, q'#IF p_txn_type IN ('TRANSFER','CASH_OUT') THEN
      wallet_risk_pkg.screen(p_from_wallet, p_to_wallet, p_amount, p_txn_type, p_description);
    END IF;
    #' || c_anch);
    EXECUTE IMMEDIATE 'CREATE OR REPLACE ' || l;
  END IF;
END;

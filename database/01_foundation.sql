-- ---------------------------------------------------------------------
-- 10) بيانات تجريبية: مستخدمون، محافظ، وأرصدة افتتاحية
--     الـPIN التجريبي لكل المستخدمين: 1234
--     الأرصدة الافتتاحية تُكتب كعمليات حقيقية في الدفتر المزدوج،
--     وليس بتعديل عمود الرصيد مباشرة، حتى تبقى الفحوصات سليمة
-- ---------------------------------------------------------------------

DECLARE
  l_system_user  NUMBER;
  l_funding_w    NUMBER;
  l_fees_w       NUMBER;
  l_w            NUMBER;

  -- ينشئ مستخدماً بـPIN مشفّر ومحفظة رئيسية، ويرجع رقم المحفظة
  FUNCTION add_user (
    p_phone  VARCHAR2,
    p_name   VARCHAR2,
    p_type   VARCHAR2,
    p_tier   VARCHAR2,
    p_pin    VARCHAR2 DEFAULT '1234'
  ) RETURN NUMBER IS
    l_salt     VARCHAR2(32) := DBMS_RANDOM.STRING('X', 16);
    l_hash     VARCHAR2(64);
    l_user_id  NUMBER;
    l_wallet   NUMBER;
  BEGIN
    SELECT RAWTOHEX(STANDARD_HASH(l_salt || p_pin, 'SHA256'))
      INTO l_hash
      FROM dual;

    INSERT INTO wlt_users (phone, full_name, user_type, kyc_tier, pin_hash, pin_salt)
    VALUES (p_phone, p_name, p_type, p_tier, l_hash, l_salt)
    RETURNING user_id INTO l_user_id;

    INSERT INTO wlt_wallets (user_id, wallet_type, currency_code, label)
    VALUES (l_user_id, 'MAIN', 'JOD', 'المحفظة الرئيسية')
    RETURNING wallet_id INTO l_wallet;

    RETURN l_wallet;
  END add_user;

  -- يشحن رصيداً افتتاحياً: قيد خصم من محفظة التمويل + قيد إضافة للمستخدم
  PROCEDURE opening_topup (p_to_wallet NUMBER, p_amount NUMBER) IS
    l_txn_id   NUMBER;
    l_bal_from NUMBER;
    l_bal_to   NUMBER;
  BEGIN
    INSERT INTO wlt_transactions
      (txn_ref, txn_type, from_wallet_id, to_wallet_id, amount, currency_code,
       status, description, created_by)
    VALUES
      ('TX' || TO_CHAR(SYSDATE, 'YYMMDD') || LPAD(wlt_txn_ref_seq.NEXTVAL, 8, '0'),
       'TOPUP', l_funding_w, p_to_wallet, p_amount, 'JOD',
       'PENDING', 'رصيد افتتاحي', l_system_user)
    RETURNING txn_id INTO l_txn_id;

    UPDATE wlt_wallets SET balance = balance - p_amount
     WHERE wallet_id = l_funding_w
    RETURNING balance INTO l_bal_from;

    INSERT INTO wlt_ledger_entries (txn_id, wallet_id, entry_type, amount, balance_after)
    VALUES (l_txn_id, l_funding_w, 'D', p_amount, l_bal_from);

    UPDATE wlt_wallets SET balance = balance + p_amount
     WHERE wallet_id = p_to_wallet
    RETURNING balance INTO l_bal_to;

    INSERT INTO wlt_ledger_entries (txn_id, wallet_id, entry_type, amount, balance_after)
    VALUES (l_txn_id, p_to_wallet, 'C', p_amount, l_bal_to);

    UPDATE wlt_transactions
       SET status = 'COMPLETED', completed_at = SYSTIMESTAMP
     WHERE txn_id = l_txn_id;
  END opening_topup;

BEGIN
  -- حساب النظام ومحفظتاه
  INSERT INTO wlt_users (phone, full_name, user_type, kyc_tier)
  VALUES ('SYSTEM', 'حساب النظام', 'SYSTEM', 'PREMIUM')
  RETURNING user_id INTO l_system_user;

  -- محفظة التمويل: تمثل المال الداخل من خارج النظام (بنك، كاش)
  -- مسموح لها تنزل بالسالب، ورصيدها السالب = مجموع المال الموجود في المحافظ
  INSERT INTO wlt_wallets (user_id, wallet_type, currency_code, label, allow_negative)
  VALUES (l_system_user, 'SYSTEM', 'JOD', 'تمويل خارجي', 'Y')
  RETURNING wallet_id INTO l_funding_w;

  -- محفظة الرسوم: هنا تتجمع أرباح المحفظة من الرسوم
  INSERT INTO wlt_wallets (user_id, wallet_type, currency_code, label)
  VALUES (l_system_user, 'SYSTEM', 'JOD', 'إيرادات الرسوم')
  RETURNING wallet_id INTO l_fees_w;

  -- مدير النظام
  l_w := add_user('0790000001', 'مدير المحفظة', 'ADMIN', 'PREMIUM');

  -- العملاء
  opening_topup(add_user('0791234567', 'محمد البطاينة', 'CUSTOMER', 'VERIFIED'), 250);
  opening_topup(add_user('0782345678', 'ليلى حداد',     'CUSTOMER', 'BASIC'),    480);
  opening_topup(add_user('0773456789', 'عمر الزعبي',    'CUSTOMER', 'BASIC'),    75.5);
  opening_topup(add_user('0794567890', 'سارة العمري',   'CUSTOMER', 'VERIFIED'), 900);
  opening_topup(add_user('0785678901', 'يزن الخطيب',    'CUSTOMER', 'BASIC'),    30);

  -- التجار
  l_w := add_user('0796789012', 'مقهى الياسمين', 'MERCHANT', 'VERIFIED');
  opening_topup(add_user('0777890123', 'صيدلية النخيل', 'MERCHANT', 'VERIFIED'), 120);

  -- الوكيل: عنده رصيد كبير ليخدم الإيداع والسحب النقدي
  opening_topup(add_user('0798901234', 'وكيل إربد المركزي', 'AGENT', 'PREMIUM'), 5000);

  INSERT INTO wlt_audit_log (actor_user_id, action, entity, details)
  VALUES (l_system_user, 'SEED', 'DATABASE', 'تهيئة الجلسة الأولى: مستخدمون وأرصدة افتتاحية');

  COMMIT;
END;

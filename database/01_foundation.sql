-- عرض مريح للمحافظ مع أصحابها (ستستخدمه صفحات APEX)
CREATE OR REPLACE VIEW wlt_v_wallets AS
SELECT w.wallet_id,
       w.wallet_type,
       w.label,
       w.currency_code,
       w.balance,
       w.held_amount,
       w.balance - w.held_amount AS available_balance,
       w.status                  AS wallet_status,
       u.user_id,
       u.full_name,
       u.phone,
       u.user_type,
       u.kyc_tier
  FROM wlt_wallets w
  JOIN wlt_users   u ON u.user_id = w.user_id;

-- فحص 1: كل عملية لازم مجموع خصمها = مجموع إضافتها
-- النتيجة الصحيحة: صفر صفوف
CREATE OR REPLACE VIEW wlt_v_check_unbalanced_txns AS
SELECT txn_id,
       SUM(CASE WHEN entry_type = 'D' THEN amount ELSE 0 END) AS total_debit,
       SUM(CASE WHEN entry_type = 'C' THEN amount ELSE 0 END) AS total_credit
  FROM wlt_ledger_entries
 GROUP BY txn_id
HAVING SUM(CASE WHEN entry_type = 'D' THEN amount ELSE 0 END)
    <> SUM(CASE WHEN entry_type = 'C' THEN amount ELSE 0 END);

-- فحص 2: رصيد كل محفظة لازم يساوي (الإضافات - الخصومات) في الدفتر
-- النتيجة الصحيحة: صفر صفوف
CREATE OR REPLACE VIEW wlt_v_check_wallet_drift AS
SELECT w.wallet_id,
       w.balance AS stored_balance,
       NVL(l.ledger_balance, 0) AS ledger_balance
  FROM wlt_wallets w
  LEFT JOIN (
        SELECT wallet_id,
               SUM(CASE WHEN entry_type = 'C' THEN amount ELSE -amount END) AS ledger_balance
          FROM wlt_ledger_entries
         GROUP BY wallet_id
       ) l ON l.wallet_id = w.wallet_id
 WHERE w.balance <> NVL(l.ledger_balance, 0);



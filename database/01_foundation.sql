-- القيود المحاسبية لا تُعدَّل ولا تُحذف أبداً.
-- الخطأ يُصحَّح بعملية عكسية جديدة (REVERSAL) وليس بمسح التاريخ
CREATE OR REPLACE TRIGGER wlt_ledger_immutable_trg
  BEFORE UPDATE OR DELETE ON wlt_ledger_entries
BEGIN
  RAISE_APPLICATION_ERROR(-20001,
    'القيود المحاسبية غير قابلة للتعديل أو الحذف. استخدم عملية عكسية.');
END;
/

CREATE OR REPLACE TRIGGER wlt_wallets_touch_trg
  BEFORE UPDATE ON wlt_wallets
  FOR EACH ROW
BEGIN
  :NEW.updated_at := SYSTIMESTAMP;
END;

-- ---------------------------------------------------------------------
-- 1) الجداول المرجعية: العملات ومستويات التوثيق وأنواع العمليات
-- ---------------------------------------------------------------------

CREATE TABLE wlt_currencies (
  currency_code  VARCHAR2(3)   CONSTRAINT pk_wlt_currencies PRIMARY KEY,
  name_ar        VARCHAR2(50)  NOT NULL,
  symbol         VARCHAR2(10)  NOT NULL,
  decimals       NUMBER(1)     DEFAULT 3 NOT NULL
                 CONSTRAINT ck_wlt_cur_decimals CHECK (decimals BETWEEN 0 AND 3),
  is_active      CHAR(1)       DEFAULT 'Y' NOT NULL
                 CONSTRAINT ck_wlt_cur_active CHECK (is_active IN ('Y','N'))
);

CREATE TABLE wlt_kyc_tiers (
  tier_code         VARCHAR2(10)  CONSTRAINT pk_wlt_kyc_tiers PRIMARY KEY,
  name_ar           VARCHAR2(50)  NOT NULL,
  single_txn_limit  NUMBER(15,3)  NOT NULL,
  daily_limit       NUMBER(15,3)  NOT NULL,
  monthly_limit     NUMBER(15,3)  NOT NULL,
  max_balance       NUMBER(15,3)  NOT NULL,
  sort_order        NUMBER(2)     NOT NULL,
  CONSTRAINT ck_wlt_tier_limits CHECK (
        single_txn_limit > 0
    AND single_txn_limit <= daily_limit
    AND daily_limit      <= monthly_limit)
);

CREATE TABLE wlt_txn_types (
  txn_type    VARCHAR2(20)  CONSTRAINT pk_wlt_txn_types PRIMARY KEY,
  name_ar     VARCHAR2(60)  NOT NULL,
  fee_pct     NUMBER(5,3)   DEFAULT 0 NOT NULL,   -- نسبة مئوية: 0.5 تعني نصف بالمئة
  fee_fixed   NUMBER(15,3)  DEFAULT 0 NOT NULL,
  fee_min     NUMBER(15,3)  DEFAULT 0 NOT NULL,
  fee_max     NUMBER(15,3),
  counts_to_limit CHAR(1)   DEFAULT 'Y' NOT NULL
              CONSTRAINT ck_wlt_tt_limit CHECK (counts_to_limit IN ('Y','N')),
  is_active   CHAR(1)       DEFAULT 'Y' NOT NULL
              CONSTRAINT ck_wlt_tt_active CHECK (is_active IN ('Y','N')),
  CONSTRAINT ck_wlt_tt_fees CHECK (
        fee_pct BETWEEN 0 AND 100
    AND fee_fixed >= 0 AND fee_min >= 0
    AND (fee_max IS NULL OR fee_max >= fee_min))
);


-- ---------------------------------------------------------------------
-- 2) المستخدمون
--    نوع المستخدم يحدد دوره: عميل، تاجر، وكيل، مدير، أو حساب النظام
--    الـPIN لا يُخزَّن أبداً كما هو: نخزن hash مع salt
-- ---------------------------------------------------------------------

CREATE TABLE wlt_users (
  user_id              NUMBER GENERATED BY DEFAULT AS IDENTITY
                       CONSTRAINT pk_wlt_users PRIMARY KEY,
  phone                VARCHAR2(15)   NOT NULL,
  full_name            VARCHAR2(100)  NOT NULL,
  user_type            VARCHAR2(10)   DEFAULT 'CUSTOMER' NOT NULL
                       CONSTRAINT ck_wlt_users_type
                       CHECK (user_type IN ('CUSTOMER','MERCHANT','AGENT','ADMIN','SYSTEM')),
  kyc_tier             VARCHAR2(10)   DEFAULT 'BASIC' NOT NULL
                       CONSTRAINT fk_wlt_users_tier REFERENCES wlt_kyc_tiers,
  pin_hash             VARCHAR2(64),
  pin_salt             VARCHAR2(32),
  failed_pin_attempts  NUMBER(2)      DEFAULT 0 NOT NULL,
  locked_until         TIMESTAMP,
  status               VARCHAR2(10)   DEFAULT 'ACTIVE' NOT NULL
                       CONSTRAINT ck_wlt_users_status
                       CHECK (status IN ('ACTIVE','SUSPENDED','CLOSED')),
  created_at           TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_wlt_users_phone UNIQUE (phone),
  -- رقم أردني: 077 / 078 / 079 ثم 7 أرقام. حساب النظام مستثنى
  CONSTRAINT ck_wlt_users_phone CHECK (
        user_type = 'SYSTEM'
     OR REGEXP_LIKE(phone, '^07[789][0-9]{7}$')),
  -- كل مستخدم حقيقي لازم يكون عنده PIN
  CONSTRAINT ck_wlt_users_pin CHECK (
        user_type = 'SYSTEM'
     OR (pin_hash IS NOT NULL AND pin_salt IS NOT NULL))
);


-- ---------------------------------------------------------------------
-- 3) المحافظ
--    المستخدم الواحد يمكن أن يملك عدة محافظ: رئيسية، ادخار، أبناء، ضمان
--    القاعدة الذهبية: الرصيد لا ينزل تحت المبلغ المحجوز
--    (إلا محافظ النظام التي تمثل المال الداخل من خارج المحفظة)
-- ---------------------------------------------------------------------

CREATE TABLE wlt_wallets (
  wallet_id       NUMBER GENERATED BY DEFAULT AS IDENTITY
                  CONSTRAINT pk_wlt_wallets PRIMARY KEY,
  user_id         NUMBER        NOT NULL
                  CONSTRAINT fk_wlt_wallets_user REFERENCES wlt_users,
  wallet_type     VARCHAR2(10)  DEFAULT 'MAIN' NOT NULL
                  CONSTRAINT ck_wlt_wallets_type
                  CHECK (wallet_type IN ('MAIN','SAVINGS','CHILD','ESCROW','SYSTEM')),
  currency_code   VARCHAR2(3)   DEFAULT 'JOD' NOT NULL
                  CONSTRAINT fk_wlt_wallets_cur REFERENCES wlt_currencies,
  label           VARCHAR2(50),
  balance         NUMBER(15,3)  DEFAULT 0 NOT NULL,
  held_amount     NUMBER(15,3)  DEFAULT 0 NOT NULL
                  CONSTRAINT ck_wlt_wallets_held CHECK (held_amount >= 0),
  allow_negative  CHAR(1)       DEFAULT 'N' NOT NULL
                  CONSTRAINT ck_wlt_wallets_neg CHECK (allow_negative IN ('Y','N')),
  status          VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL
                  CONSTRAINT ck_wlt_wallets_status
                  CHECK (status IN ('ACTIVE','FROZEN','CLOSED')),
  created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_wlt_wallets_balance CHECK (
        allow_negative = 'Y'
     OR balance >= held_amount)
);

-- محفظة رئيسية واحدة فقط لكل مستخدم في كل عملة.
-- فهرس فريد على تعبير CASE: الصفوف غير الرئيسية تعطي NULL فلا تدخل في الفهرس
CREATE UNIQUE INDEX uq_wlt_wallets_main ON wlt_wallets (
  CASE WHEN wallet_type = 'MAIN' THEN user_id END,
  CASE WHEN wallet_type = 'MAIN' THEN currency_code END
);

CREATE INDEX ix_wlt_wallets_user ON wlt_wallets (user_id);


-- ---------------------------------------------------------------------
-- 4) الحركات (رأس العملية)
--    كل عملية مالية لها صف واحد هنا، ورقم مرجعي يظهر للمستخدم في الإيصال
--    idempotency_key: إذا وصل نفس الطلب مرتين (ضغطة مزدوجة، انقطاع شبكة)
--    يرفض الفهرس الفريد النسخة الثانية فلا يتكرر الخصم
-- ---------------------------------------------------------------------

CREATE SEQUENCE wlt_txn_ref_seq START WITH 1 INCREMENT BY 1 CACHE 100;

CREATE TABLE wlt_transactions (
  txn_id           NUMBER GENERATED BY DEFAULT AS IDENTITY
                   CONSTRAINT pk_wlt_transactions PRIMARY KEY,
  txn_ref          VARCHAR2(20)   NOT NULL,
  idempotency_key  VARCHAR2(64),
  txn_type         VARCHAR2(20)   NOT NULL
                   CONSTRAINT fk_wlt_txn_type REFERENCES wlt_txn_types,
  from_wallet_id   NUMBER
                   CONSTRAINT fk_wlt_txn_from REFERENCES wlt_wallets,
  to_wallet_id     NUMBER
                   CONSTRAINT fk_wlt_txn_to REFERENCES wlt_wallets,
  amount           NUMBER(15,3)   NOT NULL
                   CONSTRAINT ck_wlt_txn_amount CHECK (amount > 0),
  fee              NUMBER(15,3)   DEFAULT 0 NOT NULL
                   CONSTRAINT ck_wlt_txn_fee CHECK (fee >= 0),
  currency_code    VARCHAR2(3)    NOT NULL
                   CONSTRAINT fk_wlt_txn_cur REFERENCES wlt_currencies,
  status           VARCHAR2(10)   DEFAULT 'PENDING' NOT NULL
                   CONSTRAINT ck_wlt_txn_status
                   CHECK (status IN ('PENDING','COMPLETED','FAILED','REVERSED','HELD')),
  description      VARCHAR2(200),
  failure_reason   VARCHAR2(200),
  created_by       NUMBER
                   CONSTRAINT fk_wlt_txn_user REFERENCES wlt_users,
  created_at       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  completed_at     TIMESTAMP,
  CONSTRAINT uq_wlt_txn_ref UNIQUE (txn_ref),
  CONSTRAINT uq_wlt_txn_idem UNIQUE (idempotency_key),
  CONSTRAINT ck_wlt_txn_wallets CHECK (
        from_wallet_id IS NOT NULL OR to_wallet_id IS NOT NULL),
  CONSTRAINT ck_wlt_txn_self CHECK (
        from_wallet_id IS NULL OR to_wallet_id IS NULL
     OR from_wallet_id <> to_wallet_id)
);

-- لعرض "آخر حركاتي" بسرعة: الفهرس مرتب حسب المحفظة ثم الوقت
CREATE INDEX ix_wlt_txn_from ON wlt_transactions (from_wallet_id, created_at);
CREATE INDEX ix_wlt_txn_to   ON wlt_transactions (to_wallet_id,   created_at);
CREATE INDEX ix_wlt_txn_type ON wlt_transactions (txn_type);


-- ---------------------------------------------------------------------
-- 5) دفتر القيود المزدوج  (قلب النظام)
--    كل عملية تُكتب كقيدين على الأقل: خصم (D) من محفظة وإضافة (C) لأخرى
--    مجموع الخصم = مجموع الإضافة دائماً، فالمال لا يُخلق ولا يختفي
--    balance_after: الرصيد بعد القيد، يعطيك كشف حساب فوري بدون حساب
-- ---------------------------------------------------------------------

CREATE TABLE wlt_ledger_entries (
  entry_id       NUMBER GENERATED BY DEFAULT AS IDENTITY
                 CONSTRAINT pk_wlt_ledger PRIMARY KEY,
  txn_id         NUMBER        NOT NULL
                 CONSTRAINT fk_wlt_ledger_txn REFERENCES wlt_transactions,
  wallet_id      NUMBER        NOT NULL
                 CONSTRAINT fk_wlt_ledger_wallet REFERENCES wlt_wallets,
  entry_type     CHAR(1)       NOT NULL
                 CONSTRAINT ck_wlt_ledger_type CHECK (entry_type IN ('D','C')),
  amount         NUMBER(15,3)  NOT NULL
                 CONSTRAINT ck_wlt_ledger_amount CHECK (amount > 0),
  balance_after  NUMBER(15,3)  NOT NULL,
  created_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

-- فهرس على كل مفتاح أجنبي: يمنع قفل الجدول كاملاً عند حذف/تعديل الأب
-- ويسرّع كشف الحساب لكل محفظة
CREATE INDEX ix_wlt_ledger_wallet ON wlt_ledger_entries (wallet_id, entry_id);
CREATE INDEX ix_wlt_ledger_txn    ON wlt_ledger_entries (txn_id);



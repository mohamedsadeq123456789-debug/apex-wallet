CREATE TABLE wlt_jamiyas (
  jam_id          NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_jam PRIMARY KEY,
  owner_user_id   NUMBER        NOT NULL CONSTRAINT fk_wlt_jam_owner REFERENCES wlt_users,
  name            VARCHAR2(80)  NOT NULL,
  installment     NUMBER(15,3)  NOT NULL CONSTRAINT ck_wlt_jam_amount CHECK (installment > 0),
  members_target  NUMBER(3)     NOT NULL CONSTRAINT ck_wlt_jam_members CHECK (members_target BETWEEN 2 AND 24),
  frequency       VARCHAR2(10)  NOT NULL CONSTRAINT ck_wlt_jam_freq CHECK (frequency IN ('WEEKLY','MONTHLY')),
  start_date      DATE          NOT NULL,
  invite_code     VARCHAR2(8)   NOT NULL CONSTRAINT uq_wlt_jam_code UNIQUE,
  escrow_wallet_id NUMBER       CONSTRAINT fk_wlt_jam_escrow REFERENCES wlt_wallets,
  current_round   NUMBER(3)     DEFAULT 0 NOT NULL,
  last_auto_run   DATE,
  status          VARCHAR2(10)  DEFAULT 'FORMING' NOT NULL
                  CONSTRAINT ck_wlt_jam_status CHECK (status IN ('FORMING','ACTIVE','COMPLETED','CANCELLED')),
  created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_wlt_jam_owner  ON wlt_jamiyas (owner_user_id);
CREATE INDEX ix_wlt_jam_escrow ON wlt_jamiyas (escrow_wallet_id);
CREATE INDEX ix_wlt_jam_status ON wlt_jamiyas (status);

CREATE TABLE wlt_jamiya_members (
  jam_id     NUMBER     NOT NULL CONSTRAINT fk_wlt_jm_jam REFERENCES wlt_jamiyas,
  user_id    NUMBER     NOT NULL CONSTRAINT fk_wlt_jm_user REFERENCES wlt_users,
  turn_no    NUMBER(3),
  joined_at  TIMESTAMP  DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_wlt_jm PRIMARY KEY (jam_id, user_id)
);
CREATE INDEX ix_wlt_jm_user ON wlt_jamiya_members (user_id);

CREATE TABLE wlt_jamiya_rounds (
  jam_id           NUMBER     NOT NULL CONSTRAINT fk_wlt_jr_jam REFERENCES wlt_jamiyas,
  round_no         NUMBER(3)  NOT NULL,
  due_date         DATE       NOT NULL,
  receiver_user_id NUMBER     NOT NULL CONSTRAINT fk_wlt_jr_user REFERENCES wlt_users,
  status           VARCHAR2(10) DEFAULT 'OPEN' NOT NULL CONSTRAINT ck_wlt_jr_status CHECK (status IN ('OPEN','PAID_OUT')),
  payout_txn_id    NUMBER     CONSTRAINT fk_wlt_jr_txn REFERENCES wlt_transactions,
  CONSTRAINT pk_wlt_jr PRIMARY KEY (jam_id, round_no)
);
CREATE INDEX ix_wlt_jr_user ON wlt_jamiya_rounds (receiver_user_id);
CREATE INDEX ix_wlt_jr_txn  ON wlt_jamiya_rounds (payout_txn_id);

CREATE TABLE wlt_jamiya_payments (
  jam_id    NUMBER     NOT NULL,
  round_no  NUMBER(3)  NOT NULL,
  user_id   NUMBER     NOT NULL CONSTRAINT fk_wlt_jp_user REFERENCES wlt_users,
  txn_id    NUMBER     NOT NULL CONSTRAINT fk_wlt_jp_txn REFERENCES wlt_transactions,
  paid_at   TIMESTAMP  DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_wlt_jp PRIMARY KEY (jam_id, round_no, user_id),
  CONSTRAINT fk_wlt_jp_round FOREIGN KEY (jam_id, round_no) REFERENCES wlt_jamiya_rounds
);
CREATE INDEX ix_wlt_jp_user ON wlt_jamiya_payments (user_id);
CREATE INDEX ix_wlt_jp_txn  ON wlt_jamiya_payments (txn_id);


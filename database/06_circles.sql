  -- العيدية
  -- -----------------------------------------------------------------
  FUNCTION create_envelope (p_sender_phone VARCHAR2, p_total NUMBER, p_shares NUMBER, p_mode VARCHAR2,
                            p_message VARCHAR2, p_theme VARCHAR2 DEFAULT 'EID', p_hours NUMBER DEFAULT 24) RETURN VARCHAR2 IS
    l_s    wlt_v_wallets%ROWTYPE := user_of(p_sender_phone);
    l_code VARCHAR2(8) := new_code('E');
    l_w    NUMBER;
    l_id   NUMBER;
    l_ref  VARCHAR2(20);
    l_rem  NUMBER := p_total;
    l_amt  NUMBER;
    l_k    NUMBER;
  BEGIN
    IF p_total IS NULL OR p_total <= 0 OR p_total <> ROUND(p_total, 3) THEN
      fail(wallet_core_pkg.c_err_bad_amount, 'أدخل مبلغ العيدية بشكل صحيح');
    END IF;
    IF p_shares IS NULL OR p_shares NOT BETWEEN 1 AND 50 OR p_shares <> TRUNC(p_shares) THEN
      fail(c_err_env, 'عدد الأشخاص بين 1 و 50');
    END IF;
    IF p_total < p_shares * c_min_share THEN
      fail(c_err_env, 'المبلغ قليل: أقل حصة 100 فلس، تحتاج ' || money(p_shares * c_min_share) || ' على الأقل');
    END IF;
    IF p_mode NOT IN ('RANDOM','EQUAL') THEN fail(c_err_env, 'اختر طريقة التوزيع'); END IF;

    l_w := new_escrow('عيدية ' || l_code);
    l_ref := wallet_core_pkg.transfer(
               p_from_wallet => l_s.wallet_id, p_to_wallet => l_w, p_amount => p_total,
               p_txn_type => 'EIDIYA', p_description => 'عيدية ' || l_code, p_commit => FALSE);
    INSERT INTO wlt_envelopes (code, sender_user_id, total_amount, shares, split_mode, message, theme,
                               escrow_wallet_id, fund_txn_id, expires_at)
    VALUES (l_code, l_s.user_id, p_total, p_shares, p_mode, SUBSTR(p_message, 1, 150), NVL(p_theme, 'EID'),
            l_w, ref_id(l_ref), SYSTIMESTAMP + NUMTODSINTERVAL(p_hours, 'HOUR'))
    RETURNING env_id INTO l_id;

    -- الحصص تُحسب مسبقاً: متساوية، أو عشوائية بطريقة "ضعف المتوسط"
    -- كل حصة عشوائية بين 0.100 وضعف متوسط الباقي، فلا يأخذ أحد كل شيء
    FOR i IN 1 .. p_shares LOOP
      l_k := p_shares - i + 1;
      IF i = p_shares THEN
        l_amt := l_rem;
      ELSIF p_mode = 'EQUAL' THEN
        l_amt := TRUNC(p_total / p_shares, 3);
      ELSE
        l_amt := ROUND(DBMS_RANDOM.VALUE(c_min_share, GREATEST(c_min_share, l_rem / l_k * 2)), 3);
        l_amt := GREATEST(c_min_share, LEAST(l_amt, l_rem - c_min_share * (l_k - 1)));
      END IF;
      INSERT INTO wlt_envelope_shares (env_id, share_no, amount) VALUES (l_id, i, l_amt);
      l_rem := l_rem - l_amt;
    END LOOP;
    COMMIT;
    RETURN l_code;
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
  END create_envelope;

  FUNCTION claim_envelope (p_phone VARCHAR2, p_code VARCHAR2, p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
    l_u     wlt_v_wallets%ROWTYPE := user_of(p_phone);
    l_e     wlt_envelopes%ROWTYPE;
    l_share NUMBER;
    l_amt   NUMBER;
    l_ref   VARCHAR2(20);
    l_left  NUMBER;
    l_snd   wlt_v_wallets%ROWTYPE;
    CURSOR c_free (p_env NUMBER) IS
      SELECT share_no, amount FROM wlt_envelope_shares
       WHERE env_id = p_env AND claimed_by IS NULL ORDER BY share_no FOR UPDATE SKIP LOCKED;
  BEGIN
    BEGIN
      SELECT * INTO l_e FROM wlt_envelopes WHERE code = UPPER(TRIM(p_code));
    EXCEPTION WHEN NO_DATA_FOUND THEN fail(c_err_env, 'لا توجد عيدية بهذا الكود');
    END;
    IF l_e.sender_user_id = l_u.user_id THEN fail(c_err_env, 'لا يمكنك فتح عيديتك بنفسك 😄'); END IF;
    BEGIN
      SELECT t.txn_ref INTO l_ref FROM wlt_envelope_shares s JOIN wlt_transactions t ON t.txn_id = s.txn_id
       WHERE s.env_id = l_e.env_id AND s.claimed_by = l_u.user_id;
      RETURN l_ref;   -- فتحها مسبقاً: نرجع نفس الإيصال
    EXCEPTION WHEN NO_DATA_FOUND THEN NULL;
    END;
    IF l_e.status <> 'ACTIVE' OR l_e.expires_at < SYSTIMESTAMP THEN fail(c_err_env, 'انتهت هذه العيدية'); END IF;

    OPEN c_free(l_e.env_id);
    FETCH c_free INTO l_share, l_amt;
    IF c_free%NOTFOUND THEN CLOSE c_free; fail(c_err_env, 'وصلت متأخراً، فُتحت كل الحصص 😅'); END IF;
    CLOSE c_free;

    l_ref := wallet_core_pkg.transfer(
               p_from_wallet => l_e.escrow_wallet_id, p_to_wallet => l_u.wallet_id, p_amount => l_amt,
               p_txn_type => 'EIDIYA_CLAIM', p_idem_key => p_idem,
               p_description => NVL(l_e.message, 'عيدية'), p_commit => FALSE);
    UPDATE wlt_envelope_shares SET claimed_by = l_u.user_id, claimed_at = SYSTIMESTAMP, txn_id = ref_id(l_ref)
     WHERE env_id = l_e.env_id AND share_no = l_share;
    SELECT COUNT(*) INTO l_left FROM wlt_envelope_shares WHERE env_id = l_e.env_id AND claimed_by IS NULL;
    IF l_left = 0 THEN UPDATE wlt_envelopes SET status = 'FINISHED' WHERE env_id = l_e.env_id; END IF;
    wallet_social_pkg.notify(l_e.sender_user_id, 'EIDIYA', l_u.shown_name || ' فتح عيديتك 🎁',
      'حصل على ' || money(l_amt) || ' د.أ · باقي ' || l_left || ' حصص', 13);
    COMMIT;
    RETURN l_ref;
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    IF SQLCODE = -1 THEN fail(c_err_env, 'فتحت هذه العيدية مسبقاً'); END IF;
    RAISE;
  END claim_envelope;

  -- -----------------------------------------------------------------
  -- المهمة المجدولة: تحصيل أقساط الجمعيات المستحقة + استرجاع العيديات المنتهية
  -- -----------------------------------------------------------------
  FUNCTION run_due RETURN NUMBER IS
    l_done NUMBER := 0;
    l_ref  VARCHAR2(20);
    l_left NUMBER;
    l_snd  wlt_v_wallets%ROWTYPE;
  BEGIN
    FOR j IN (SELECT j.jam_id, j.name, j.installment, j.current_round
                FROM wlt_jamiyas j JOIN wlt_jamiya_rounds r ON r.jam_id = j.jam_id AND r.round_no = j.current_round
               WHERE j.status = 'ACTIVE' AND r.due_date <= SYSDATE
                 AND (j.last_auto_run IS NULL OR j.last_auto_run < TRUNC(SYSDATE))) LOOP
      FOR m IN (SELECT mm.user_id, u.phone FROM wlt_jamiya_members mm JOIN wlt_users u ON u.user_id = mm.user_id
                 WHERE mm.jam_id = j.jam_id
                   AND NOT EXISTS (SELECT 1 FROM wlt_jamiya_payments p
                                    WHERE p.jam_id = j.jam_id AND p.round_no = j.current_round AND p.user_id = mm.user_id)) LOOP
        BEGIN
          l_ref := pay_installment(m.phone, j.jam_id);
          l_done := l_done + 1;
        EXCEPTION WHEN OTHERS THEN
          wallet_social_pkg.notify(m.user_id, 'JAMIYA', 'تعذّر خصم قسط جمعية ' || j.name,
            REGEXP_REPLACE(REGEXP_SUBSTR(SQLERRM, '^[^' || CHR(10) || ']+'), '^ORA-\d+: ', '') || ' · اشحن رصيدك وادفع من صفحة الجمعية', 12);
          COMMIT;
        END;
      END LOOP;
      UPDATE wlt_jamiyas SET last_auto_run = SYSDATE WHERE jam_id = j.jam_id;
      COMMIT;
    END LOOP;

    FOR x IN (SELECT env_id FROM wlt_envelopes WHERE status = 'ACTIVE' AND expires_at < SYSTIMESTAMP) LOOP
     DECLARE
      e wlt_envelopes%ROWTYPE;
     BEGIN
      SELECT * INTO e FROM wlt_envelopes WHERE env_id = x.env_id AND status = 'ACTIVE' FOR UPDATE SKIP LOCKED;
      SELECT NVL(SUM(amount), 0) INTO l_left FROM wlt_envelope_shares WHERE env_id = e.env_id AND claimed_by IS NULL;
      IF l_left > 0 THEN
        l_snd := user_by_id(e.sender_user_id);
        l_ref := wallet_core_pkg.transfer(
                   p_from_wallet => e.escrow_wallet_id, p_to_wallet => l_snd.wallet_id, p_amount => l_left,
                   p_txn_type => 'REFUND', p_idem_key => 'ENVREF-' || e.env_id,
                   p_description => 'استرجاع عيدية ' || e.code || ' غير مفتوحة', p_commit => FALSE);
      END IF;
      UPDATE wlt_envelopes SET status = 'REFUNDED' WHERE env_id = e.env_id;
      COMMIT;
     EXCEPTION WHEN NO_DATA_FOUND THEN NULL;
     END;
    END LOOP;
    RETURN l_done;
  END run_due;

  PROCEDURE run_job IS
    l NUMBER;
  BEGIN
    l := run_due;
  END run_job;

END wallet_circle_pkg;

  sender_user_id   NUMBER        NOT NULL CONSTRAINT fk_wlt_env_sender REFERENCES wlt_users,
  total_amount     NUMBER(15,3)  NOT NULL CONSTRAINT ck_wlt_env_total CHECK (total_amount > 0),
  shares           NUMBER(3)     NOT NULL CONSTRAINT ck_wlt_env_shares CHECK (shares BETWEEN 1 AND 50),
  split_mode       VARCHAR2(10)  NOT NULL CONSTRAINT ck_wlt_env_mode CHECK (split_mode IN ('RANDOM','EQUAL')),
  message          VARCHAR2(150),
  theme            VARCHAR2(10)  DEFAULT 'EID' NOT NULL CONSTRAINT ck_wlt_env_theme CHECK (theme IN ('EID','GRAD','BDAY')),
  escrow_wallet_id NUMBER        NOT NULL CONSTRAINT fk_wlt_env_escrow REFERENCES wlt_wallets,
  fund_txn_id      NUMBER        CONSTRAINT fk_wlt_env_txn REFERENCES wlt_transactions,
  expires_at       TIMESTAMP     NOT NULL,
  status           VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL

CREATE OR REPLACE PACKAGE BODY wallet_circle_pkg AS
  c_min_share CONSTANT NUMBER := 0.1;

  PROCEDURE fail (p_code PLS_INTEGER, p_msg VARCHAR2) IS
  BEGIN RAISE_APPLICATION_ERROR(p_code, p_msg); END;

  FUNCTION money (p NUMBER) RETURN VARCHAR2 IS
  BEGIN RETURN TO_CHAR(p, 'FM999G999G990D000', 'NLS_NUMERIC_CHARACTERS=''.,'''); END;

  FUNCTION user_of (p_phone VARCHAR2) RETURN wlt_v_wallets%ROWTYPE IS
    l wlt_v_wallets%ROWTYPE;
  BEGIN
    SELECT * INTO l FROM wlt_v_wallets
     WHERE phone = p_phone AND wallet_type = 'MAIN' AND currency_code = 'JOD' AND user_type <> 'SYSTEM';
    RETURN l;
  EXCEPTION WHEN NO_DATA_FOUND THEN
    fail(wallet_core_pkg.c_err_not_found, 'الرقم ' || p_phone || ' غير مسجّل في المحفظة');
    RETURN l;
  END user_of;

  FUNCTION user_by_id (p_id NUMBER) RETURN wlt_v_wallets%ROWTYPE IS
    l wlt_v_wallets%ROWTYPE;
  BEGIN
    SELECT * INTO l FROM wlt_v_wallets WHERE user_id = p_id AND wallet_type = 'MAIN' AND currency_code = 'JOD';
    RETURN l;
  END user_by_id;

  FUNCTION new_code (p_prefix VARCHAR2) RETURN VARCHAR2 IS
    l VARCHAR2(8);
    n NUMBER;
  BEGIN
    LOOP
      l := p_prefix || TRANSLATE(DBMS_RANDOM.STRING('X', 5), '0O1I', '7K9P');
      SELECT COUNT(*) INTO n FROM (SELECT invite_code c FROM wlt_jamiyas UNION ALL SELECT code FROM wlt_envelopes) WHERE c = l;
      EXIT WHEN n = 0;
    END LOOP;
    RETURN l;
  END new_code;

  FUNCTION new_escrow (p_label VARCHAR2) RETURN NUMBER IS
    l_sys NUMBER;
    l_w   NUMBER;
  BEGIN
    SELECT MIN(user_id) INTO l_sys FROM wlt_users WHERE user_type = 'SYSTEM';
    INSERT INTO wlt_wallets (user_id, wallet_type, label) VALUES (l_sys, 'ESCROW', SUBSTR(p_label, 1, 50))
    RETURNING wallet_id INTO l_w;
    RETURN l_w;
  END new_escrow;

  FUNCTION ref_id (p_ref VARCHAR2) RETURN NUMBER IS
    l NUMBER;
  BEGIN
    SELECT txn_id INTO l FROM wlt_transactions WHERE txn_ref = p_ref;
    RETURN l;
  END ref_id;

  -- -----------------------------------------------------------------
  -- الجمعية
  -- -----------------------------------------------------------------
  FUNCTION create_jamiya (p_owner_phone VARCHAR2, p_name VARCHAR2, p_amount NUMBER, p_members NUMBER,
                          p_frequency VARCHAR2, p_start DATE) RETURN VARCHAR2 IS
    l_o    wlt_v_wallets%ROWTYPE := user_of(p_owner_phone);
    l_id   NUMBER;
    l_code VARCHAR2(8) := new_code('J');
  BEGIN
    IF NOT REGEXP_LIKE(NVL(TRIM(p_name), ' '), '\S') THEN fail(c_err_jam, 'اكتب اسماً للجمعية'); END IF;
    IF p_amount IS NULL OR p_amount <= 0 OR p_amount <> ROUND(p_amount, 3) THEN
      fail(wallet_core_pkg.c_err_bad_amount, 'أدخل قيمة القسط بشكل صحيح');
    END IF;
    IF p_members IS NULL OR p_members NOT BETWEEN 2 AND 24 THEN fail(c_err_jam, 'عدد الأعضاء بين 2 و 24'); END IF;
    IF p_frequency NOT IN ('WEEKLY','MONTHLY') THEN fail(c_err_jam, 'اختر أسبوعية أو شهرية'); END IF;
    IF p_start < TRUNC(SYSDATE) THEN fail(c_err_jam, 'تاريخ البداية لا يكون في الماضي'); END IF;

    INSERT INTO wlt_jamiyas (owner_user_id, name, installment, members_target, frequency, start_date, invite_code)
    VALUES (l_o.user_id, SUBSTR(TRIM(p_name), 1, 80), p_amount, p_members, p_frequency, TRUNC(p_start), l_code)
    RETURNING jam_id INTO l_id;
    INSERT INTO wlt_jamiya_members (jam_id, user_id) VALUES (l_id, l_o.user_id);
    COMMIT;
    RETURN l_code;
  END create_jamiya;

  FUNCTION join_jamiya (p_phone VARCHAR2, p_code VARCHAR2) RETURN NUMBER IS
    l_u wlt_v_wallets%ROWTYPE := user_of(p_phone);
    l_j wlt_jamiyas%ROWTYPE;
    l_n NUMBER;
  BEGIN
    BEGIN
      SELECT * INTO l_j FROM wlt_jamiyas WHERE invite_code = UPPER(TRIM(p_code)) FOR UPDATE;
    EXCEPTION WHEN NO_DATA_FOUND THEN
      fail(c_err_jam, 'لا توجد جمعية بهذا الكود');
    END;
    IF l_j.status <> 'FORMING' THEN fail(c_err_jam, 'هذه الجمعية بدأت ولا تقبل أعضاء جدداً'); END IF;
    SELECT COUNT(*) INTO l_n FROM wlt_jamiya_members WHERE jam_id = l_j.jam_id AND user_id = l_u.user_id;
    IF l_n > 0 THEN fail(c_err_jam, 'أنت عضو في هذه الجمعية مسبقاً'); END IF;
    SELECT COUNT(*) INTO l_n FROM wlt_jamiya_members WHERE jam_id = l_j.jam_id;
    IF l_n >= l_j.members_target THEN fail(c_err_jam, 'الجمعية مكتملة العدد'); END IF;
    INSERT INTO wlt_jamiya_members (jam_id, user_id) VALUES (l_j.jam_id, l_u.user_id);
    wallet_social_pkg.notify(l_j.owner_user_id, 'JAMIYA', l_u.shown_name || ' انضم لجمعية ' || l_j.name,
                             'الأعضاء الآن ' || (l_n + 1) || ' من ' || l_j.members_target, 12);
    COMMIT;
    RETURN l_j.jam_id;
  END join_jamiya;

  PROCEDURE start_jamiya (p_owner_phone VARCHAR2, p_jam_id NUMBER, p_shuffle BOOLEAN DEFAULT TRUE) IS
    l_o   wlt_v_wallets%ROWTYPE := user_of(p_owner_phone);
    l_j   wlt_jamiyas%ROWTYPE;
    l_n   NUMBER;
    l_t   NUMBER := 0;
    l_start DATE;
  BEGIN
    BEGIN
      SELECT * INTO l_j FROM wlt_jamiyas WHERE jam_id = p_jam_id AND owner_user_id = l_o.user_id FOR UPDATE;
    EXCEPTION WHEN NO_DATA_FOUND THEN
      fail(c_err_jam, 'الجمعية غير موجودة أو لست منظّمها');
    END;
    IF l_j.status <> 'FORMING' THEN fail(c_err_jam, 'الجمعية بدأت مسبقاً'); END IF;
    SELECT COUNT(*) INTO l_n FROM wlt_jamiya_members WHERE jam_id = l_j.jam_id;
    IF l_n < 2 THEN fail(c_err_jam, 'تحتاج عضوين على الأقل'); END IF;
    l_start := GREATEST(l_j.start_date, TRUNC(SYSDATE));

    -- ترتيب الأدوار: قرعة عشوائية أو حسب أسبقية الانضمام
    FOR m IN (SELECT user_id FROM wlt_jamiya_members WHERE jam_id = l_j.jam_id
               ORDER BY CASE WHEN p_shuffle THEN DBMS_RANDOM.VALUE ELSE 0 END, joined_at) LOOP
      l_t := l_t + 1;
      UPDATE wlt_jamiya_members SET turn_no = l_t WHERE jam_id = l_j.jam_id AND user_id = m.user_id;
      INSERT INTO wlt_jamiya_rounds (jam_id, round_no, due_date, receiver_user_id)
      VALUES (l_j.jam_id, l_t,
              CASE l_j.frequency WHEN 'WEEKLY' THEN l_start + 7 * (l_t - 1) ELSE ADD_MONTHS(l_start, l_t - 1) END,
              m.user_id);
      wallet_social_pkg.notify(m.user_id, 'JAMIYA', 'بدأت جمعية ' || l_j.name,
        'دورك رقم ' || l_t || ' · القسط ' || money(l_j.installment) || ' د.أ · تستلم ' || money(l_j.installment * l_n) || ' د.أ', 12);
    END LOOP;

    UPDATE wlt_jamiyas
       SET status = 'ACTIVE', members_target = l_n, current_round = 1, start_date = l_start,
           escrow_wallet_id = new_escrow('جمعية: ' || l_j.name)
     WHERE jam_id = l_j.jam_id;
    COMMIT;
  END start_jamiya;

  -- يصرف الدور لصاحبه عندما يكتمل دفع كل الأعضاء
  PROCEDURE try_payout (p_jam_id NUMBER) IS
    l_j   wlt_jamiyas%ROWTYPE;
    l_r   wlt_jamiya_rounds%ROWTYPE;
    l_n   NUMBER;
    l_ref VARCHAR2(20);
    l_rcv wlt_v_wallets%ROWTYPE;
  BEGIN
    SELECT * INTO l_j FROM wlt_jamiyas WHERE jam_id = p_jam_id FOR UPDATE;
    IF l_j.status <> 'ACTIVE' THEN RETURN; END IF;
    SELECT * INTO l_r FROM wlt_jamiya_rounds WHERE jam_id = p_jam_id AND round_no = l_j.current_round;
    SELECT COUNT(*) INTO l_n FROM wlt_jamiya_payments WHERE jam_id = p_jam_id AND round_no = l_r.round_no;
    IF l_n < l_j.members_target OR l_r.status = 'PAID_OUT' THEN RETURN; END IF;

    l_rcv := user_by_id(l_r.receiver_user_id);
    l_ref := wallet_core_pkg.transfer(
               p_from_wallet => l_j.escrow_wallet_id, p_to_wallet => l_rcv.wallet_id,
               p_amount => l_j.installment * l_j.members_target, p_txn_type => 'JAMIYA_PAYOUT',
               p_idem_key => 'JAMPAY-' || p_jam_id || '-' || l_r.round_no,
               p_description => 'جمعية ' || l_j.name || ' · الدور ' || l_r.round_no, p_commit => FALSE);
    UPDATE wlt_jamiya_rounds SET status = 'PAID_OUT', payout_txn_id = ref_id(l_ref)
     WHERE jam_id = p_jam_id AND round_no = l_r.round_no;
    UPDATE wlt_jamiyas
       SET current_round = CASE WHEN l_r.round_no < members_target THEN l_r.round_no + 1 ELSE current_round END,
           status = CASE WHEN l_r.round_no >= members_target THEN 'COMPLETED' ELSE status END
     WHERE jam_id = p_jam_id;
    FOR m IN (SELECT user_id FROM wlt_jamiya_members WHERE jam_id = p_jam_id AND user_id <> l_r.receiver_user_id) LOOP
      wallet_social_pkg.notify(m.user_id, 'JAMIYA', 'جمعية ' || l_j.name || ': استلم ' || l_rcv.shown_name || ' دوره',
        CASE WHEN l_r.round_no >= l_j.members_target THEN 'اكتملت الجمعية 🎉' ELSE 'الدور التالي رقم ' || (l_r.round_no + 1) END, 12);
    END LOOP;
  END try_payout;

  FUNCTION pay_installment (p_phone VARCHAR2, p_jam_id NUMBER, p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
    l_u   wlt_v_wallets%ROWTYPE := user_of(p_phone);
    l_j   wlt_jamiyas%ROWTYPE;
    l_n   NUMBER;
    l_ref VARCHAR2(20);
  BEGIN
    BEGIN
      SELECT * INTO l_j FROM wlt_jamiyas WHERE jam_id = p_jam_id FOR UPDATE;
    EXCEPTION WHEN NO_DATA_FOUND THEN fail(c_err_jam, 'الجمعية غير موجودة');
    END;
    IF l_j.status <> 'ACTIVE' THEN fail(c_err_jam, 'الجمعية ليست فعّالة الآن'); END IF;
    SELECT COUNT(*) INTO l_n FROM wlt_jamiya_members WHERE jam_id = p_jam_id AND user_id = l_u.user_id;
    IF l_n = 0 THEN fail(c_err_jam, 'لست عضواً في هذه الجمعية'); END IF;
    SELECT COUNT(*) INTO l_n FROM wlt_jamiya_payments
     WHERE jam_id = p_jam_id AND round_no = l_j.current_round AND user_id = l_u.user_id;
    IF l_n > 0 THEN fail(c_err_jam, 'دفعت قسط هذا الدور مسبقاً'); END IF;

    l_ref := wallet_core_pkg.transfer(
               p_from_wallet => l_u.wallet_id, p_to_wallet => l_j.escrow_wallet_id,
               p_amount => l_j.installment, p_txn_type => 'JAMIYA',
               p_idem_key => NVL(p_idem, 'JAM-' || p_jam_id || '-' || l_j.current_round || '-' || l_u.user_id),
               p_description => 'جمعية ' || l_j.name || ' · الدور ' || l_j.current_round, p_commit => FALSE);
    INSERT INTO wlt_jamiya_payments (jam_id, round_no, user_id, txn_id)
    VALUES (p_jam_id, l_j.current_round, l_u.user_id, ref_id(l_ref));
    try_payout(p_jam_id);
    COMMIT;
    RETURN l_ref;
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
  END pay_installment;


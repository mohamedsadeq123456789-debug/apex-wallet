    c owa_cookie.cookie;
  BEGIN
    c := owa_cookie.get('WLT_DEV');
    IF c.num_vals > 0 AND REGEXP_LIKE(c.vals(1), '^[A-Za-z0-9]{24,64}$') THEN RETURN c.vals(1); END IF;
    RETURN NULL;
  EXCEPTION WHEN OTHERS THEN RETURN NULL;
  END device_token;

  FUNCTION device_ok (p_user_id NUMBER) RETURN BOOLEAN IS
    l_t VARCHAR2(64);
    n   NUMBER;
  BEGIN
    IF setting('DEVICE_CHECK', 'ON') <> 'ON' THEN RETURN TRUE; END IF;
    l_t := device_token;
    IF l_t IS NULL THEN RETURN FALSE; END IF;
    SELECT COUNT(*) INTO n FROM wlt_devices
     WHERE user_id = p_user_id AND dev_hash = wallet_otp_pkg.sha(l_t) AND status = 'TRUSTED';
    RETURN n > 0;
  END device_ok;

  FUNCTION device_label (p_ua VARCHAR2) RETURN VARCHAR2 IS
    b VARCHAR2(20); o VARCHAR2(20);
  BEGIN
    b := CASE WHEN p_ua LIKE '%Edg/%' THEN 'Edge' WHEN p_ua LIKE '%OPR/%' THEN 'Opera' WHEN p_ua LIKE '%SamsungBrowser%' THEN 'Samsung'
              WHEN p_ua LIKE '%Firefox/%' THEN 'Firefox' WHEN p_ua LIKE '%Chrome/%' THEN 'Chrome' WHEN p_ua LIKE '%Safari/%' THEN 'Safari'
              ELSE 'متصفح' END;
    o := CASE WHEN p_ua LIKE '%Android%' THEN 'Android' WHEN p_ua LIKE '%iPhone%' THEN 'iPhone' WHEN p_ua LIKE '%iPad%' THEN 'iPad'
              WHEN p_ua LIKE '%Windows%' THEN 'Windows' WHEN p_ua LIKE '%Mac OS%' THEN 'Mac' WHEN p_ua LIKE '%Linux%' THEN 'Linux'
              ELSE 'جهاز' END;
    RETURN b || ' · ' || o;
  END device_label;

  PROCEDURE trust_device (p_user_id NUMBER, p_via VARCHAR2, p_quiet BOOLEAN DEFAULT FALSE) IS
    l_t   VARCHAR2(64) := device_token;
    l_h   VARCHAR2(64);
    l_lbl VARCHAR2(60);
    l_new BOOLEAN;
    n     NUMBER;
  BEGIN

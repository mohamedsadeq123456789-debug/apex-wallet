      END IF;
    END IF;
  END trust_device;

  PROCEDURE touch (p_user_id NUMBER) IS
    l_t VARCHAR2(64) := device_token;
  BEGIN
    IF l_t IS NOT NULL THEN
      UPDATE wlt_devices SET last_seen = SYSTIMESTAMP
       WHERE user_id = p_user_id AND dev_hash = wallet_otp_pkg.sha(l_t) AND status = 'TRUSTED';
    END IF;
  END touch;

  PROCEDURE revoke_device (p_user_id NUMBER, p_device_id NUMBER) IS
  BEGIN
    UPDATE wlt_devices SET status = 'REVOKED' WHERE device_id = p_device_id AND user_id = p_user_id AND status = 'TRUSTED';

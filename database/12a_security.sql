    WHEN NOT MATCHED THEN INSERT (user_id, dev_hash, label, via) VALUES (p_user_id, l_h, l_lbl, p_via);
    IF l_new THEN
      INSERT INTO wlt_audit_log (actor_user_id, action, entity, entity_id, details)
      VALUES (p_user_id, 'DEVICE_TRUST', 'USER', p_user_id, l_lbl || ' · ' || p_via);

  FUNCTION pepper RETURN VARCHAR2 IS
  BEGIN
    IF g_pepper IS NULL THEN
      SELECT secret_value INTO g_pepper FROM wlt_secrets WHERE secret_key = 'PIN_PEPPER';
    END IF;
    RETURN g_pepper;
  END pepper;

  -- تمديد المفتاح: كل محاولة تخمين تكلّف 30,000 عملية تجزئة، والفلفل السري يدخل في كل جولة
  FUNCTION stretch (p_salt VARCHAR2, p_inner VARCHAR2) RETURN VARCHAR2 IS
    l_seed VARCHAR2(400) := pepper || ':' || p_salt || ':' || p_inner;
    l_h    VARCHAR2(64);
  BEGIN
    WITH r (n, h) AS (
      SELECT 1, RAWTOHEX(STANDARD_HASH(l_seed, 'SHA256')) FROM dual
      UNION ALL
      SELECT n + 1, RAWTOHEX(STANDARD_HASH(h || l_seed, 'SHA256')) FROM r WHERE n < c_iter)
    SELECT h INTO l_h FROM r WHERE n = c_iter;
    RETURN l_h;
  END stretch;

  FUNCTION pin_ok (p_user wlt_users%ROWTYPE, p_pin VARCHAR2) RETURN BOOLEAN IS
    l_inner VARCHAR2(64);
  BEGIN
    IF p_user.pin_hash IS NULL OR p_pin IS NULL THEN RETURN FALSE; END IF;
    l_inner := wallet_otp_pkg.sha(p_user.pin_salt || p_pin);
    IF p_user.pin_ver = 2 THEN
      RETURN stretch(p_user.pin_salt, l_inner) = p_user.pin_hash;
    END IF;
    RETURN l_inner = p_user.pin_hash;
  END pin_ok;

  -- رمز الجهاز: رقم عشوائي يولّده المتصفح ويحفظه في cookie. نخزّن بصمته فقط، لا الرمز نفسه

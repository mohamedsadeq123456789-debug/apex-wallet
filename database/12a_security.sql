BEFORE INSERT OR UPDATE OF pin_hash ON wlt_users
FOR EACH ROW
BEGIN
  IF :new.pin_hash IS NOT NULL THEN
    :new.pin_hash := wallet_sec_pkg.stretch(:new.pin_salt, :new.pin_hash);
    :new.pin_ver  := 2;
  END IF;
END;
/

-- ترحيل كل الرموز الحالية فوراً: التجزئة القديمة تُلف بالتمديد، فلا حاجة لانتظار دخول المستخدم
UPDATE wlt_users SET pin_hash = pin_hash WHERE pin_ver = 1 AND pin_hash IS NOT NULL;
COMMIT;


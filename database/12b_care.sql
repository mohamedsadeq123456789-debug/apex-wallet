CREATE TABLE wlt_disputes (
  dispute_id  NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_disp PRIMARY KEY,
  txn_id      NUMBER        NOT NULL CONSTRAINT fk_wlt_disp_txn REFERENCES wlt_transactions,
  user_id     NUMBER        NOT NULL CONSTRAINT fk_wlt_disp_user REFERENCES wlt_users,
  reason      VARCHAR2(10)  NOT NULL CONSTRAINT ck_wlt_disp_reason CHECK (reason IN ('NOT_ME','WRONG_AMT','NOT_RECV','DUPLICATE','OTHER')),
  note        VARCHAR2(300),
  status      VARCHAR2(10)  DEFAULT 'OPEN' NOT NULL CONSTRAINT ck_wlt_disp_status CHECK (status IN ('OPEN','RESOLVED','REJECTED','REVERSED')),
  admin_id    NUMBER        CONSTRAINT fk_wlt_disp_admin REFERENCES wlt_users,
  admin_note  VARCHAR2(300),
  decided_at  TIMESTAMP,
  created_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX uq_wlt_disp_open ON wlt_disputes (CASE WHEN status = 'OPEN' THEN txn_id END, CASE WHEN status = 'OPEN' THEN user_id END);
CREATE INDEX ix_wlt_disp_txn   ON wlt_disputes (txn_id);
CREATE INDEX ix_wlt_disp_user  ON wlt_disputes (user_id);
CREATE INDEX ix_wlt_disp_admin ON wlt_disputes (admin_id);
CREATE INDEX ix_wlt_disp_stat  ON wlt_disputes (status, created_at);

CREATE TABLE wlt_kyc_docs (
  doc_id      NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_kycd PRIMARY KEY,
  req_id      NUMBER        NOT NULL CONSTRAINT fk_wlt_kycd_req REFERENCES wlt_kyc_requests,
  kind        VARCHAR2(10)  NOT NULL CONSTRAINT ck_wlt_kycd_kind CHECK (kind IN ('ID','SELFIE')),
  mime        VARCHAR2(30)  NOT NULL,
  bytes       NUMBER        NOT NULL,
  content     BLOB          NOT NULL,
  created_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_wlt_kycd UNIQUE (req_id, kind)
);

CREATE TABLE wlt_test_runs (
  run_id       NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_test_runs PRIMARY KEY,
  run_by       VARCHAR2(20)  NOT NULL,
  started_at   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  finished_at  TIMESTAMP,
  passed       NUMBER        DEFAULT 0 NOT NULL,
  failed       NUMBER        DEFAULT 0 NOT NULL,
  report       CLOB
);


CREATE OR REPLACE PACKAGE wallet_care_pkg AS
  c_err CONSTANT PLS_INTEGER := -20196;
  FUNCTION  reason_ar (p VARCHAR2) RETURN VARCHAR2;
  FUNCTION  open_dispute (p_phone VARCHAR2, p_ref VARCHAR2, p_reason VARCHAR2, p_note VARCHAR2, p_quiet BOOLEAN DEFAULT FALSE) RETURN NUMBER;
  PROCEDURE decide_dispute (p_admin_phone VARCHAR2, p_id NUMBER, p_action VARCHAR2, p_note VARCHAR2);
  FUNCTION  request_tier_docs (p_phone VARCHAR2, p_tier VARCHAR2, p_note VARCHAR2, p_id BLOB, p_selfie BLOB) RETURN NUMBER;
  FUNCTION  doc_data_url (p_req_id NUMBER, p_kind VARCHAR2) RETURN CLOB;
  PROCEDURE stmt_totals (p_wallet NUMBER, p_from TIMESTAMP, p_to TIMESTAMP,
                         p_open OUT NUMBER, p_in OUT NUMBER, p_out OUT NUMBER, p_close OUT NUMBER, p_cnt OUT NUMBER);
END wallet_care_pkg;
/

CREATE OR REPLACE PACKAGE BODY wallet_care_pkg AS
  PROCEDURE fail (p_msg VARCHAR2) IS BEGIN RAISE_APPLICATION_ERROR(c_err, p_msg); END;

  FUNCTION admin_id (p_phone VARCHAR2) RETURN NUMBER IS
    l NUMBER;
  BEGIN
    SELECT user_id INTO l FROM wlt_users WHERE phone = p_phone AND user_type = 'ADMIN' AND status = 'ACTIVE';
    RETURN l;
  EXCEPTION WHEN NO_DATA_FOUND THEN fail('للإدارة فقط'); RETURN NULL;
  END admin_id;

  FUNCTION reason_ar (p VARCHAR2) RETURN VARCHAR2 IS
  BEGIN
    RETURN CASE p WHEN 'NOT_ME' THEN 'لم أقم بهذه العملية' WHEN 'WRONG_AMT' THEN 'المبلغ غير صحيح'
                  WHEN 'NOT_RECV' THEN 'لم أستلم الخدمة أو المبلغ' WHEN 'DUPLICATE' THEN 'خُصمت مرتين' ELSE 'مشكلة أخرى' END;
  END reason_ar;

  FUNCTION open_dispute (p_phone VARCHAR2, p_ref VARCHAR2, p_reason VARCHAR2, p_note VARCHAR2, p_quiet BOOLEAN DEFAULT FALSE) RETURN NUMBER IS
    u    wlt_users%ROWTYPE;
    t    wlt_transactions%ROWTYPE;
    n    NUMBER;
    l_id NUMBER;
  BEGIN
    SELECT * INTO u FROM wlt_users WHERE phone = p_phone;
    BEGIN
      SELECT * INTO t FROM wlt_transactions WHERE txn_ref = UPPER(TRIM(p_ref));
    EXCEPTION WHEN NO_DATA_FOUND THEN fail('العملية غير موجودة');
    END;
    SELECT COUNT(*) INTO n FROM wlt_wallets WHERE user_id = u.user_id AND wallet_id IN (t.from_wallet_id, t.to_wallet_id);
    IF n = 0 THEN fail('العملية غير موجودة'); END IF;
    IF t.status <> 'COMPLETED' THEN fail('يمكن الإبلاغ عن العمليات المكتملة فقط'); END IF;
    IF t.created_at < SYSTIMESTAMP - INTERVAL '60' DAY THEN fail('مضى أكثر من 60 يوماً على العملية، تواصل مع الدعم'); END IF;
    IF p_reason IS NULL OR p_reason NOT IN ('NOT_ME','WRONG_AMT','NOT_RECV','DUPLICATE','OTHER') THEN fail('اختر سبب البلاغ'); END IF;
    IF p_reason = 'OTHER' AND TRIM(p_note) IS NULL THEN fail('اكتب تفاصيل المشكلة'); END IF;
    INSERT INTO wlt_disputes (txn_id, user_id, reason, note)
    VALUES (t.txn_id, u.user_id, p_reason, SUBSTR(REGEXP_REPLACE(TRIM(p_note), '[<>"]', ''), 1, 300))
    RETURNING dispute_id INTO l_id;
    INSERT INTO wlt_audit_log (actor_user_id, action, entity, entity_id, details)
    VALUES (u.user_id, 'DISPUTE_OPEN', 'TRANSACTION', t.txn_id, '#' || l_id || ' ' || p_reason);
    IF NOT p_quiet THEN
      FOR a IN (SELECT user_id FROM wlt_users WHERE user_type = 'ADMIN' AND status = 'ACTIVE') LOOP
        wallet_social_pkg.notify(a.user_id, 'SECURITY', '🚩 بلاغ جديد #' || l_id, reason_ar(p_reason) || ' · ' || t.txn_ref, 21);
      END LOOP;
    END IF;
    wallet_social_pkg.notify(u.user_id, 'SECURITY', '🚩 استلمنا بلاغك #' || l_id, 'سنراجع العملية ' || t.txn_ref || ' ونرد عليك هنا', 23);
    COMMIT;
    RETURN l_id;
  EXCEPTION WHEN DUP_VAL_ON_INDEX THEN ROLLBACK; fail('لديك بلاغ مفتوح على هذه العملية'); RETURN NULL;
  END open_dispute;

  PROCEDURE decide_dispute (p_admin_phone VARCHAR2, p_id NUMBER, p_action VARCHAR2, p_note VARCHAR2) IS
    l_a   NUMBER := admin_id(p_admin_phone);
    d     wlt_disputes%ROWTYPE;
    l_ref VARCHAR2(20);
    l_new VARCHAR2(20);
    l_nt  VARCHAR2(300) := SUBSTR(REGEXP_REPLACE(TRIM(p_note), '[<>"]', ''), 1, 300);
  BEGIN
    IF p_action NOT IN ('RESOLVE','REJECT','REVERSE') THEN fail('إجراء غير صالح'); END IF;
    SELECT * INTO d FROM wlt_disputes WHERE dispute_id = p_id;
    IF d.status <> 'OPEN' THEN fail('البلاغ مغلق مسبقاً'); END IF;
    IF p_action = 'REJECT' AND l_nt IS NULL THEN fail('اكتب سبب الرفض للعميل'); END IF;
    SELECT txn_ref INTO l_ref FROM wlt_transactions WHERE txn_id = d.txn_id;
    IF p_action = 'REVERSE' THEN
      -- العكس يفحص رصيد المستلم ونوع العملية ويسجل ويبلّغ المرسل بنفسه
      l_new := wallet_account_pkg.admin_reverse(p_admin_phone, l_ref, 'بلاغ #' || p_id || ': ' || NVL(l_nt, reason_ar(d.reason)));
    END IF;
    UPDATE wlt_disputes
       SET status = CASE p_action WHEN 'REVERSE' THEN 'REVERSED' WHEN 'RESOLVE' THEN 'RESOLVED' ELSE 'REJECTED' END,
           admin_id = l_a, admin_note = l_nt, decided_at = SYSTIMESTAMP
     WHERE dispute_id = p_id AND status = 'OPEN';
    IF SQL%ROWCOUNT = 0 THEN fail('البلاغ مغلق مسبقاً'); END IF;
    INSERT INTO wlt_audit_log (actor_user_id, action, entity, entity_id, details)
    VALUES (l_a, 'DISPUTE_' || p_action, 'TRANSACTION', d.txn_id, '#' || p_id || ' ' || l_nt);
    wallet_social_pkg.notify(d.user_id, 'SECURITY',
      CASE p_action WHEN 'REVERSE' THEN '✅ بلاغك #' || p_id || ': عُكست العملية وأُعيد المبلغ'
                    WHEN 'RESOLVE' THEN '✅ بلاغك #' || p_id || ': تمّ الحل'
                    ELSE 'بلاغك #' || p_id || ': راجعنا العملية ولم نجد خطأ' END,
      NVL(l_nt, l_ref), 23);
    COMMIT;
  END decide_dispute;

  FUNCTION img_mime (p BLOB) RETURN VARCHAR2 IS
    h VARCHAR2(16) := RAWTOHEX(DBMS_LOB.SUBSTR(p, 4, 1));
  BEGIN
    RETURN CASE WHEN h LIKE 'FFD8FF%' THEN 'image/jpeg' WHEN h = '89504E47' THEN 'image/png' WHEN h = '52494646' THEN 'image/webp' END;
  END img_mime;

  PROCEDURE check_img (p BLOB, p_lbl VARCHAR2) IS
    n NUMBER := NVL(DBMS_LOB.GETLENGTH(p), 0);
  BEGIN
    IF n = 0 THEN fail('أرفق ' || p_lbl); END IF;
    IF n < 5000 THEN fail(p_lbl || ': الصورة صغيرة جداً أو غير واضحة'); END IF;
    IF n > 3000000 THEN fail(p_lbl || ': الصورة أكبر من 3 ميغابايت'); END IF;
    IF img_mime(p) IS NULL THEN fail(p_lbl || ': الملف ليس صورة'); END IF;
  END check_img;

  FUNCTION request_tier_docs (p_phone VARCHAR2, p_tier VARCHAR2, p_note VARCHAR2, p_id BLOB, p_selfie BLOB) RETURN NUMBER IS
    l_id NUMBER;
    l_m1 VARCHAR2(30);
    l_m2 VARCHAR2(30);
  BEGIN
    check_img(p_id, 'صورة الهوية');
    check_img(p_selfie, 'الصورة الشخصية');
    wallet_account_pkg.request_tier(p_phone, p_tier, p_note);
    SELECT MAX(r.req_id) INTO l_id
      FROM wlt_kyc_requests r JOIN wlt_users u ON u.user_id = r.user_id
     WHERE u.phone = p_phone AND r.status = 'PENDING';
    l_m1 := img_mime(p_id); l_m2 := img_mime(p_selfie);
    INSERT INTO wlt_kyc_docs (req_id, kind, mime, bytes, content) VALUES (l_id, 'ID', l_m1, DBMS_LOB.GETLENGTH(p_id), p_id);
    INSERT INTO wlt_kyc_docs (req_id, kind, mime, bytes, content) VALUES (l_id, 'SELFIE', l_m2, DBMS_LOB.GETLENGTH(p_selfie), p_selfie);
    COMMIT;
    RETURN l_id;
  END request_tier_docs;

  FUNCTION doc_data_url (p_req_id NUMBER, p_kind VARCHAR2) RETURN CLOB IS
    l_b BLOB;
    l_m VARCHAR2(30);
  BEGIN
    SELECT content, mime INTO l_b, l_m FROM wlt_kyc_docs WHERE req_id = p_req_id AND kind = p_kind;
    RETURN 'data:' || l_m || ';base64,' || REPLACE(REPLACE(apex_web_service.blob2clobbase64(l_b), CHR(13)), CHR(10));
  EXCEPTION WHEN NO_DATA_FOUND THEN RETURN NULL;
  END doc_data_url;

  -- الأرصدة من دفتر القيود نفسه: الرصيد بعد كل قيد محفوظ، فالكشف لا يحتاج إعادة حساب
  PROCEDURE stmt_totals (p_wallet NUMBER, p_from TIMESTAMP, p_to TIMESTAMP,
                         p_open OUT NUMBER, p_in OUT NUMBER, p_out OUT NUMBER, p_close OUT NUMBER, p_cnt OUT NUMBER) IS
  BEGIN
    BEGIN
      SELECT balance_after INTO p_open FROM wlt_ledger_entries
       WHERE wallet_id = p_wallet AND created_at < p_from ORDER BY entry_id DESC FETCH FIRST 1 ROWS ONLY;
    EXCEPTION WHEN NO_DATA_FOUND THEN p_open := 0;
    END;
    SELECT NVL(SUM(CASE WHEN entry_type = 'C' THEN amount END), 0), NVL(SUM(CASE WHEN entry_type = 'D' THEN amount END), 0),
           COUNT(DISTINCT txn_id), MAX(balance_after) KEEP (DENSE_RANK LAST ORDER BY entry_id)
      INTO p_in, p_out, p_cnt, p_close
      FROM wlt_ledger_entries
     WHERE wallet_id = p_wallet AND created_at >= p_from AND created_at < p_to;
    p_close := NVL(p_close, p_open);
  END stmt_totals;
END wallet_care_pkg;
/


CREATE OR REPLACE PACKAGE wallet_test_pkg AS
  FUNCTION run_all (p_by VARCHAR2 DEFAULT 'MANUAL') RETURN NUMBER;

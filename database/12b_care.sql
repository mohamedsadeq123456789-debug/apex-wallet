  PROCEDURE api IS
    a     VARCHAR2(20)   := apex_application.g_x01;
    x2    VARCHAR2(4000) := apex_application.g_x02;
    x3    VARCHAR2(4000) := apex_application.g_x03;
    x4    VARCHAR2(4000) := apex_application.g_x04;
    u     wlt_users%ROWTYPE;
    l_id  NUMBER;
    l_c   CLOB;
    l_b1  BLOB;
    l_b2  BLOB;
    l_msg VARCHAR2(4000);
    t     wlt_test_runs%ROWTYPE;
    d     wlt_disputes%ROWTYPE;
    PROCEDURE ok IS BEGIN apex_json.open_object; apex_json.write('ok', TRUE); END;
    PROCEDURE admin_only IS BEGIN IF u.user_type <> 'ADMIN' THEN RAISE_APPLICATION_ERROR(-20196, 'للإدارة فقط'); END IF; END;
    FUNCTION f2blob (p apex_application_global.vc_arr2) RETURN BLOB IS
      c CLOB;
    BEGIN
      IF p.COUNT = 0 THEN RETURN NULL; END IF;
      DBMS_LOB.CREATETEMPORARY(c, TRUE);
      FOR i IN 1 .. p.COUNT LOOP DBMS_LOB.WRITEAPPEND(c, LENGTH(p(i)), p(i)); END LOOP;
      RETURN apex_web_service.clobbase642blob(c);
    END;
  BEGIN
    u := me;
    CASE a
      WHEN 'dspinfo' THEN
        ok;
        BEGIN
          SELECT ds.* INTO d FROM wlt_disputes ds JOIN wlt_transactions tx ON tx.txn_id = ds.txn_id
           WHERE tx.txn_ref = UPPER(TRIM(x2)) AND ds.user_id = u.user_id ORDER BY ds.dispute_id DESC FETCH FIRST 1 ROWS ONLY;
          apex_json.write('id', d.dispute_id);
          apex_json.write('status', d.status);
          apex_json.write('reason', wallet_care_pkg.reason_ar(d.reason));
          apex_json.write('reply', d.admin_note);
        EXCEPTION WHEN NO_DATA_FOUND THEN NULL;
        END;
        apex_json.close_object;
      WHEN 'dspopen' THEN
        l_id := wallet_care_pkg.open_dispute(u.phone, x2, x3, x4);
        ok; apex_json.write('id', l_id); apex_json.close_object;
      WHEN 'dspdo' THEN
        admin_only;
        wallet_care_pkg.decide_dispute(u.phone, TO_NUMBER(x2), x3, x4);
        ok; apex_json.close_object;
      WHEN 'devdel' THEN
        wallet_sec_pkg.revoke_device(u.user_id, TO_NUMBER(x2));
        ok; apex_json.close_object;
      WHEN 'kyc2' THEN
        l_b1 := f2blob(apex_application.g_f01);
        l_b2 := f2blob(apex_application.g_f02);
        l_id := wallet_care_pkg.request_tier_docs(u.phone, x2, x3, l_b1, l_b2);
        ok; apex_json.write('id', l_id); apex_json.close_object;
      WHEN 'kycdoc' THEN
        admin_only;
        l_c := wallet_care_pkg.doc_data_url(TO_NUMBER(x2), x3);
        ok; IF l_c IS NOT NULL THEN apex_json.write('url', l_c); END IF; apex_json.close_object;
      WHEN 'stmt' THEN
        IF NOT REGEXP_LIKE(x2, '^\d{4}-\d{2}$') THEN RAISE_APPLICATION_ERROR(-20196, 'شهر غير صالح'); END IF;
        ok; apex_json.write('html', stmt_html(u.user_id, x2)); apex_json.close_object;
      WHEN 'tests' THEN
        admin_only;
        l_id := wallet_test_pkg.run_all(u.phone);
        SELECT * INTO t FROM wlt_test_runs WHERE run_id = l_id;
        ok;
        apex_json.write('passed', t.passed); apex_json.write('failed', t.failed);
        apex_json.write('secs', ROUND((CAST(t.finished_at AS DATE) - CAST(t.started_at AS DATE)) * 86400, 1));
        apex_json.open_array('lines');
        FOR l IN (SELECT REGEXP_SUBSTR(t.report, '[^' || CHR(10) || ']+', 1, LEVEL) ln FROM dual
                  CONNECT BY LEVEL <= REGEXP_COUNT(t.report, CHR(10))) LOOP
          apex_json.write(l.ln);
        END LOOP;
        apex_json.close_array;
        apex_json.close_object;
      ELSE RAISE_APPLICATION_ERROR(-20199, 'عملية غير معروفة');
    END CASE;
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK;

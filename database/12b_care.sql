CREATE OR REPLACE PACKAGE BODY wallet_test_pkg AS
  g_rep CLOB;
  g_p   PLS_INTEGER;
  g_f   PLS_INTEGER;

  PROCEDURE res (p_code VARCHAR2, p_name VARCHAR2, p_ok BOOLEAN, p_info VARCHAR2 DEFAULT NULL) IS
  BEGIN
    IF p_ok THEN g_p := g_p + 1; ELSE g_f := g_f + 1; END IF;
    g_rep := g_rep || CASE WHEN p_ok THEN 'PASS' ELSE 'FAIL' END || '|' || p_code || '|' || p_name || '|' || SUBSTR(p_info, 1, 300) || CHR(10);
  END res;

  PROCEDURE err (p_code VARCHAR2, p_name VARCHAR2) IS
  BEGIN
    res(p_code, p_name, FALSE, REGEXP_REPLACE(REGEXP_SUBSTR(SQLERRM, '^[^' || CHR(10) || ']+'), '^ORA-\d+: ', ''));
  END err;

  FUNCTION bal (p_w NUMBER) RETURN NUMBER IS
    l NUMBER;
  BEGIN
    SELECT balance INTO l FROM wlt_wallets WHERE wallet_id = p_w;
    RETURN l;
  END bal;

  FUNCTION expect_err (p_sql VARCHAR2) RETURN VARCHAR2 IS
  BEGIN
    EXECUTE IMMEDIATE p_sql;
    RETURN 'NO ERROR';
  EXCEPTION WHEN OTHERS THEN
    RETURN CASE WHEN SQLCODE BETWEEN -20999 AND -20000 THEN 'OK' ELSE 'ORA' || SQLCODE END;
  END expect_err;

  FUNCTION run_all (p_by VARCHAR2 DEFAULT 'MANUAL') RETURN NUMBER IS
    l_run NUMBER;
    a     NUMBER;
    b     NUMBER;
    n     NUMBER;
    x     NUMBER; y NUMBER; z NUMBER; w NUMBER;
    r1    VARCHAR2(40); r2 VARCHAR2(40);
    s     VARCHAR2(400);
    u     wlt_users%ROWTYPE;
    l_key VARCHAR2(64);
  BEGIN
    g_rep := NULL; g_p := 0; g_f := 0;
    INSERT INTO wlt_test_runs (run_by) VALUES (SUBSTR(p_by, 1, 20)) RETURNING run_id INTO l_run;
    COMMIT;
    a := wallet_core_pkg.main_wallet('0770009001');
    b := wallet_core_pkg.main_wallet('0770009002');

    BEGIN
      SELECT COUNT(*) INTO n FROM (SELECT currency_code FROM wlt_wallets GROUP BY currency_code HAVING SUM(balance) <> 0);
      res('T01', 'الدفتر متوازن لكل عملة (مجموع الأرصدة = صفر)', n = 0, n || ' عملة غير متوازنة');
    EXCEPTION WHEN OTHERS THEN err('T01', 'الدفتر متوازن'); END;

    BEGIN
      SELECT COUNT(*) INTO n FROM wlt_v_check_unbalanced_txns;
      res('T02', 'كل عملية: مجموع المدين = مجموع الدائن', n = 0, n || ' عملية');
    EXCEPTION WHEN OTHERS THEN err('T02', 'توازن العمليات'); END;

    BEGIN
      SELECT COUNT(*) INTO n FROM wlt_v_check_wallet_drift;
      res('T03', 'رصيد كل محفظة يطابق دفتر القيود', n = 0, n || ' محفظة');
    EXCEPTION WHEN OTHERS THEN err('T03', 'تطابق الأرصدة'); END;

    BEGIN
      SELECT COUNT(*) INTO n FROM user_objects
       WHERE status <> 'VALID' AND object_type <> 'MATERIALIZED VIEW' AND (object_name LIKE 'WALLET%' OR object_name LIKE 'WLT%');
      res('T04', 'لا يوجد أي كود معطّل', n = 0, n || ' كائن');
    EXCEPTION WHEN OTHERS THEN err('T04', 'الكود سليم'); END;

    BEGIN
      SELECT COUNT(*) INTO n FROM user_scheduler_job_run_details
       WHERE job_name LIKE 'WLT%' AND job_name NOT LIKE 'WLT_STRESS%' AND status <> 'SUCCEEDED' AND log_date > SYSTIMESTAMP - INTERVAL '1' DAY;
      res('T05', 'المهام المجدولة بلا أخطاء آخر 24 ساعة', n = 0, n || ' فشل');
    EXCEPTION WHEN OTHERS THEN err('T05', 'المهام المجدولة'); END;

    BEGIN
      x := bal(a); y := bal(b);
      r1 := wallet_core_pkg.transfer(a, b, 1.111, 'TRANSFER', 'TEST-' || l_run || '-06', 'اختبار آلي');
      SELECT fee INTO z FROM wlt_transactions WHERE txn_ref = r1;
      res('T06', 'التحويل يخصم ويضيف المبلغ بالضبط', bal(a) = x - 1.111 - z AND bal(b) = y + 1.111,
          x || ' → ' || bal(a) || ' / ' || y || ' → ' || bal(b));
      r2 := wallet_core_pkg.reverse(r1, 'اختبار آلي');
      res('T07', 'عكس العملية يرجع الرصيدين كما كانا', bal(a) = x AND bal(b) = y, r2);
    EXCEPTION WHEN OTHERS THEN err('T06', 'التحويل والعكس'); END;

    BEGIN
      x := bal(a);
      l_key := 'TEST-' || l_run || '-08';
      r1 := wallet_core_pkg.transfer(a, b, 0.5, 'TRANSFER', l_key, 'اختبار آلي');
      r2 := wallet_core_pkg.transfer(a, b, 0.5, 'TRANSFER', l_key, 'اختبار آلي');
      SELECT COUNT(*) INTO n FROM wlt_transactions WHERE idempotency_key = l_key;
      res('T08', 'نفس الطلب مرتين لا يُنفَّذ مرتين', r1 = r2 AND n = 1 AND bal(a) = x - 0.5, r1 || ' / ' || r2);
      r2 := wallet_core_pkg.reverse(r1, 'اختبار آلي');
    EXCEPTION WHEN OTHERS THEN err('T08', 'منع التكرار'); END;

    BEGIN
      s := expect_err('DECLARE r VARCHAR2(40); BEGIN r := wallet_core_pkg.transfer(' || a || ', ' || b || ', 99999999, ''TRANSFER''); END;');
      res('T09', 'التحويل بأكثر من الرصيد يُرفض', s = 'OK', s);
      s := expect_err('DECLARE r VARCHAR2(40); BEGIN r := wallet_core_pkg.transfer(' || a || ', ' || b || ', 0, ''TRANSFER''); END;');
      res('T10', 'المبلغ صفر أو سالب يُرفض', s = 'OK', s);
      s := expect_err('DECLARE r VARCHAR2(40); BEGIN r := wallet_core_pkg.transfer(' || a || ', ' || a || ', 1, ''TRANSFER''); END;');
      res('T11', 'التحويل لنفس المحفظة يُرفض', s = 'OK', s);
    EXCEPTION WHEN OTHERS THEN err('T09', 'رفض المبالغ الخاطئة'); END;

    BEGIN
      res('T12', 'تشفير الرمز ثابت ويتغير مع الملح',
          wallet_sec_pkg.stretch('S1', 'X') = wallet_sec_pkg.stretch('S1', 'X') AND wallet_sec_pkg.stretch('S1', 'X') <> wallet_sec_pkg.stretch('S2', 'X')
          AND LENGTH(wallet_sec_pkg.stretch('S1', 'X')) = 64);
      u.pin_salt := 'TESTSALT'; u.pin_ver := 2;
      u.pin_hash := wallet_sec_pkg.stretch(u.pin_salt, wallet_otp_pkg.sha(u.pin_salt || '2468'));
      res('T13', 'الرمز الصحيح يُقبل والخاطئ يُرفض', wallet_sec_pkg.pin_ok(u, '2468') AND NOT wallet_sec_pkg.pin_ok(u, '2469'));
      SELECT COUNT(*) INTO n FROM wlt_users WHERE pin_ver <> 2 AND pin_hash IS NOT NULL;
      res('T14', 'كل الرموز مخزّنة بالتشفير القوي', n = 0, n || ' رمز قديم');
      SELECT COUNT(*) INTO n FROM wlt_otp_codes WHERE created_at > SYSTIMESTAMP - INTERVAL '30' DAY AND LENGTH(code_hash) <> 64;
      res('T15', 'رموز التحقق مخزّنة كبصمة لا كنص', n = 0, n);
    EXCEPTION WHEN OTHERS THEN err('T12', 'تشفير الرموز'); END;

    BEGIN
      wallet_care_pkg.stmt_totals(a, CAST(TRUNC(SYSDATE, 'MM') AS TIMESTAMP) - INTERVAL '3' HOUR, SYSTIMESTAMP + INTERVAL '1' DAY, x, y, z, w, n);
      res('T16', 'كشف الحساب: الافتتاحي + الوارد − الصادر = الختامي', x + y - z = w, x || ' + ' || y || ' − ' || z || ' = ' || w);
    EXCEPTION WHEN OTHERS THEN err('T16', 'كشف الحساب'); END;

    BEGIN
      r1 := wallet_core_pkg.transfer(a, b, 0.25, 'TRANSFER', 'TEST-' || l_run || '-17', 'اختبار آلي');
      n := wallet_care_pkg.open_dispute('0770009001', r1, 'WRONG_AMT', 'اختبار آلي', TRUE);
      s := expect_err('DECLARE n NUMBER; BEGIN n := wallet_care_pkg.open_dispute(''0770009001'', ''' || r1 || ''', ''WRONG_AMT'', ''x''); END;');
      res('T17', 'بلاغ مكرر على نفس العملية يُرفض', s = 'OK', s);
      SELECT phone INTO s FROM wlt_users WHERE user_type = 'ADMIN' AND status = 'ACTIVE' ORDER BY user_id FETCH FIRST 1 ROWS ONLY;
      wallet_care_pkg.decide_dispute(s, n, 'REVERSE', 'اختبار آلي');
      SELECT status INTO s FROM wlt_disputes WHERE dispute_id = n;
      SELECT status INTO r2 FROM wlt_transactions WHERE txn_ref = r1;
      res('T18', 'البلاغ يعكس العملية ويغلق نفسه', s = 'REVERSED' AND r2 = 'REVERSED', s || ' / ' || r2);
    EXCEPTION WHEN OTHERS THEN err('T17', 'دورة البلاغ'); END;

    BEGIN
      SELECT MAX(txn_ref) INTO r1 FROM wlt_transactions WHERE txn_type = 'SAVE' AND status = 'COMPLETED';
      IF r1 IS NULL THEN
        res('T19', 'عمليات الحصّالة لا تُعكس من لوحة الإدارة', TRUE, 'لا توجد عملية ادخار للفحص');
      ELSE
        SELECT phone INTO s FROM wlt_users WHERE user_type = 'ADMIN' AND status = 'ACTIVE' ORDER BY user_id FETCH FIRST 1 ROWS ONLY;
        s := expect_err('DECLARE r VARCHAR2(40); BEGIN r := wallet_account_pkg.admin_reverse(''' || s || ''', ''' || r1 || ''', ''x''); END;');
        res('T19', 'عمليات الحصّالة لا تُعكس من لوحة الإدارة', s = 'OK', s);
      END IF;
    EXCEPTION WHEN OTHERS THEN err('T19', 'حماية العكس'); END;

    BEGIN
      res('T20', 'تصنيف أنواع العمليات', wallet_ui8_pkg.cat_of('TRANSFER') = 'P2P' AND wallet_ui8_pkg.cat_of('BILL_PAY') = 'BILL'

CREATE TABLE wlt_notifications (
  notif_id    NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_notif PRIMARY KEY,
  user_id     NUMBER        NOT NULL CONSTRAINT fk_wlt_notif_user REFERENCES wlt_users,
  kind        VARCHAR2(20)  NOT NULL,
  title       VARCHAR2(200) NOT NULL,
  body        VARCHAR2(400),
  link_page   NUMBER,
  is_read     CHAR(1)       DEFAULT 'N' NOT NULL CONSTRAINT ck_wlt_notif_read CHECK (is_read IN ('Y','N')),
  created_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_wlt_notif_user ON wlt_notifications (user_id, is_read, created_at);

CREATE TABLE wlt_splits (
  split_id      NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_splits PRIMARY KEY,
  owner_user_id NUMBER        NOT NULL CONSTRAINT fk_wlt_split_owner REFERENCES wlt_users,
  title         VARCHAR2(100) NOT NULL,
  total_amount  NUMBER(15,3)  NOT NULL CONSTRAINT ck_wlt_split_total CHECK (total_amount > 0),
  owner_share   NUMBER(15,3)  DEFAULT 0 NOT NULL,
  reminders     NUMBER(3)     DEFAULT 0 NOT NULL,
  created_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_wlt_split_owner ON wlt_splits (owner_user_id, created_at);

CREATE TABLE wlt_money_requests (
  req_id             NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_req PRIMARY KEY,
  token              VARCHAR2(32)  NOT NULL CONSTRAINT uq_wlt_req_token UNIQUE,
  requester_user_id  NUMBER        NOT NULL CONSTRAINT fk_wlt_req_from REFERENCES wlt_users,
  payer_user_id      NUMBER        CONSTRAINT fk_wlt_req_payer REFERENCES wlt_users,
  amount             NUMBER(15,3)  NOT NULL CONSTRAINT ck_wlt_req_amount CHECK (amount > 0),
  note               VARCHAR2(100),
  split_id           NUMBER        CONSTRAINT fk_wlt_req_split REFERENCES wlt_splits,
  expires_at         TIMESTAMP     NOT NULL,
  status             VARCHAR2(10)  DEFAULT 'PENDING' NOT NULL
                     CONSTRAINT ck_wlt_req_status CHECK (status IN ('PENDING','PAID','DECLINED','CANCELLED','EXPIRED')),
  paid_txn_id        NUMBER        CONSTRAINT fk_wlt_req_txn REFERENCES wlt_transactions,
  paid_by            NUMBER        CONSTRAINT fk_wlt_req_paidby REFERENCES wlt_users,
  created_at         TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_wlt_req_self CHECK (payer_user_id IS NULL OR payer_user_id <> requester_user_id)
);
CREATE INDEX ix_wlt_req_requester ON wlt_money_requests (requester_user_id, created_at);
CREATE INDEX ix_wlt_req_payer     ON wlt_money_requests (payer_user_id, status);
CREATE INDEX ix_wlt_req_split     ON wlt_money_requests (split_id);
CREATE INDEX ix_wlt_req_txn       ON wlt_money_requests (paid_txn_id);
CREATE INDEX ix_wlt_req_paidby    ON wlt_money_requests (paid_by);

CREATE TABLE wlt_scheduled_transfers (
  sched_id      NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_wlt_sched PRIMARY KEY,
  from_user_id  NUMBER        NOT NULL CONSTRAINT fk_wlt_sched_from REFERENCES wlt_users,
  to_user_id    NUMBER        NOT NULL CONSTRAINT fk_wlt_sched_to REFERENCES wlt_users,
  amount        NUMBER(15,3)  NOT NULL CONSTRAINT ck_wlt_sched_amount CHECK (amount > 0),
  note          VARCHAR2(100),
  frequency     VARCHAR2(10)  NOT NULL CONSTRAINT ck_wlt_sched_freq CHECK (frequency IN ('ONCE','DAILY','WEEKLY','MONTHLY')),
  next_run_at   TIMESTAMP     NOT NULL,
  max_runs      NUMBER(4),
  runs_count    NUMBER(4)     DEFAULT 0 NOT NULL,
  status        VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL
                CONSTRAINT ck_wlt_sched_status CHECK (status IN ('ACTIVE','PAUSED','CANCELLED','DONE')),
  last_txn_id   NUMBER        CONSTRAINT fk_wlt_sched_txn REFERENCES wlt_transactions,
  last_error    VARCHAR2(400),
  created_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_wlt_sched_self CHECK (from_user_id <> to_user_id)
);
CREATE INDEX ix_wlt_sched_due  ON wlt_scheduled_transfers (status, next_run_at);
CREATE INDEX ix_wlt_sched_from ON wlt_scheduled_transfers (from_user_id);
CREATE INDEX ix_wlt_sched_to   ON wlt_scheduled_transfers (to_user_id);
CREATE INDEX ix_wlt_sched_txn  ON wlt_scheduled_transfers (last_txn_id);


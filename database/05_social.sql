CREATE OR REPLACE PACKAGE BODY wallet_social_pkg AS

  PROCEDURE fail (p_code PLS_INTEGER, p_msg VARCHAR2) IS
  BEGIN RAISE_APPLICATION_ERROR(p_code, p_msg); END;

  FUNCTION money (p NUMBER) RETURN VARCHAR2 IS
  BEGIN RETURN TO_CHAR(p, 'FM999G999G990D000', 'NLS_NUMERIC_CHARACTERS=''.,'''); END;

  FUNCTION user_of (p_phone VARCHAR2) RETURN wlt_v_wallets%ROWTYPE IS
    l wlt_v_wallets%ROWTYPE;
  BEGIN
    SELECT * INTO l FROM wlt_v_wallets
     WHERE phone = p_phone AND wallet_type = 'MAIN' AND currency_code = 'JOD' AND user_type <> 'SYSTEM';
    RETURN l;
  EXCEPTION WHEN NO_DATA_FOUND THEN
    fail(wallet_core_pkg.c_err_not_found, 'الرقم ' || p_phone || ' غير مسجّل في المحفظة');
    RETURN l;
  END user_of;

  FUNCTION user_by_id (p_id NUMBER) RETURN wlt_v_wallets%ROWTYPE IS
    l wlt_v_wallets%ROWTYPE;
  BEGIN
    SELECT * INTO l FROM wlt_v_wallets WHERE user_id = p_id AND wallet_type = 'MAIN' AND currency_code = 'JOD';
    RETURN l;
  END user_by_id;

  PROCEDURE notify (p_user_id NUMBER, p_kind VARCHAR2, p_title VARCHAR2, p_body VARCHAR2 DEFAULT NULL, p_page NUMBER DEFAULT NULL) IS
  BEGIN
    INSERT INTO wlt_notifications (user_id, kind, title, body, link_page)
    VALUES (p_user_id, p_kind, SUBSTR(p_title, 1, 200), SUBSTR(p_body, 1, 400), p_page);
  END notify;

  -- -----------------------------------------------------------------
  -- طلب الأموال
  -- -----------------------------------------------------------------
  FUNCTION request_money (p_requester_phone VARCHAR2, p_payer_phone VARCHAR2, p_amount NUMBER,
                          p_note VARCHAR2 DEFAULT NULL, p_split_id NUMBER DEFAULT NULL) RETURN VARCHAR2 IS
    l_req   wlt_v_wallets%ROWTYPE := user_of(p_requester_phone);
    l_payer wlt_v_wallets%ROWTYPE;
    l_token VARCHAR2(32) := LOWER(DBMS_RANDOM.STRING('X', 20));
    l_hours NUMBER;
  BEGIN
    IF p_amount IS NULL OR p_amount <= 0 OR p_amount <> ROUND(p_amount, 3) THEN
      fail(wallet_core_pkg.c_err_bad_amount, 'أدخل مبلغاً صحيحاً');
    END IF;
    IF p_payer_phone IS NOT NULL THEN
      l_payer := user_of(p_payer_phone);
      IF l_payer.user_id = l_req.user_id THEN
        fail(c_err_request, 'لا يمكنك طلب مال من نفسك');
      END IF;
    END IF;
    SELECT TO_NUMBER(setting_value) INTO l_hours FROM wlt_app_settings WHERE setting_key = 'REQUEST_HOURS';

    INSERT INTO wlt_money_requests (token, requester_user_id, payer_user_id, amount, note, split_id, expires_at)
    VALUES (l_token, l_req.user_id, l_payer.user_id, p_amount, SUBSTR(p_note, 1, 100), p_split_id,
            SYSTIMESTAMP + NUMTODSINTERVAL(l_hours, 'HOUR'));

    IF l_payer.user_id IS NOT NULL THEN
      notify(l_payer.user_id, 'REQUEST',
             l_req.shown_name || ' يطلب منك ' || money(p_amount) || ' د.أ',
             NVL(p_note, 'طلب أموال') || ' · صالح ' || l_hours || ' ساعة', 8);
    END IF;
    IF p_split_id IS NULL THEN COMMIT; END IF;
    RETURN l_token;
  END request_money;

  FUNCTION pay_request (p_payer_phone VARCHAR2, p_token VARCHAR2, p_idem VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
    l_r     wlt_money_requests%ROWTYPE;
    l_payer wlt_v_wallets%ROWTYPE := user_of(p_payer_phone);
    l_req   wlt_v_wallets%ROWTYPE;
    l_ref   VARCHAR2(20);
    l_txn   NUMBER;
  BEGIN
    BEGIN
      SELECT * INTO l_r FROM wlt_money_requests WHERE token = LOWER(TRIM(p_token)) FOR UPDATE;
    EXCEPTION WHEN NO_DATA_FOUND THEN
      fail(c_err_request, 'الطلب غير موجود');
    END;
    IF l_r.status = 'PAID' AND l_r.paid_by = l_payer.user_id THEN
      SELECT txn_ref INTO l_ref FROM wlt_transactions WHERE txn_id = l_r.paid_txn_id;
      RETURN l_ref;
    END IF;
    IF l_r.status <> 'PENDING' THEN
      fail(c_err_request, CASE l_r.status WHEN 'PAID' THEN 'هذا الطلب مدفوع مسبقاً'
                                          WHEN 'DECLINED' THEN 'هذا الطلب مرفوض'
                                          ELSE 'هذا الطلب لم يعد متاحاً' END);
    END IF;
    IF l_r.expires_at < SYSTIMESTAMP THEN
      UPDATE wlt_money_requests SET status = 'EXPIRED' WHERE req_id = l_r.req_id;
      COMMIT;
      fail(c_err_request, 'انتهت صلاحية الطلب');
    END IF;
    IF l_r.payer_user_id IS NOT NULL AND l_r.payer_user_id <> l_payer.user_id THEN
      fail(c_err_request, 'هذا الطلب موجّه لشخص آخر');
    END IF;
    IF l_r.requester_user_id = l_payer.user_id THEN
      fail(c_err_request, 'لا يمكنك دفع طلبك بنفسك');
    END IF;
    l_req := user_by_id(l_r.requester_user_id);

    l_ref := wallet_core_pkg.transfer(
               p_from_wallet => l_payer.wallet_id, p_to_wallet => l_req.wallet_id,
               p_amount => l_r.amount, p_idem_key => p_idem,
               p_description => NVL(l_r.note, 'دفع طلب أموال'), p_commit => FALSE);
    SELECT txn_id INTO l_txn FROM wlt_transactions WHERE txn_ref = l_ref;
    UPDATE wlt_money_requests SET status = 'PAID', paid_txn_id = l_txn, paid_by = l_payer.user_id
     WHERE req_id = l_r.req_id;
    notify(l_req.user_id, 'REQUEST_PAID', l_payer.shown_name || ' دفع طلبك ' || money(l_r.amount) || ' د.أ',
           NVL(l_r.note, 'طلب أموال') || ' · ' || l_ref, 8);
    COMMIT;
    RETURN l_ref;
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
  END pay_request;

  PROCEDURE decline_request (p_payer_phone VARCHAR2, p_token VARCHAR2) IS
    l_payer wlt_v_wallets%ROWTYPE := user_of(p_payer_phone);
    l_r     wlt_money_requests%ROWTYPE;
  BEGIN
    SELECT * INTO l_r FROM wlt_money_requests
     WHERE token = p_token AND payer_user_id = l_payer.user_id AND status = 'PENDING' FOR UPDATE;
    UPDATE wlt_money_requests SET status = 'DECLINED' WHERE req_id = l_r.req_id;
    notify(l_r.requester_user_id, 'REQUEST_DECLINED',
           l_payer.shown_name || ' رفض طلبك ' || money(l_r.amount) || ' د.أ', l_r.note, 8);
    COMMIT;
  EXCEPTION WHEN NO_DATA_FOUND THEN
    fail(c_err_request, 'الطلب غير موجود أو لم يعد معلّقاً');
  END decline_request;

  PROCEDURE cancel_request (p_requester_phone VARCHAR2, p_token VARCHAR2) IS
    l_req wlt_v_wallets%ROWTYPE := user_of(p_requester_phone);
  BEGIN
    UPDATE wlt_money_requests SET status = 'CANCELLED'
     WHERE token = p_token AND requester_user_id = l_req.user_id AND status = 'PENDING';
    IF SQL%ROWCOUNT = 0 THEN fail(c_err_request, 'الطلب غير موجود أو لم يعد معلّقاً'); END IF;
    COMMIT;
  END cancel_request;

  -- -----------------------------------------------------------------
  -- تقسيم الفاتورة: حصص متساوية، والفلسات الزائدة على صاحب التقسيم
  -- -----------------------------------------------------------------
  FUNCTION create_split (p_owner_phone VARCHAR2, p_title VARCHAR2, p_total NUMBER,
                         p_phones VARCHAR2, p_include_owner BOOLEAN DEFAULT TRUE) RETURN NUMBER IS
    l_owner  wlt_v_wallets%ROWTYPE := user_of(p_owner_phone);
    l_phones apex_t_varchar2;
    l_n      PLS_INTEGER;
    l_share  NUMBER;
    l_owner_share NUMBER := 0;
    l_id     NUMBER;
    l_tok    VARCHAR2(32);
    l_p      wlt_v_wallets%ROWTYPE;
  BEGIN
    SELECT DISTINCT TRIM(COLUMN_VALUE) BULK COLLECT INTO l_phones
      FROM TABLE(apex_string.split(p_phones, ','))
     WHERE TRIM(COLUMN_VALUE) IS NOT NULL AND TRIM(COLUMN_VALUE) <> p_owner_phone;
    IF l_phones.COUNT = 0 THEN fail(c_err_split, 'أضف شخصاً واحداً على الأقل'); END IF;
    IF l_phones.COUNT > 20 THEN fail(c_err_split, 'الحد الأقصى 20 شخصاً في التقسيم'); END IF;
    IF p_total IS NULL OR p_total <= 0 OR p_total <> ROUND(p_total, 3) THEN
      fail(wallet_core_pkg.c_err_bad_amount, 'أدخل المبلغ الكلي بشكل صحيح');
    END IF;
    IF NOT REGEXP_LIKE(NVL(TRIM(p_title), ' '), '\S') THEN fail(c_err_split, 'اكتب عنواناً للتقسيم'); END IF;

    l_n := l_phones.COUNT + CASE WHEN p_include_owner THEN 1 ELSE 0 END;
    l_share := TRUNC(p_total / l_n, 3);
    IF l_share <= 0 THEN fail(c_err_split, 'المبلغ صغير جداً للتقسيم'); END IF;
    IF p_include_owner THEN l_owner_share := p_total - l_share * l_phones.COUNT; END IF;

    INSERT INTO wlt_splits (owner_user_id, title, total_amount, owner_share)
    VALUES (l_owner.user_id, SUBSTR(TRIM(p_title), 1, 100), p_total, l_owner_share)
    RETURNING split_id INTO l_id;

    FOR i IN 1 .. l_phones.COUNT LOOP
      l_tok := request_money(p_owner_phone, l_phones(i),
                 CASE WHEN NOT p_include_owner AND i = 1 THEN p_total - l_share * (l_phones.COUNT - 1) ELSE l_share END,
                 SUBSTR('تقسيم: ' || TRIM(p_title), 1, 100), l_id);
    END LOOP;
    COMMIT;
    RETURN l_id;
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
  END create_split;

  FUNCTION remind_split (p_owner_phone VARCHAR2, p_split_id NUMBER) RETURN NUMBER IS
    l_owner wlt_v_wallets%ROWTYPE := user_of(p_owner_phone);
    l_s     wlt_splits%ROWTYPE;
    l_n     NUMBER := 0;
  BEGIN
    SELECT * INTO l_s FROM wlt_splits WHERE split_id = p_split_id AND owner_user_id = l_owner.user_id FOR UPDATE;
    FOR r IN (SELECT * FROM wlt_money_requests WHERE split_id = p_split_id AND status = 'PENDING') LOOP
      notify(r.payer_user_id, 'REMINDER', 'تذكير: ' || l_owner.shown_name || ' بانتظار ' || money(r.amount) || ' د.أ',
             l_s.title, 8);
      l_n := l_n + 1;
    END LOOP;
    UPDATE wlt_splits SET reminders = reminders + 1 WHERE split_id = p_split_id;
    COMMIT;
    RETURN l_n;
  EXCEPTION WHEN NO_DATA_FOUND THEN
    fail(c_err_split, 'التقسيم غير موجود');
    RETURN 0;
  END remind_split;

  -- -----------------------------------------------------------------
  -- التحويلات المجدولة
  -- -----------------------------------------------------------------
  FUNCTION schedule (p_from_phone VARCHAR2, p_to_phone VARCHAR2, p_amount NUMBER, p_note VARCHAR2,
                     p_frequency VARCHAR2, p_first_run TIMESTAMP, p_max_runs NUMBER DEFAULT NULL) RETURN NUMBER IS
    l_from wlt_v_wallets%ROWTYPE := user_of(p_from_phone);
    l_to   wlt_v_wallets%ROWTYPE := user_of(p_to_phone);
    l_id   NUMBER;
  BEGIN
    IF l_from.user_id = l_to.user_id THEN fail(c_err_sched, 'لا يمكن جدولة تحويل لنفسك'); END IF;
    IF p_amount IS NULL OR p_amount <= 0 OR p_amount <> ROUND(p_amount, 3) THEN
      fail(wallet_core_pkg.c_err_bad_amount, 'أدخل مبلغاً صحيحاً');
    END IF;
    IF p_frequency NOT IN ('ONCE','DAILY','WEEKLY','MONTHLY') THEN fail(c_err_sched, 'اختر التكرار'); END IF;
    IF p_first_run < SYSTIMESTAMP - INTERVAL '5' MINUTE THEN fail(c_err_sched, 'اختر موعداً في المستقبل'); END IF;
    INSERT INTO wlt_scheduled_transfers (from_user_id, to_user_id, amount, note, frequency, next_run_at, max_runs)
    VALUES (l_from.user_id, l_to.user_id, p_amount, SUBSTR(p_note, 1, 100), p_frequency, p_first_run,
            CASE WHEN p_frequency = 'ONCE' THEN 1 ELSE p_max_runs END)
    RETURNING sched_id INTO l_id;
    COMMIT;
    RETURN l_id;
  END schedule;

  PROCEDURE set_schedule_status (p_owner_phone VARCHAR2, p_sched_id NUMBER, p_status VARCHAR2) IS
    l_from wlt_v_wallets%ROWTYPE := user_of(p_owner_phone);
  BEGIN
    IF p_status NOT IN ('ACTIVE','PAUSED','CANCELLED') THEN fail(c_err_sched, 'حالة غير صالحة'); END IF;
    UPDATE wlt_scheduled_transfers SET status = p_status
     WHERE sched_id = p_sched_id AND from_user_id = l_from.user_id AND status IN ('ACTIVE','PAUSED');
    IF SQL%ROWCOUNT = 0 THEN fail(c_err_sched, 'التحويل المجدول غير موجود'); END IF;
    COMMIT;
  END set_schedule_status;

  -- ينفّذ كل ما حان موعده. مفتاح منع التكرار = رقم الجدولة + رقم الدورة،
  -- فلو اشتغلت المهمة مرتين في نفس اللحظة لن يُخصم المبلغ مرتين
  FUNCTION run_due RETURN NUMBER IS
    l_ref  VARCHAR2(20);
    l_txn  NUMBER;
    l_done NUMBER := 0;
    l_from wlt_v_wallets%ROWTYPE;
    l_to   wlt_v_wallets%ROWTYPE;
    l_next TIMESTAMP;
    l_msg  VARCHAR2(400);
  BEGIN
    FOR s IN (SELECT sched_id FROM wlt_scheduled_transfers
               WHERE status = 'ACTIVE' AND next_run_at <= SYSTIMESTAMP ORDER BY next_run_at) LOOP
      DECLARE
        l_s wlt_scheduled_transfers%ROWTYPE;
      BEGIN
        SELECT * INTO l_s FROM wlt_scheduled_transfers
         WHERE sched_id = s.sched_id AND status = 'ACTIVE' AND next_run_at <= SYSTIMESTAMP
           FOR UPDATE SKIP LOCKED;
        l_from := user_by_id(l_s.from_user_id);
        l_to   := user_by_id(l_s.to_user_id);
        l_next := CASE l_s.frequency
                    WHEN 'DAILY'   THEN l_s.next_run_at + INTERVAL '1' DAY
                    WHEN 'WEEKLY'  THEN l_s.next_run_at + INTERVAL '7' DAY
                    WHEN 'MONTHLY' THEN ADD_MONTHS(l_s.next_run_at, 1)
                    ELSE l_s.next_run_at END;
        BEGIN
          l_ref := wallet_core_pkg.transfer(
                     p_from_wallet => l_from.wallet_id, p_to_wallet => l_to.wallet_id,
                     p_amount => l_s.amount,
                     p_idem_key => 'SCH-' || l_s.sched_id || '-' || (l_s.runs_count + 1),
                     p_description => NVL(l_s.note, 'تحويل مجدول'), p_commit => FALSE);
          SELECT txn_id INTO l_txn FROM wlt_transactions WHERE txn_ref = l_ref;
          UPDATE wlt_scheduled_transfers
             SET runs_count = runs_count + 1, last_txn_id = l_txn, last_error = NULL, next_run_at = l_next,
                 status = CASE WHEN max_runs IS NOT NULL AND runs_count + 1 >= max_runs THEN 'DONE' ELSE status END
           WHERE sched_id = l_s.sched_id;
          notify(l_s.from_user_id, 'SCHEDULED_OK',
                 'نُفّذ تحويل مجدول ' || money(l_s.amount) || ' د.أ',
                 'إلى ' || l_to.shown_name || ' · ' || l_ref, 10);
          l_done := l_done + 1;
        EXCEPTION WHEN OTHERS THEN
          l_msg := REGEXP_REPLACE(REGEXP_SUBSTR(SQLERRM, '^[^' || CHR(10) || ']+'), '^ORA-\d+: ', '');
          UPDATE wlt_scheduled_transfers
             SET last_error = SUBSTR(l_msg, 1, 400),
                 next_run_at = CASE WHEN frequency = 'ONCE' THEN next_run_at ELSE l_next END,
                 status = CASE WHEN frequency = 'ONCE' THEN 'PAUSED' ELSE status END
           WHERE sched_id = l_s.sched_id;
          notify(l_s.from_user_id, 'SCHEDULED_FAIL',
                 'تعذّر تنفيذ تحويل مجدول ' || money(l_s.amount) || ' د.أ', l_msg, 10);
        END;
        COMMIT;
      EXCEPTION WHEN NO_DATA_FOUND THEN NULL;   -- عملية أخرى أخذته، أو تغيّرت حالته
      END;
    END LOOP;

    UPDATE wlt_money_requests SET status = 'EXPIRED'
     WHERE status = 'PENDING' AND expires_at < SYSTIMESTAMP;
    COMMIT;
    RETURN l_done;
  END run_due;

  PROCEDURE run_job IS
    l NUMBER;
  BEGIN
    l := run_due;
  END run_job;

END wallet_social_pkg;

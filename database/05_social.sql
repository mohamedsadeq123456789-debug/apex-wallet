          'استلمت ' || TO_CHAR(:NEW.amount, 'FM999G990D000', 'NLS_NUMERIC_CHARACTERS=''.,''') || ' د.أ',
          CASE WHEN l_from_t = 'SYSTEM' THEN l_type ELSE l_type || ' من ' || l_from_n END
          || NVL2(:NEW.description, ' · ' || :NEW.description, '') || ' · ' || :NEW.txn_ref,
          1);
END;
